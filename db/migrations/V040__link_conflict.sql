-- V040: вид связи «противоречие» (ADR-045, шип 2 ночи 02→03.09).
-- Требование объявляет relations[].kind = conflicts_with с обоснованием;
-- пересчёт связей кладёт его в таблицу links видом conflict, чтобы граф,
-- матрицы и готовность видели противоречие наравне с decompose/trace.
-- Неразрешённое противоречие (без resolution) — разрыв готовности к
-- базированию. Данных миграция не меняет.
ALTER TYPE link_kind ADD VALUE IF NOT EXISTS 'conflict';
