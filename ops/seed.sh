#!/bin/sh
# Заполнение демо-проектом при подъёме стека.
#
# Сам заполнитель (SeedDemoKt) намеренно отказывается работать по непустой
# базе: и когда там чужой проект, и когда демо уже загружено. Для повторного
# `docker compose up` второй случай — норма, а не отказ, поэтому здесь он
# отличается от первого ПО ПРИЧИНЕ, а не по коду возврата.
#
# Отказ из-за чужих объектов остаётся отказом: заполнение демо-данными базы
# рабочего проекта — ровно то, что заполнитель обязан не допустить.
set -eu

out="$(java -jar app.jar 2>&1)" && status=0 || status=$?
printf '%s\n' "$out"

if [ "$status" -eq 0 ]; then
  exit 0
fi

case "$out" in
  *"демо-проект уже загружен"*)
    echo "заполнение пропущено: база уже содержит демо-проект"
    exit 0
    ;;
esac

echo "заполнение не выполнено (код $status)" >&2
exit "$status"
