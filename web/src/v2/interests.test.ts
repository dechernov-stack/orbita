// Интересы стороны — список её слов с цитатой (истина 24.09): экран читает
// любой вид поля — строку прежних записей, перечень эталона, список объектов.
import { describe, expect, it } from 'vitest'
import { интересы } from './interests'

describe('интересы стороны', () => {
  it('строка прежних записей делится по «;» и переводам строк, пустое выпадает', () => {
    expect(интересы('телематика; контроль исполнения\n\n ;')).toEqual([
      { statement: 'телематика' }, { statement: 'контроль исполнения' },
    ])
  })
  it('перечень строк эталона и список объектов читаются одинаково, цитата — при объекте', () => {
    expect(интересы(['а', { statement: 'б', quote: '…б…' }, { statement: '' }, 7])).toEqual([
      { statement: 'а' }, { statement: 'б', quote: '…б…' },
    ])
  })
  it('пустого и чужого вида — нет интересов', () => {
    expect(интересы(undefined)).toEqual([])
    expect(интересы(null)).toEqual([])
    expect(интересы({ text: 'не поле' })).toEqual([])
  })
})
