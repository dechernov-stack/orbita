// Смена сборки под открытой вкладкой замечается, а не висит молча.
//
// Проход владельца 20.09: «завис сервер — не отвечает». Сервер был жив: все
// контейнеры здоровы, ответы за доли секунды, а страница держала старую
// сборку после выката образа web — её чанков на новом контейнере уже нет.
import { describe, expect, it } from 'vitest'
import оболочка from './shell.tsx?raw'

describe('обновление сборки', () => {
  it('сверяется имя главного скрипта, а не время', () => {
    expect(оболочка).toContain('function useОбновление')
    expect(оболочка).toContain("cache: 'no-store'")
    expect(оболочка).toContain('/assets/')
  })

  it('ошибка загрузки чанка — тот же признак', () => {
    expect(оболочка).toContain("window.addEventListener('error', наОшибку, true)")
  })

  it('страница не перезагружается сама — решает человек', () => {
    expect(оболочка).toContain('Вышло обновление интерфейса')
    expect(оболочка).toContain('onClick={() => window.location.reload()}')
    expect(оболочка).toContain('несохранённый ввод в формах пропадёт')
  })
})
