// Экран «Требования» (шип 2, экран 9): четыре вида, чипы отбора, сортируемые
// заголовки, группировка, отметки строк и массовые действия. Реестр
// открывается из задачи уже отфильтрованным — прямой вход без отбора.
import { describe, expect, it } from 'vitest'
import { ТЕКСТ_ТРЕБОВАНИЙ as экран } from './test-support/requirementsSource'

describe('виды реестра', () => {
  it('четыре вида переключаются вкладками (шип 5 §1.1)', () => {
    expect(экран).toContain("['таблица', 'Таблица'], ['иерархия', 'По иерархии'], ['документы', 'По документам'], ['матрица', 'Матрица'],")
    expect(экран).toContain('<Вкладки label="вид реестра требований"')
    expect(экран).toContain("useВкладка<ВидРеестра>('requirements', 'таблица'")
    expect(экран).toContain('function МатрицаНосителей')
    // «Документ» узнаётся по данным проекта, а не по форме кода источника.
    expect(экран).toContain("api.entities(project, 'material')")
    expect(экран).toContain('т.sources.filter((и) => документы.includes(и))')
  })

  it('заголовки колонок сортируют, стрелка стоит на отсортированной', () => {
    expect(экран).toContain('aria-label={`сортировать по «${слово}»`}')
    expect(экран).toContain("сортировка.по === к ? (сортировка.вверх ? ' ↑' : ' ↓') : ''")
    expect(экран).toContain('function упорядочить')
  })

  it('чипы отбора берут значения из данных и говорят словами истины', () => {
    expect(экран).toContain('function ЧипОтбора')
    expect(экран).toContain('function значения')
    expect(экран).toContain('только без носителя')
    expect(экран).toContain('aria-label="поиск по требованиям"')
  })

  it('группировка по носителю и по уровню', () => {
    expect(экран).toContain('aria-label="группировка реестра"')
    expect(экран).toContain('function сгруппировать')
    expect(экран).toContain('<option value="carrier">по носителю</option>')
  })
})

describe('массовые действия', () => {
  it('идут по отмеченным строкам, без отметок кнопка заперта и говорит почему', () => {
    // Шип 5 §4: общий массовый приём (§1.4) — отметка строки, липкая панель
    // «выбрано N»; без отметок действий на панели нет, вместо них — наборы.
    expect(экран).toContain('<Отметка ключ={т.code} выбрана={отмечена} onToggle={onОтметить} />')
    expect(экран).toContain('aria-label="отметить все строки на экране"')
    expect(экран).toContain('<ПанельМассово выбранные={м.выбранные} действия={массово}')
    expect(экран).toContain("слово: 'распределить носитель'")
    expect(экран).toContain("слово: 'базировать выбранные'")
    expect(экран).toContain("слово: 'снять линт-помету с причиной'")
    expect(экран).toContain('{ lint_acknowledged: принятые }')
  })

  it('носитель предлагается по природе уровня отмеченных, а не списком в коде', () => {
    expect(экран).toContain('const виды = [...new Set(уровни.flatMap((у) => НОСИТЕЛЬ[у]?.виды ?? [\'component\']))]')
    expect(экран).toContain("'массовое распределение носителя'")
  })
})

describe('реестр из задачи', () => {
  it('принимает начальный отбор и говорит, что открыт из задачи', () => {
    expect(экран).toContain('export interface ОтборТребований')
    expect(экран).toContain('реестр открыт из задачи: показаны')
    expect(экран).toContain('function отобрать')
  })
})
