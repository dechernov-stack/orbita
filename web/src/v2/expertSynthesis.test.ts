// Старый синтез из СРЕЗА поля — только в эксперт-режиме (ПМИ-7, предусловия).
//
// Владелец 16.09 жал «Сформировать постановку из поля» вместо чтения
// документа и получал 26 предложений из 50 элементов среза. Путь по
// умолчанию — «Прочитать документ»; старая кнопка остаётся эксперту.
import { describe, expect, it } from 'vitest'
import экран from './knowledgefield.tsx?raw'
import оболочка from './shell.tsx?raw'

describe('старый синтез — только эксперт-режим', () => {
  it('кнопка синтеза из среза стоит под флагом expert', () => {
    const кусок = экран.slice(экран.indexOf('function Постановка'), экран.indexOf('Принять все, кроме требующих внимания'))
    const кнопка = кусок.indexOf('Сформировать постановку из среза поля')
    expect(кнопка).toBeGreaterThan(0)
    const флаг = кусок.lastIndexOf('{expert && (', кнопка)
    expect(флаг).toBeGreaterThan(0)
    // Между флагом и кнопкой ветка не закрывается: кнопка внутри условия.
    expect(кусок.slice(флаг, кнопка)).not.toContain(')}')
  })

  it('оболочка передаёт эксперт-режим в поле знаний', () => {
    expect(оболочка).toContain('<KnowledgeField project={project} expert={expert} />')
  })

  it('на экране по умолчанию нет «Сформировать постановку из поля»', () => {
    // Старое имя кнопки не должно жить ни одной разметкой вне комментариев.
    const разметка = экран.split('\n').filter((с) => !с.trim().startsWith('//') && !с.trim().startsWith('*') && !с.includes('{/*'))
    expect(разметка.join('\n')).not.toContain("'Сформировать постановку из поля'")
  })
})

