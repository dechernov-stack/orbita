// Нужда правится ВЕЗДЕ, где показана: и в строке стороны, и в её карточке.
//
// Прогон владельца 16.09: «карандаша нет в нуждах, только текст. Редактируется
// влияние и всё остальное — а нужды нет». Он открывал карточку стороны (▾), а
// карандаш стоял только в свёрнутой строке. Сторож читает сам экран: у каждого
// места, где нужда выводится, обязан быть свой карандаш.
import { describe, expect, it } from 'vitest'
// Текст экрана читается как есть (Vite `?raw`): сторож смотрит на разметку,
// а не поднимает React — ему нужно лишь «карандаш стоит там, где показана нужда».
import экран from './scenes.tsx?raw'

/** Кусок сцены 3 — от заголовка сцены до следующей сцены. */
const сцена3 = экран.slice(
  экран.indexOf('export function SceneStakeholders'),
  экран.indexOf('export function SceneGoals'),
)

describe('сцена 3: нужды правятся там же, где показаны', () => {
  it('в карточке стороны у нужды есть карандаш', () => {
    const карточка = сцена3.slice(сцена3.indexOf('нужды ('), сцена3.indexOf('основания:'))
    expect(карточка).toContain('Карандаш')
    expect(карточка).toContain('setПравка(n.code)')
  })

  it('в свёрнутой строке у нужды тоже есть карандаш', () => {
    const колонка = сцена3.slice(
      сцена3.indexOf('нужд нет — сцена не закроется'),
      сцена3.indexOf('Сторон пока нет'),
    )
    expect(колонка).toContain('Карандаш')
    expect(колонка).toContain('setПравка(n.code)')
  })

  it('форма правки нужды одна на оба места — второй не заводим', () => {
    const правки = сцена3.split('ПравкаСтроки').length - 1
    // Две: одна на сторону, одна на нужду. Третья означала бы копию, которая
    // разойдётся с первой.
    expect(правки).toBeLessThanOrEqual(4)
    expect(сцена3).toContain("{ key: 'statement', label: 'формулировка' }")
  })
})
