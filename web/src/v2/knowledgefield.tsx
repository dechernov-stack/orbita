// Экран «Поле знаний» (ЗАДАНИЕ-ПОЛЕ-ЗНАНИЙ §3; замечания прохода 08.09).
//
// Поле знаний — не список фактов, а рабочая поверхность: ТЕМЫ (о чём
// накопились утверждения), ДИСПОЗИЦИИ (что с ними решено) и ИСТОЧНИКИ
// (откуда). И оно же — дом для ВХОДА: источник загружается здесь, разбор
// кладёт факты и темы на глазах, план действий ложится на акцепт тут же.
//
// Три правила прохода 08.09:
//   1. Обоснование — только там, где оно несёт смысл: отклонение, спор,
//      смена уже принятого. Согласие и «рассмотрен» — одним кликом.
//      Обоснование не должно быть налогом на согласие.
//   2. Загрузка во вкладке: текст, файл или ссылка + задание → разбор.
//   3. Ручные темы и факты — полноправные; ручное видно отдельно.
//
// Поле знаний v2 (ЗНАНИЯ-V2, мера ПМИ-6 пп. 1.2–1.9) живёт ЗДЕСЬ ЖЕ и только
// там, где сервер его признал: вкладка «Постановка из поля», счётчик дрейфа
// «поле изменилось: N», колонка ранга доверия, отбор «из исследований» и
// ранг вместо типа в форме источника показываются, когда адреса синтеза
// отвечают делом; на проекте прохода ПМИ-5 те же адреса отвечают отказом 409,
// и экран остаётся прежним целиком.
//
// Ни одна цифра здесь не считается: счётчики групп дифа, дрейф поля и доля
// знаний приходят с сервера готовыми. Ни одно слияние, принятие и уточнение
// не происходит без нажатия человека — служба только предлагает.
import { useCallback, useEffect, useState } from 'react'
import { ConfirmBox, useConfirm } from '../ui/Confirm'
import { api, type FactRow, type FieldDrift, type FormationOntology, type Gate, type ResearchTask } from './api'
import { отказПодробно, type Покрытие, type Тема } from './knowledge/common'
import { ВкладкаДокументы } from './knowledge/documents'
import { ВерификацияПоля } from './knowledge/verification'
import { ВкладкаФакты } from './knowledge/facts'
import { Manual } from './knowledge/manual'
import { Постановка } from './knowledge/proposals'
import { ВыгрузкаКартины } from './knowledge/source'
import { ПоискПоБазе } from './glossary'
import { ResearchPanel } from './research'
import { Вкладки, useВкладка } from './ui/tabs'

type ВкладкаПоля = 'документы' | 'факты' | 'предложения' | 'исследование' | 'верификация' | 'индекс'
const ВКЛАДКИ_ПОЛЯ: readonly ВкладкаПоля[] = ['документы', 'факты', 'предложения', 'исследование', 'верификация', 'индекс']

export function KnowledgeField({ project, expert = false, ручной = false, onGoGlossary, точки, onGoScene }: {
  /** Переход в словарь: кандидаты из приёма плана принимаются там. */
  onGoGlossary?: () => void
  /** Точки фазы: срок подтверждения допущения в окне приёма. */
  точки?: Gate[]
  /** «К месту» факта — сцена его темы. */
  onGoScene?: (сцена: string, зачем?: string) => void
  project: string | null
  expert?: boolean
  /**
   * Открыть сразу ручной ввод: сюда приходят из §11 отчёта («Темы без
   * разрешения»), и дорога обязана привести К ФОРМЕ, а не к экрану, где
   * форму ещё надо найти (владелец 21.09).
   */
  ручной?: boolean
}) {
  const [факты, setФакты] = useState<FactRow[] | null>(null)
  const [темы, setТемы] = useState<Тема[]>([])
  const [покрытие, setПокрытие] = useState<Покрытие | null>(null)
  const [отказ, setОтказ] = useState<string | null>(null)
  // Хуки — до любых возвратов: порядок хуков стережёт CI.
  const [адресТемы, setАдресТемы] = useState('')
  // Поле знаний v2 — состояния объявлены ДО ранних возвратов (порядок хуков
  // стережёт CI): вкладка, дрейф поля, онтология, задачи исследования и окно
  // подтверждения. Признак самого поля знаний v2 даёт сервер, а не догадка.
  // Шип 5 §3: три вкладки — Документы · Факты · Предложения — и эксперт-вкладки
  // Исследование · Верификация · Индекс; выбор помнится на раздел. Сюда из
  // §11 отчёта («Темы без разрешения») ведут к форме ручного ввода — на «Факты».
  const [вкладка, выбратьВкладку] = useВкладка<ВкладкаПоля>('knowledge', ручной ? 'факты' : 'документы', ВКЛАДКИ_ПОЛЯ)
  /** Итог чтения документа и его прогон: «Предложения» открываются с отбором по нему. */
  const [прочитано, setПрочитано] = useState<{ run: string; note: string } | null>(null)
  const [знанияV2, setЗнанияV2] = useState(false)
  const [дрейф, setДрейф] = useState<FieldDrift | null>(null)
  const [онтология, setОнтология] = useState<FormationOntology | null>(null)
  const [исследования, setИсследования] = useState<ResearchTask[]>([])
  const [слитьВ, setСлитьВ] = useState('')
  /** Имена документов по коду: чип документа и «откуда» факта — словом. */
  const [имяДокумента, setИмяДокумента] = useState<Record<string, string>>({})
  const [ask, спросить, закрытьВопрос] = useConfirm()

  const перечитать = useCallback(() => {
    if (!project) return
    api.facts(project).then((r) => setФакты(r.items)).catch((e) => setОтказ(String(e.message ?? e)))
    api.topics(project).then((r) => setТемы(r.items)).catch(() => setТемы([]))
    api.materials(project)
      .then((r) => setИмяДокумента(Object.fromEntries(r.items.map((м) => [м.code, м.name]))))
      .catch(() => setИмяДокумента({}))
    api.knowledgeCoverage(project).then(setПокрытие).catch(() => setПокрытие(null))
    // «Поле изменилось: N» считает сервер. Он же и отвечает, включено ли
    // поле знаний v2: на проекте прохода тот же адрес даёт отказ 409 — и
    // экран остаётся прежним, без вкладки, ранга и отбора исследований.
    api.synthesisPending(project)
      .then((д) => {
        setДрейф(д)
        setЗнанияV2(true)
        api.research(project).then((r) => setИсследования(r.items)).catch(() => setИсследования([]))
        api.formationOntology(project).then(setОнтология).catch(() => setОнтология(null))
      })
      .catch(() => {
        setДрейф(null)
        setЗнанияV2(false)
        setИсследования([])
      })
  }, [project])

  useEffect(перечитать, [перечитать])

  if (!project) {
    return <div className="v2-panel" data-why="следующий-клик"><div className="v2-empty">Проект не выбран.</div></div>
  }
  if (отказ) {
    return (
      <div className="v2-panel" data-why="почему-нельзя">
        <div className="v2-locked">{отказ}</div>
        <button type="button" className="v2-link" onClick={() => { setОтказ(null); перечитать() }}>ещё раз</button>
      </div>
    )
  }

  const все = факты ?? []
  const ручных = все.filter((ф) => ф.manual).length
  const имяТемы = (код: string) => темы.find((т) => т.id === код)?.label ?? код

  const разрешитьТему = (тема: string) => {
    if (!адресТемы.trim()) return
    api.resolveTopic(project, тема, адресТемы.trim(), 'инженер')
      .then(() => { setАдресТемы(''); перечитать() })
      .catch((e) => setОтказ(String(e.message ?? e)))
  }

  /**
   * Строка темы (разрешить в сущность, слить) — когда отбор фактов сужен до
   * одной темы чипом: к точке принятые факты темы обязаны найти адрес.
   */
  const темаПанель = (тема: string) => {
    const т = темы.find((x) => x.id === тема)
    if (!т) return null
    return (
      <div className="v2-kf__bar" data-why="работа">
        <span className="v2-dim">тема «{т.label}»:</span>
        {т.resolved_to
          ? <span>разрешена в <span className="v2-mono">{т.resolved_to}</span></span>
          : (
            <>
              <input value={адресТемы} placeholder="код сущности проекта (узел, сторона, требование…)"
                aria-label="код сущности, в которую разрешается тема"
                onChange={(e) => setАдресТемы(e.target.value)} />
              <button type="button" className="v2-link" disabled={!адресТемы.trim()}
                title="к точке принятые факты темы обязаны найти адрес — сущность проекта"
                onClick={() => разрешитьТему(т.id)}>разрешить в сущность</button>
            </>
          )}
        {знанияV2 && темы.filter((д) => д.id !== т.id).length > 0 && (
          <>
            <select value={слитьВ} onChange={(e) => setСлитьВ(e.target.value)} aria-label="тема, в которую сливаем"
              title="один предмет — одна тема, как бы его ни звали документы: тождество предлагает разбор, сливает человек">
              <option value="">— слить эту тему в другую —</option>
              {темы.filter((д) => д.id !== т.id).map((д) => (
                <option key={д.id} value={д.id}>{д.label}</option>
              ))}
            </select>
            <button type="button" className="v2-link" disabled={!слитьВ}
              title={слитьВ
                ? 'слить темы: факты обеих читаются по голове цепочки, ни один факт не пропадает'
                : 'выберите тему, в которую сливаем: слияние без цели не бывает'}
              onClick={() => спросить({
                question: `Слить тему «${т.label}» в «${имяТемы(слитьВ)}»? `
                  + 'Факты обеих будут читаться по одной голове; отменить слияние нельзя.',
                ok: 'Слить',
                input: { label: 'почему это одна тема', required: true },
                onOk: (повод) => api.mergeTopic(project, т.id, слитьВ, 'инженер', повод)
                  .then(() => { setСлитьВ(''); перечитать() })
                  .catch((e) => setОтказ(отказПодробно(e))),
              })}>слить темы</button>
          </>
        )}
      </div>
    )
  }

  // Вкладка «Предложения» и исследования живут там, где сервер признал поле
  // знаний v2; на проекте прохода их нет, и экран остаётся Документами и Фактами.
  const доступна = (к: ВкладкаПоля) => знанияV2 || (к !== 'предложения' && к !== 'исследование')
  const текущая: ВкладкаПоля = доступна(вкладка) ? вкладка : 'документы'
  const документов = Object.keys(имяДокумента).length
  const выгрузки = (
    <>
      <a className="v2-link" href={api.knowledgeZipUrl(project)} target="_blank" rel="noreferrer"
        title="пакет знаний внешнему контуру: MD-файлы с отпечатком в шапке — факты принятые · допущенные · замеченные с якорями">
        выгрузка знаний
      </a>
      <ВыгрузкаКартины project={project} />
    </>
  )
  return (
    <div className="v2-panel" data-why="работа">
      <div className="v2-context">
        {project} · поле знаний · {документов} {документов === 1 ? 'документ' : документов < 5 && документов > 1 ? 'документа' : 'документов'}
        {факты !== null && ` · ${все.length} фактов · руками ${ручных}`}
        {покрытие && ` · из источников ${покрытие.share_percent}% сущностей`}
        {знанияV2 && дрейф !== null && дрейф.changed > 0 && (
          <span className="v2-warn" title="столько в поле поменялось после последнего синтеза — число считает сервер">
            {` · поле изменилось: ${дрейф.changed}`}
          </span>
        )}
      </div>
      <Вкладки label="поле знаний" current={текущая} onChange={выбратьВкладку} expert={expert} tail={выгрузки}
        items={[
          { key: 'документы', word: 'Документы', count: документов, hint: 'документы проекта: роль, ранг, фактов, последний прогон, вклад; досье и чтение в постановку' },
          { key: 'факты', word: 'Факты', count: факты === null ? '…' : все.length, hint: 'факты полосами по предмету: решения, противоречия, допущения, ручной ввод' },
          ...(знанияV2 ? [{
            key: 'предложения' as const, word: 'Предложения', count: дрейф !== null && дрейф.changed > 0 ? дрейф.changed : null,
            health: дрейф !== null && дрейф.changed > 0 ? 'debt' as const : null,
            hint: дрейф !== null && дрейф.changed > 0
              ? `поле изменилось с последнего синтеза: ${дрейф.changed} — число сервера`
              : 'что поле предлагает постановке: группы по вердикту, приём массово; заводит только клик человека',
          }] : []),
          ...(знанияV2 ? [{ key: 'исследование' as const, word: 'Исследование', count: исследования.length || null, expert: true, hint: 'исследования полноты внешним контуром: источники подтверждает человек' }] : []),
          { key: 'верификация', word: 'Верификация', expert: true, hint: 'документ против поля: тезисы без оснований, числа против фактов, противоречия' },
          { key: 'индекс', word: 'Индекс', expert: true, hint: 'поиск по базе знаний и перестроение индекса проекта' },
        ]} />

      {текущая === 'документы' && (
        <ВкладкаДокументы project={project} факты={все}
          onRead={(run, note) => { setПрочитано({ run, note }); перечитать(); выбратьВкладку('предложения') }}
          onChanged={перечитать} onError={setОтказ} onGoGlossary={onGoGlossary} />
      )}

      {текущая === 'факты' && факты !== null && (
        <ВкладкаФакты project={project} факты={все} темы={темы} знанияV2={знанияV2}
          документы={имяДокумента} автор="инженер" точки={точки}
          ручнойОткрыт={ручной} onChanged={перечитать} onGoScene={onGoScene} темаПанель={темаПанель}
          ручнойВвод={<Manual project={project} темы={темы} знанияV2={знанияV2} onDone={перечитать} onError={setОтказ} />} />
      )}

      {текущая === 'предложения' && (
        <>
          {прочитано && <div className="v2-note-line" data-why="следующий-клик">документ прочитан: {прочитано.note} · прогон {прочитано.run}</div>}
          <Постановка project={project} онтология={онтология} onChanged={перечитать} expert={expert} прогон={прочитано?.run} />
        </>
      )}

      {текущая === 'исследование' && (
        <div data-why="следующий-клик">
          <div className="v2-empty__why">
            Принесённое внешним контуром живёт материалом сомнительного ранга: его факты не идут в предложения
            сцен, пока человек не подтвердил источники — чип «из исследований» во вкладке «Факты» показывает их все.
          </div>
          {исследования.length === 0 && <div className="v2-empty">Исследований пока не было.</div>}
          {местаИсследований(исследования).map((з) => (
            <ResearchPanel key={з.id} project={project} trigger={з.trigger} onChanged={перечитать} />
          ))}
        </div>
      )}

      {текущая === 'верификация' && <ВерификацияПоля project={project} />}
      {текущая === 'индекс' && <ПоискПоБазе project={project} />}

      <ConfirmBox request={ask} onClose={закрытьВопрос} />
    </div>
  )
}

/**
 * По одной панели на МЕСТО входа: у места бывает несколько циклов, а панель
 * ведёт последний — две панели одного места были бы одной и той же дважды.
 */
function местаИсследований(задачи: ResearchTask[]): ResearchTask[] {
  const место = (з: ResearchTask) => з.trigger.scene ?? з.trigger.gate ?? з.place
  return задачи.filter((з, i) => задачи.findIndex((д) => место(д) === место(з)) === i)
}

