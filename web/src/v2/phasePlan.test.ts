// План работ фазы: точки по порядку, сцены под своей точкой, связи по датам.
//
// Первая версия (20.09) была перечнем из 27 полей подряд — владелец назвал её
// «записками сумасшедшего»: связи между датами нет, окно можно задать задом
// наперёд (так и легло: сцена 2 — начало 10.10, конец 25.09), а после
// заполнения экран продолжал требовать план, потому что подсказка была
// написана навсегда.
import { describe, expect, it } from 'vitest'
import план from './plan.tsx?raw'
import работа from './work.tsx?raw'

describe('план работ фазы', () => {
  it('стоит на карте фазы', () => {
    expect(работа).toContain('<PhasePlan phase={фаза} project={project}')
    expect(работа).toContain("import { PhasePlan } from './plan'")
  })

  it('сцены сгруппированы под точкой, которая их ждёт', () => {
    expect(план).toContain('с.awaited_by.some((имя) => имя.includes(т.title))')
    expect(план).toContain('закрывает сцены')
    expect(план).toContain('вне точек')
  })

  it('связь по датам: окна раскладываются от точки к точке', () => {
    expect(план).toContain('Разложить окна по точкам')
    expect(план).toContain('const шаг = (до - от) / свои.length')
    // Раскладка невозможна, пока у точек нет дат — сказано словами.
    expect(план).toContain('сначала даты точек: от них и раскладываются окна')
  })

  it('несходности названы словами до записи', () => {
    expect(план).toContain('раньше, чем')
    expect(план).toContain('конец ${о.end} раньше начала ${о.start}')
    expect(план).toContain('а её точка')
    expect(план).toContain('План не сходится')
  })

  it('шапка говорит состояние, а не требует уже сделанного', () => {
    expect(план).toContain('даты точек ${точки.length - безДаты.length} из ${точки.length}')
    expect(план).toContain('План задан целиком')
    // Требование показывается ТОЛЬКО пока чего-то нет.
    expect(план).toContain('безДаты.length > 0 || безОкна.length > 0 ? (')
  })

  it('пустая дата не записывается как ноль', () => {
    expect(план).toContain('.filter(([, д]) => д)')
    expect(план).toContain('.filter(([, о]) => о.start && о.end)')
  })
})
