// Состав системы деревом-таблицей (шип 2, экран 8): 135 узлов читаются,
// правка идёт на месте, действия — пиктограммами с подсказкой.
import { describe, expect, it } from 'vitest'
import экран from './composition.tsx?raw'
import данные from './composition.api.ts?raw'

describe('дерево-таблица', () => {
  it('колонки называются истиной и полкой, а не словами экрана', () => {
    expect(экран).toContain("{состав.метки.code ?? 'Код'}")
    expect(экран).toContain("{состав.метки.name ?? 'Наименование'}")
    expect(экран).toContain("{состав.кратностьПоле?.метка ?? '×N'}")
    expect(данные).toContain("api.kind('component')")
    expect(данные).toContain('const ОЖИДАЕМОЕ_ПОЛЕ_КРАТНОСТИ')
  })

  it('раскрытие и «развернуть до уровня» — вместо списка со свёрткой', () => {
    expect(экран).toContain('aria-label="развернуть дерево до уровня"')
    expect(экран).toContain('const раскрыть = (код: string, да: boolean)')
    expect(данные).toContain('export function видимые')
  })

  it('ключевая величина выбирается, а ключи спрашивает полка', () => {
    expect(экран).toContain('aria-label="ключевая величина колонкой"')
    expect(данные).toContain('export function ключиВеличин')
    expect(экран).toContain('величин полка не спрашивает')
  })
})

describe('правка на месте и действия строки', () => {
  it('имя и кратность правятся двойным кликом по ячейке', () => {
    expect(экран).toContain('aria-label={`имя узла ${узел.code}`}')
    expect(экран).toContain('aria-label={`кратность узла ${узел.code}`}')
    expect(экран).toContain("'правка состава на месте'")
  })

  it('кратность без своего вхождения не правится — сказано словами', () => {
    expect(экран).toContain('кратность узла ${узел.code} приходит с полки')
    expect(экран).toContain('истина схем не называет поля кратности у вхождения')
  })

  // Шип 5 §1.5: действие строки — общая кнопка-пиктограмма, у неё title и aria-label — слово.
  it('действия строки — пиктограммы с подсказкой: добавить, снять, карточка', () => {
    expect(экран).toContain('<ИконКнопка икон="добавить" слово={`добавить дочерний узел под ${узел.code}`}')
    expect(экран).toContain('<ИконКнопка икон="снять" disabled={снят}')
    expect(экран).toContain('<ИконКнопка икон="карточка" aria-expanded={откр}')
    expect(экран).not.toContain('<Икон имя=')
  })

  // Шип 5 §7: узел — карточка объекта §1.3 вниз от строки, с гранями анкеты.
  it('карточка узла вниз от строки: грани истины и анкета, правка величины — своей записью или новым значением', () => {
    expect(экран).toContain('<КарточкаУзла project={project} узел={узел} состав={состав}')
    expect(экран).toContain('<Карточка project={project} row={запись} spec={вид}')
    expect(экран).toContain("api.patchEntity(project, было.code, { measure: мера }, кто, 'величина анкеты узла в карточке')")
    expect(экран).toContain("target: узел.code, key: п.key, measure: мера, origin: 'manual',")
    // Колонки «Ступень · смотреть» и панели под деревом нет: ступень — грань карточки.
    expect(экран).not.toContain('<th>Ступень</th>')
    expect(экран).not.toContain('смотреть\n')
  })

  it('снятие узла требует обоснования, ступень и анкету считает сервер', () => {
    expect(экран).toContain('снятие без обоснования не записывается')
    expect(экран).toContain('api.componentCard(project, узел.code, состав.точка.key)')
    expect(экран).toContain('полка не спрашивает')
  })
})
