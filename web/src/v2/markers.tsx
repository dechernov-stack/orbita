// Три фигуры кодируют род объекта везде (ДИЗАЙН-НАПРАВЛЕНИЕ): кружок — сцена,
// ромб — точка, квадрат со скошенным углом — мероприятие. Заливка — состояние:
// пустой · контур кобальтом («здесь и сейчас») · заполнен зелёным (выполнено) ·
// янтарный контур (ждёт) · красная точка сбоку (блокирует). Статус всегда и
// словом: фигура без подписи на экране не стоит — маркер несёт title.
import type { CSSProperties } from 'react'

export type Род = 'сцена' | 'точка' | 'мероприятие'
export type Состояние = 'пусто' | 'текущее' | 'выполнено' | 'ждёт' | 'блок' | 'закрыто'

const СЛОВО: Record<Состояние, string> = {
  пусто: 'не начато', текущее: 'здесь и сейчас', выполнено: 'выполнено', ждёт: 'ждёт', блок: 'блокирует', закрыто: 'закрыто',
}
const ЦВЕТ: Record<Состояние, { stroke: string; fill: string }> = {
  пусто: { stroke: 'var(--ink)', fill: 'var(--surface)' },
  текущее: { stroke: 'var(--cobalt)', fill: 'var(--surface)' },
  выполнено: { stroke: 'var(--green)', fill: 'var(--green)' },
  ждёт: { stroke: 'var(--amber)', fill: 'var(--surface)' },
  блок: { stroke: 'var(--red)', fill: 'var(--surface)' },
  закрыто: { stroke: 'var(--graphite)', fill: 'var(--surface)' },
}

/**
 * Маркер рода объекта с состоянием. `подпись` — что это (имя сцены, точки,
 * мероприятия): она уходит в title вместе со словом состояния, чтобы цвет
 * никогда не был единственным носителем смысла.
 */
export function Маркер({ род, состояние = 'пусто', подпись, size = 12, style }: {
  род: Род
  состояние?: Состояние
  подпись: string
  size?: number
  style?: CSSProperties
}) {
  const { stroke, fill } = ЦВЕТ[состояние]
  const w = состояние === 'текущее' ? 2.4 : 1.6
  const title = `${род}: ${подпись} — ${СЛОВО[состояние]}`
  const общие = { stroke, fill, strokeWidth: w, vectorEffect: 'non-scaling-stroke' as const }
  return (
    <svg className="v2-marker" width={size} height={size} viewBox="0 0 16 16" role="img" aria-label={title} style={style}>
      <title>{title}</title>
      {род === 'сцена' && <circle cx="8" cy="8" r="5.5" {...общие} />}
      {род === 'точка' && <path d="M8 1.8 14.2 8 8 14.2 1.8 8Z" {...общие} />}
      {род === 'мероприятие' && <path d="M2.5 2.5h7.5l3.5 3.5v7.5h-11Z" {...общие} />}
      {состояние === 'блок' && <circle cx="14" cy="3" r="2.2" fill="var(--red)" stroke="none" />}
    </svg>
  )
}

/** Слово состояния — для строки рядом с маркером: «выполнена», «ждёт 3». */
export function словоСостояния(с: Состояние): string {
  return СЛОВО[с]
}
