// Правило противоречий 26.09 на экране фактов (ответ владельца — блокер ПМИ-8).
//
// Противоречие — только у однозначного (это считает сервер); экран отвечает за
// второе правило: противоречие к принятому факту — долг ДРУГОГО факта. У
// принятого спор с непринятым не показывается равноправным — он назван
// «оспаривают», а красным стоит у непринятого. То же значение из другого
// документа — «подтверждено N».
import { describe, expect, it } from 'vitest'
import type { FactRow } from './api'
import { долгСпора, группыФактов, оспаривают, подтверждающие, фактыПоКоду } from './knowledge/facts'

const факт = (code: string, material: string, extra: Partial<FactRow> = {}): FactRow => ({
  id: code, code, subject: 'Минтранс России', predicate: 'роль', value: 'заказчик', material, mark: 'И',
  disposition: 'free', conflicts: [], links: [], ...extra,
} as FactRow)

describe('противоречие к принятому — долг другого факта', () => {
  const принятый = факт('F-1', 'SD-1', { disposition: 'adopted', conflicts: ['F-2'] })
  const спорящий = факт('F-2', 'SD-2', { value: 'регулятор', conflicts: ['F-1'] })
  const поКоду = фактыПоКоду([принятый, спорящий])

  it('у принятого спор с непринятым — не его долг, он назван «оспаривают»', () => {
    expect(долгСпора(принятый, поКоду)).toEqual([])
    expect(оспаривают(принятый, поКоду)).toEqual(['F-2'])
  })

  it('у непринятого — весь спор, это его долг', () => {
    expect(долгСпора(спорящий, поКоду)).toEqual(['F-1'])
    expect(оспаривают(спорящий, поКоду)).toEqual([])
  })

  it('оба приняты — спор у обоих: принятое не согласовано', () => {
    const а = факт('F-3', 'SD-1', { disposition: 'adopted', conflicts: ['F-4'] })
    const б = факт('F-4', 'SD-2', { disposition: 'adopted', value: 'регулятор', conflicts: ['F-3'] })
    const м = фактыПоКоду([а, б])
    expect(долгСпора(а, м)).toEqual(['F-4'])
    expect(долгСпора(б, м)).toEqual(['F-3'])
  })

  it('полоса считает противоречия долгами: принятый с непринятым — одно, не два', () => {
    const [группа] = группыФактов([принятый, спорящий])
    expect(группа.противоречий).toBe(1)
  })
})

describe('подтверждено N документами', () => {
  it('другие документы по связям same_as и supports; свой документ не считается', () => {
    const а = факт('F-1', 'SD-1', { links: [
      { type: 'same_as', from: 'F-1', to: 'F-2', rationale: '' },
      { type: 'supports', from: 'F-3', to: 'F-1', rationale: '' },
      { type: 'same_as', from: 'F-1', to: 'F-4', rationale: '' },
      { type: 'contradicts', from: 'F-1', to: 'F-5', rationale: '' },
    ] })
    const м = фактыПоКоду([а, факт('F-2', 'SD-2'), факт('F-3', 'SD-3'), факт('F-4', 'SD-1'), факт('F-5', 'SD-5')])
    expect(подтверждающие(а, м).sort()).toEqual(['SD-2', 'SD-3'])
  })
})
