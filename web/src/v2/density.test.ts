// Тест действия — проверкой, а не намерением (ДИЗАЙН-ПРИНЦИПЫ-V2 §1).
//
// Приёмка дизайна требует обхода экрана: каждый элемент называется по
// вопросу, на который он отвечает. Обход, который делает человек, здесь
// сведён к утверждению: состав экрана — данные, и каждый элемент состава
// обязан нести один из трёх ответов.
import { describe, expect, it } from 'vitest'
import { ИМЯ_РЕЖИМА, РЕЖИМ_ПО_РОЛИ, пунктыРейки, режимПоРоли, составЭкрана } from './density'
import type { Зачем } from './density'

const ОТВЕТЫ: Зачем[] = ['работа', 'почему-нельзя', 'следующий-клик']

describe('плотность по роли', () => {
  it('инженеру — одно мероприятие, ведущему СИ — сцена, руководителю — фаза', () => {
    expect(режимПоРоли('specialist')).toBe('мероприятие')
    expect(режимПоРоли('lead_se')).toBe('сцена')
    expect(режимПоРоли('lead')).toBe('фаза')
    expect(режимПоРоли('da_review')).toBe('фаза')
  })

  it('роль неизвестна — самая узкая плотность, а не самая широкая', () => {
    expect(режимПоРоли(null)).toBe('мероприятие')
    expect(режимПоРоли('кто-то ещё')).toBe('мероприятие')
  })

  it('у каждой роли реестра есть умолчание и имя режима', () => {
    Object.entries(РЕЖИМ_ПО_РОЛИ).forEach(([роль, режим]) => {
      expect(ИМЯ_РЕЖИМА[режим], `роль ${роль}`).toBeTruthy()
    })
  })
})

describe('тест действия: состав экрана', () => {
  it('каждый элемент отвечает на один из трёх вопросов и объясняет себя', () => {
    ;(['мероприятие', 'сцена', 'фаза'] as const).forEach((режим) => {
      составЭкрана(режим).forEach((блок) => {
        expect(ОТВЕТЫ, `${режим}/${блок.key}`).toContain(блок.зачем)
        expect(блок.почему.length, `${режим}/${блок.key}`).toBeGreaterThan(10)
      })
    })
  })

  it('у инженера на экране ровно четыре блока и ни одной схемы', () => {
    const состав = составЭкрана('мероприятие').map((б) => б.key)
    expect(состав).toEqual(['контекст', 'поверхность', 'выходы', 'рейка'])
    expect(состав.some((к) => к.includes('схема') || к.includes('карта'))).toBe(false)
  })

  it('поверхность — ровно один блок «работа»: две рабочие области не бывают', () => {
    ;(['мероприятие', 'сцена'] as const).forEach((режим) => {
      const работа = составЭкрана(режим).filter((б) => б.зачем === 'работа')
      expect(работа.map((б) => б.key), режим).toEqual(['поверхность'])
    })
  })

  it('у ведущего СИ схема сцены добавляется СВЕРХУ, состав инженера цел', () => {
    const сцена = составЭкрана('сцена').map((б) => б.key)
    expect(сцена[0]).toBe('схема-сцены')
    expect(сцена.slice(1)).toEqual(составЭкрана('мероприятие').map((б) => б.key))
  })

  it('у руководителя стартовый экран — карта фазы, поверхности за кликом', () => {
    expect(составЭкрана('фаза').map((б) => б.key)).toEqual(['карта-фазы'])
  })
})

describe('рейка: счётчики вместо списков', () => {
  it('пункт без данных на рейку не выходит', () => {
    const пункты = пунктыРейки({ условийВсего: 0, условийЗакрыто: 0, входов: 0, откроет: 0 })
    expect(пункты.map((п) => п.key)).toEqual(['схема'])
  })

  it('условия показываются дробью и объясняют, почему нельзя дальше', () => {
    const пункты = пунктыРейки({ условийВсего: 3, условийЗакрыто: 2, входов: 2, откроет: 3 })
    expect(пункты.map((п) => п.key)).toEqual(['условия', 'входы', 'откроет', 'схема'])
    expect(пункты[0].счёт).toBe('2/3')
    expect(пункты[0].зачем).toBe('почему-нельзя')
    пункты.forEach((п) => expect(ОТВЕТЫ).toContain(п.зачем))
  })
})
