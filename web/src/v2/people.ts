// Инициалы человека или организации — для чипа в шапке, на карте и в сетке
// влияния. Полное имя всегда рядом: в подсказке или в строке таблицы, иначе
// чип нечем прочитать.
export function инициалы(имя: string): string {
  const слова = имя.replace(/^tg:/, '').split(/[\s.·«»"'()]+/).filter(Boolean)
  const буквы = слова.slice(0, 2).map((с) => с[0]?.toUpperCase() ?? '').join('')
  return буквы || имя.slice(0, 2).toUpperCase()
}
