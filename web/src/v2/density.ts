// Плотность экрана по роли и ТЕСТ ДЕЙСТВИЯ (ДИЗАЙН-ПРИНЦИПЫ-V2 §1–§3).
//
// Здесь нет разметки — только решение, ЧТО показывается и ЗАЧЕМ. Состав
// экрана вынесен в чистую функцию, потому что главное правило дизайна
// проверяемо: каждый элемент обязан отвечать на один из трёх вопросов —
// с ним работают · он объясняет, почему нельзя дальше · он нужен для
// следующего клика. Элемент без ответа на экран не попадает, и это
// стережёт тест, а не намерение.

/** Роль в проекте — приходит с сервера (`/auth/whoami`), не выбирается. */
export type Роль = 'lead' | 'lead_se' | 'specialist' | 'sma' | 'da_review' | 'reader'

/** Плотность: что видно по умолчанию. Переключается, но умолчание — роль. */
export type Режим = 'мероприятие' | 'сцена' | 'фаза'

/** Тест действия: три допустимых ответа на вопрос «зачем это здесь». */
export type Зачем = 'работа' | 'почему-нельзя' | 'следующий-клик'

export interface Блок {
  key: string
  зачем: Зачем
  /** Чем оправдан — словами; идёт в подсказку и в отчёт обхода. */
  почему: string
}

/**
 * Умолчание плотности (§2). Инженер работает в одном мероприятии; ведущий
 * СИ ведёт сцену целиком; руководитель и DA смотрят фазу.
 */
export const РЕЖИМ_ПО_РОЛИ: Record<Роль, Режим> = {
  specialist: 'мероприятие',
  reader: 'мероприятие',
  lead_se: 'сцена',
  sma: 'сцена',
  lead: 'фаза',
  da_review: 'фаза',
}

export function режимПоРоли(роль: string | null | undefined): Режим {
  const р = (роль ?? '') as Роль
  return РЕЖИМ_ПО_РОЛИ[р] ?? 'мероприятие'
}

/** Подпись режима для переключателя: плотность видна и меняется руками. */
export const ИМЯ_РЕЖИМА: Record<Режим, string> = {
  мероприятие: 'мероприятие',
  сцена: 'сцена',
  фаза: 'фаза',
}

/**
 * Состав экрана по режиму. Порядок = порядок сверху вниз.
 *
 * Три яруса (§3): первичное — поверхность; вторичное — строка выходов и
 * рейка со счётчиками; третичное (история, схема, точки) живёт за кликом
 * рейки и в состав по умолчанию не входит.
 */
export function составЭкрана(режим: Режим): Блок[] {
  const мероприятие: Блок[] = [
    {
      key: 'контекст',
      зачем: 'следующий-клик',
      почему: 'одна строка: где я в сцене и куда шаг вперёд-назад',
    },
    {
      key: 'поверхность',
      зачем: 'работа',
      почему: 'то, с чем работают: ввод, выбор, принятие',
    },
    {
      key: 'выходы',
      зачем: 'почему-нельзя',
      почему: 'счётчики выходов и то, что не даёт завершить мероприятие',
    },
    {
      key: 'документ',
      зачем: 'следующий-клик',
      почему: 'куда попадает работа: раздел документа, и его можно открыть',
    },
    {
      key: 'рейка',
      зачем: 'следующий-клик',
      почему: 'условия, входы, что откроет и схема — счётчиками, за кликом',
    },
  ]
  if (режим === 'сцена') {
    return [
      {
        key: 'схема-сцены',
        зачем: 'следующий-клик',
        почему: 'мероприятия сцены и переход между ними — работа ведущего СИ',
      },
      ...мероприятие,
    ]
  }
  if (режим === 'фаза') {
    return [
      {
        key: 'карта-фазы',
        зачем: 'следующий-клик',
        почему: 'дорожки, сцены и точки: вход руководителя в любую работу',
      },
    ]
  }
  return мероприятие
}

/** Пункт рейки: знак, счётчик и зачем он на экране. */
export interface ПунктРейки {
  key: 'условия' | 'входы' | 'откроет' | 'схема'
  знак: string
  счёт: string
  подсказка: string
  зачем: Зачем
}

/**
 * Рейка (§3, ярус 2): счётчики вместо списков. Пункт без данных на рейку
 * не выходит — счётчик «0» не отвечает ни на один из трёх вопросов.
 */
export function пунктыРейки(вход: {
  условийВсего: number
  условийЗакрыто: number
  входов: number
  откроет: number
}): ПунктРейки[] {
  const пункты: ПунктРейки[] = []
  if (вход.условийВсего > 0) {
    пункты.push({
      key: 'условия',
      знак: '☐',
      счёт: `${вход.условийЗакрыто}/${вход.условийВсего}`,
      подсказка: `условия завершения: ${вход.условийЗакрыто} из ${вход.условийВсего}`,
      зачем: 'почему-нельзя',
    })
  }
  if (вход.входов > 0) {
    пункты.push({
      key: 'входы', знак: '⇣', счёт: String(вход.входов),
      подсказка: `входы: ${вход.входов}`, зачем: 'следующий-клик',
    })
  }
  if (вход.откроет > 0) {
    пункты.push({
      key: 'откроет', знак: '⇢', счёт: String(вход.откроет),
      подсказка: `откроет: ${вход.откроет}`, зачем: 'следующий-клик',
    })
  }
  пункты.push({
    key: 'схема', знак: '▦', счёт: '',
    подсказка: 'схема фазы: где эта работа в фазе', зачем: 'следующий-клик',
  })
  return пункты
}
