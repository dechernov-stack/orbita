// «Один label — один контрол» (шип 5 §1.3, §9) — на разметку поверхности.
//
// У подписи ровно один контрол: поле, селект, текст или кнопка. Подпись над
// группой кнопок (шкала 1–5, три строки одной грани) — не <label>, а подпись
// грани; тогда чтение экрана не склеит два контрола в одно имя. Подпись с
// `for` указывает на контрол по id и сама контролов не содержит.
const КОНТРОЛ = /<(input|select|textarea|button)\b(?![^>]*type="hidden")/g

/** Подписи, нарушающие правило: начало каждой — чтобы в отказе было видно, какая. */
export function нарушенияПодписей(html: string): string[] {
  const нарушения: string[] = []
  for (const м of html.matchAll(/<label\b([^>]*)>([\s\S]*?)<\/label>/g)) {
    const внутри = м[2].match(КОНТРОЛ) ?? []
    const поСсылке = /\bfor="/.test(м[1])
    if (внутри.length > 1 || (поСсылке && внутри.length > 0)) нарушения.push(м[0].slice(0, 160))
  }
  return нарушения
}
