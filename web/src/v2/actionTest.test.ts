// Шип 5 §9 — тест действия: от входа (Мостик у ведущих, Моя работа у
// инженера) до главного действия экрана — не больше двух кликов; больше —
// объяснено в отчёте шипа или убрано.
//
// Точки: «Зафиксировать» стояло за третьим кликом — рейка, строка точки,
// кнопка. Карточка ближайшей непройденной точки (той, что в шапке) теперь
// открыта сразу, один раз на вход: решение — вторым кликом.
import { describe, expect, it } from 'vitest'
import точки from './points.tsx?raw'

describe('тест действия: точка решается вторым кликом от входа', () => {
  it('карточка ближайшей непройденной точки открыта сразу, один раз на вход', () => {
    expect(точки).toContain('setОткрыта((вид.items.find((т) => !т.passed) ?? null)?.key ?? null)')
    expect(точки).toContain('if (!вид || раскрытаСама) return')
    // Дальше открывает и сворачивает человек: строка точки по-прежнему переключает карточку.
    expect(точки).toContain('onClick={() => setОткрыта(т.key === открыта ? null : т.key)}')
  })
})
