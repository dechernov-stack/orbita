// Экран «Постановка» (шип 5 §2) — вкладки по понятиям постановки в порядке
// онтологии: Стороны · Нужды · Цели · Сервисы · Ограничения · Допущения ·
// Применимость. Каждая вкладка — реестр одного вида: таблица, карточка
// объекта вниз от строки, массовые действия и чипы отбора значениями из
// данных. «Без нужд» — чип «Сторон» и маркер её вкладки, «Покрытие k из n» —
// число вкладки «Нужды» и колонка «состояние»: не разделы (владелец, КТ2).
//
// Реестры — общие с сценами 3–6 (registry/*.tsx): одна поверхность — один
// компонент, второй копии таблицы нет. Одна строка контекста, одна строка
// вкладок; больше на экране ничего нет.
import type { Phase } from './api'
import { Применимость } from './applicability'
import './formulation.css'
import { РеестрДопущений } from './registry/assumptions'
import { РеестрОграничений } from './registry/constraints'
import { сводкаВкладок, сцена4Держит, useПостановка, type КлючВкладки } from './registry/data'
import { РеестрЦелей } from './registry/goals'
import { РеестрНужд } from './registry/needs'
import { РеестрСервисов } from './registry/services'
import { РеестрСторон } from './registry/stakeholders'
import { Вкладки, useВкладка } from './ui/tabs'

export const ВКЛАДКИ_ПОСТАНОВКИ: readonly КлючВкладки[] = ['стороны', 'нужды', 'цели', 'сервисы', 'ограничения', 'допущения', 'применимость']

const СЛОВО_ВКЛАДКИ: Record<КлючВкладки, string> = {
  стороны: 'Стороны',
  нужды: 'Нужды',
  цели: 'Цели',
  сервисы: 'Сервисы',
  ограничения: 'Ограничения',
  допущения: 'Допущения',
  применимость: 'Применимость',
}

const СОСТОЯНИЕ_СЦЕНЫ: Record<string, string> = { locked: 'закрыта', open: 'идёт', done: 'прожита' }

/** Строка контекста: проект · фаза · текущая сцена и её состояние. */
export function строкаКонтекста(фаза: Phase | null | undefined): string {
  if (!фаза) return ''
  const сцена = фаза.scenes.find((с) => с.key === фаза.current_scene)
  return [фаза.project, фаза.phase, сцена ? `сцена ${сцена.key} «${сцена.title}» ${СОСТОЯНИЕ_СЦЕНЫ[сцена.state] ?? ''}`.trim() : null]
    .filter(Boolean).join(' · ')
}

export function Formulation({ project, фаза, onGoScene }: {
  project: string | null
  фаза?: Phase | null
  onGoScene?: (сцена: string, зачем?: string) => void
}) {
  const { данные, отказ, перечитать } = useПостановка(project, { факты: true, применимость: true })
  const [вкладка, выбрать] = useВкладка<КлючВкладки>('formulation', 'стороны', ВКЛАДКИ_ПОСТАНОВКИ)

  if (!project) {
    return (
      <div className="v2-panel" data-why="почему-нельзя">
        <div className="v2-empty">
          Проект не выбран.
          <span className="v2-empty__why">Постановка — стороны, нужды, цели, сервисы и рамки одного проекта.</span>
        </div>
      </div>
    )
  }
  if (отказ) return <div className="v2-panel" data-why="почему-нельзя"><div className="v2-locked">{отказ}</div></div>

  const сводка = сводкаВкладок(данные, сцена4Держит(фаза))
  const реестр = { project, данные, onChanged: перечитать, onGoScene }
  return (
    <div className="v2-panel v2-formulation" data-why="работа">
      {фаза && <div className="v2-context">{строкаКонтекста(фаза)}</div>}
      <Вкладки label="постановка" current={вкладка} onChange={выбрать}
        items={ВКЛАДКИ_ПОСТАНОВКИ.map((к) => ({ key: к, word: СЛОВО_ВКЛАДКИ[к], ...сводка[к] }))} />
      {данные.читаю && <div className="v2-empty">Читаю постановку…</div>}
      {!данные.читаю && вкладка === 'стороны' && <РеестрСторон {...реестр} />}
      {!данные.читаю && вкладка === 'нужды' && <РеестрНужд {...реестр} />}
      {!данные.читаю && вкладка === 'цели' && <РеестрЦелей {...реестр} />}
      {!данные.читаю && вкладка === 'сервисы' && <РеестрСервисов {...реестр} />}
      {!данные.читаю && вкладка === 'ограничения' && <РеестрОграничений {...реестр} />}
      {!данные.читаю && вкладка === 'допущения' && <РеестрДопущений project={project} данные={данные} onChanged={перечитать} точки={фаза?.gates} />}
      {вкладка === 'применимость' && <Применимость project={project} onChanged={перечитать} />}
    </div>
  )
}
