// Схема процесса (РЕШЕНИЕ-ПРОЦЕСС-НА-ЭКРАНЕ): поверхность работы — та же
// схема, которую исполняет движок. Два её уровня отвечают на разные вопросы и
// потому рисуются по-разному:
//
// • ФАЗА (PhaseMap, экран 5 шипа 2) — «когда»: карта на ОСИ ВРЕМЕНИ.
//   Календарные недели слева направо, линия «сегодня», дорожки метода,
//   станции-сцены на датах своих окон, ромбы точек на своих датах. Позиция
//   считается из ДАТ: у раскладки графа календаря нет, и сроки в ней не
//   читаются — а руководителю нужны именно сроки (ДИЗАЙН-НАПРАВЛЕНИЕ: карта
//   фазы — герой продукта). Координат мы не храним и с сервера не получаем:
//   карта есть проекция плана и состояния движка, а не картинка.
// • СЦЕНА (SceneMap) — «что за чем»: поток мероприятий без календаря. Его
//   раскладку считает БИБЛИОТЕКА (@xyflow/react + @dagrejs/dagre) при каждом
//   показе, как и граф трассировки (ADR-046).
//
// Сторож tools/validate_graph_library.py правилом 5 запрещает в экранах v2
// ручные <line|path|polyline|marker>: «рёбра рисует библиотека». Ветвь
// артефакта между дорожками — единственное место карты, где нужна линия, и
// она идёт <path> с пунктиром; всё остальное — кружки, ромбы, скошенные
// квадраты и полоски, то есть <circle|polygon|rect>. Правило уже нарушают
// маркеры и пиктограммы основы шипа 2 (markers.tsx, icons.tsx): фигуры v2
// рисуются руками по дизайн-направлению. Обходить сторож нельзя — вопрос
// вынесен в отчёт шипа: сузить правило 5 до экранов графа или дать карте
// фазы библиотеку, которая умеет календарь.
