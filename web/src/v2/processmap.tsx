/** День от эпохи: целое, потому что дата берётся UTC-полночью. */
export function деньОт(дата: string): number {
  return Date.parse(`${дата}T00:00:00Z`) / СУТКИ
}

function датаДня(день: number): string {
  return new Date(день * СУТКИ).toISOString().slice(0, 10)
}

/** Понедельник недели даты: ось идёт календарными неделями, а не «с первой сцены». */
export function понедельник(дата: string): string {
  const день = деньОт(дата)
  const деньНедели = new Date(день * СУТКИ).getUTCDay()
  return датаДня(день - (деньНедели === 0 ? 6 : деньНедели - 1))
}

/** Недели оси: понедельники от самой ранней даты до самой поздней. */
export function неделиОси(даты: string[]): string[] {
  const свои = даты.filter((д) => д && д.length >= 10).slice().sort()
  if (свои.length === 0) return []
  const конец = деньОт(свои[свои.length - 1])
  const недели: string[] = []
  for (let день = деньОт(понедельник(свои[0])); день <= конец; день += 7) недели.push(датаДня(день))
  return недели
}

/** Дата коротко — «06.10»: год на оси недель и без того виден. */
export function датаКратко(дата: string): string {
  const [, месяц, день] = дата.split('-')
  return день && месяц ? `${день}.${месяц}` : дата
}

/** Сегодня по МЕСТНОМУ календарю: карта говорит про день человека, не про UTC. */
export function сегодняДата(когда = new Date()): string {
  const месяц = `${когда.getMonth() + 1}`.padStart(2, '0')
  const день = `${когда.getDate()}`.padStart(2, '0')
  return `${когда.getFullYear()}-${месяц}-${день}`
}

/**
 * Разложить подписи по рядам: подпись встаёт в первый ряд, где не задевает
 * уже стоящие, а не нашлось такого — заводится новый ряд. Так «ничего не
 * налезает» без ручной правки координат и одинаково при каждом показе:
 * подписи разбираются слева направо. У края карты подпись не центрируется, а
 * прижимается — иначе её обрезал бы viewBox.
 */
export function поРядам(
  метки: { x: number; текст: string }[],
  левыйКрай: number,
  правыйКрай: number,
): ПодписьКарты[] {
  const занято: number[] = []
  return метки.map(({ x, текст }) => {
    const ширина = текст.length * ЗНАК
    let привязка: ПривязкаПодписи = 'middle'
    let лево = x - ширина / 2
    if (лево < левыйКрай) {
      привязка = 'start'
      лево = левыйКрай
    } else if (лево + ширина > правыйКрай) {
      привязка = 'end'
      лево = правыйКрай - ширина
    }
    let ряд = занято.findIndex((край) => край <= лево)
    if (ряд < 0) ряд = занято.length
    занято[ряд] = лево + ширина + ПРОСВЕТ
    const точка = привязка === 'start' ? левыйКрай : привязка === 'end' ? правыйКрай : x
    return { x: точка, текст, ряд, привязка }
  })
}

/** Сколько рядов заняли подписи. */
function рядов(подписи: ПодписьКарты[]): number {
  return подписи.reduce((всего, п) => (п.ряд + 1 > всего ? п.ряд + 1 : всего), 0)
}

/** Заголовок дорожки в одну-две строки: полные подписи, без усечения. */
export function вСтроки(заголовок: string, предел = 18): string[] {
  const слова = заголовок.split(' ')
  const первая: string[] = []
  while (слова.length > 0 && (первая.length === 0 || `${первая.join(' ')} ${слова[0]}`.length <= предел)) {
    первая.push(слова.shift()!)
  }
  return слова.length > 0 ? [первая.join(' '), слова.join(' ')] : [первая.join(' ')]
}

/** Заливка кружка — состояние сцены: выполнена · в работе (кобальт) · закрыта (графит). */
function состояниеСцены(с: Scene): Состояние {
  if (с.state === 'done') return 'выполнено'
  if (с.state === 'locked') return 'закрыто'
  return 'текущее'
}

function состояниеДела(дело: Activity): Состояние {
  if (дело.state === 'done') return 'выполнено'
  if (дело.state === 'blocked') return 'закрыто'
  if (дело.state === 'in_progress') return 'текущее'
  return 'пусто'
}

/**
 * Сцена-источник входов мероприятия дорожки: вход назван ИМЕНЕМ мероприятия
 * сцены или её выходом — так поток задан в шаблоне (сервер: «вход одного
 * назван выходом (именем) другого»). Берётся первая по порядку сцена: ветвь
 * ведёт оттуда, где артефакт рождается раньше.
 */
export function источникВходов(дело: Activity, сцены: Scene[]): { сцена: Scene; артефакт: string } | null {
  for (const вход of дело.inputs) {
    const сцена = сцены.find((с) => с.output === вход
      || с.activities.some((д) => д.name === вход || д.outputs.some((в) => в.what === вход)))
    if (сцена) return { сцена, артефакт: вход }
  }
  return null
}

/**
 * Раскладка карты фазы: всё, что рисует SVG, считается здесь одной чистой
 * функцией — её проверяет vitest датами, а не глазами по картинке.
 * `null` — плана нет вовсе (ни окна, ни даты точки): календарной карте не на
 * чем стоять, экран говорит об этом словами.
 */
export function раскладкаКарты(phase: Phase, сегодня: string): РаскладкаКарты | null {
  const сОкном = phase.scenes.filter((с) => с.window)
  const датыТочек = phase.gates.map((т) => т.planned_date).filter((д): д is string => !!д)
  if (сОкном.length === 0 && датыТочек.length === 0) return null

  // «Сегодня» входит в размах всегда: линия текущего дня обязана быть на карте,
  // даже если весь план уже в прошлом.
  const недели = неделиОси([
    ...сОкном.flatMap((с) => [с.window!.start, с.window!.end]),
    ...датыТочек,
    сегодня,
  ])
  const отДня = деньОт(недели[0])
  const доДня = деньОт(недели[недели.length - 1]) + 7
  const левое = ЛЕВОЕ
  const правое = ШИРИНА - ПОЛКА - 12
  const ширинаДня = (правое - левое) / (доДня - отДня)
  const поДате = (дата: string) => левое + (деньОт(дата) - отДня) * ширинаДня
  const осьY = 30

  const дневныеНедели = недели.map((дата) => ({ дата, x: поДате(дата), подпись: датаКратко(дата) }))
  const сегодняX = поДате(сегодня)

  // ── Дорожки. Сцены живут на дорожке «of: scenes», мероприятия метода — на
  // своих. Дорожка сцен идёт ВЕРХНЕЙ: на ней стоят ромбы точек и от неё
  // расходятся ветви артефактов (порядок остальных — как у сервера).
  const списокДорожек: Lane[] = (phase.lanes.length > 0
    ? phase.lanes
    : [{ key: 'design', title: 'Проектирование', of: 'scenes', activities: [] }])
    .slice()
    .sort((а, б) => (а.of === 'scenes' ? 0 : 1) - (б.of === 'scenes' ? 0 : 1))

  /** Станции сцен: кружок на дате НАЧАЛА окна, полоска — само окно. */
  const станцииСцен = (): СтанцияКарты[] => сОкном.map((с) => {
    const окно = с.window!
    const левыйКрай = поДате(окно.start)
    const ширинаОкна = поДате(окно.end) - левыйКрай
    // Просрочка — сравнение с КАЛЕНДАРЁМ, не вердикт из величин модели:
    // окно кончилось, а сцена не выполнена, значит полоска янтарная.
    const просрочено = окно.end < сегодня && с.state !== 'done'
    const роль = РОЛЬ_ЧИПОМ[с.role] ?? null
    const состояние = состояниеСцены(с)
    return {
      ключ: с.key,
      имя: `${с.key} · ${с.title}`,
      x: левыйКрай,
      состояние,
      окно: { x: левыйКрай, ширина: ширинаОкна < 8 ? 8 : ширинаОкна, просрочено },
      роль,
      подсказка: `сцена ${с.key} «${с.title}» — ${словоСостояния(состояние)}`
        + `; окно ${датаКратко(окно.start)} — ${датаКратко(окно.end)}`
        + (просрочено ? '; окно просрочено' : '')
        + (роль ? `; ведёт ${роль.слово}` : '')
        + (с.state === 'locked' && с.blockers[0] ? `; закрыта: ${с.blockers[0]}` : '')
        + ' — открыть сцену',
      подпись: { x: левыйКрай, текст: `${с.key} · ${с.title}`, ряд: 0, привязка: 'middle' },
    }
  })

  /**
   * Станции дорожки мероприятий: скошенный квадрат на позиции сцены-источника
   * входов. Пачка мероприятий одной сцены расходится вправо шагом, который
   * укладывается в просвет до следующей пачки: так дата видна, а квадраты не
   * садятся друг на друга. Мероприятие без источника идёт за предыдущим —
   * цепочкой метода.
   */
  const станцииДел = (дорожка: Lane): СтанцияКарты[] => {
    let последняя = левое
    const базы = дорожка.activities.map((дело) => {
      const найдено = источникВходов(дело, phase.scenes)
      if (найдено?.сцена.window) последняя = поДате(найдено.сцена.window.start)
      return последняя
    })
    const пачки = new Map<number, number>()
    return дорожка.activities.map((дело, i) => {
      const база = базы[i]
      const номерВПачке = пачки.get(база) ?? 0
      пачки.set(база, номерВПачке + 1)
      const своих = базы.filter((б) => б === база).length
      const дальше = базы.filter((б) => б > база).sort((а, б) => а - б)[0]
      const просвет = (дальше ?? правое) - база
      const полный = 2 * R_ДЕЛА + 8
      const шаг = своих > 1 && просвет / своих < полный ? просвет / своих : полный
      const x = база + номерВПачке * шаг
      const состояние = состояниеДела(дело)
      return {
        ключ: null,
        имя: `${дело.code} · ${дело.name}`,
        x: x > правое ? правое : x,
        состояние,
        окно: null,
        роль: null,
        подсказка: `мероприятие ${дело.code} «${дело.name}» — ${словоСостояния(состояние)}`
          + (дело.goal ? `; цель: ${дело.goal}` : '')
          + (дело.inputs.length > 0 ? `; ждёт: ${дело.inputs.join('; ')}` : ''),
        подпись: { x: x > правое ? правое : x, текст: `${дело.code} · ${дело.name}`, ряд: 0, привязка: 'middle' as ПривязкаПодписи },
      }
    })
  }

  const заготовки = списокДорожек.map((дорожка) => {
    const станции = дорожка.of === 'scenes' ? станцииСцен() : станцииДел(дорожка)
    const подписи = поРядам(станции.map((ст) => ({ x: ст.x, текст: ст.подпись.текст })), 4, ШИРИНА - 4)
    return {
      ключ: дорожка.key,
      заголовок: дорожка.title,
      строки: вСтроки(дорожка.title),
      рядВысота: дорожка.of === 'scenes' ? РЯД_СЦЕН : РЯД_ДЕЛ,
      станции: станции.map((ст, i) => ({ ...ст, подпись: подписи[i] })),
      рядов: рядов(подписи) || 1,
    }
  })

  // ── Точки: ромбы на своих датах на ВЕРХНЕЙ дорожке, подписи над ней.
  const ближайшая = phase.gates.find((т) => !т.passed) ?? null
  const точкиСДатой = phase.gates.filter((т) => т.planned_date)
  const подписиТочек = поРядам(
    точкиСДатой.map((т) => ({
      x: поДате(т.planned_date!),
      текст: `${т.title} · ${датаКратко(т.planned_date!)}`
        + (т.blocking.length > 0 ? ` · блокирует ${т.blocking.length}` : ''),
    })),
    4,
    ШИРИНА - 4,
  )
  const рядовТочек = рядов(подписиТочек) || 1

  // Верхняя дорожка стоит ниже подписей точек; каждая следующая — ниже подписей
  // предыдущей и поперечин ветвей, которые в неё приходят.
  const верхняя = осьY + 22 + рядовТочек * РЯД_ТОЧЕК
  const ветвейВ = (ключ: string) => {
    const дорожка = списокДорожек.find((д) => д.key === ключ)
    if (!дорожка || дорожка.of === 'scenes') return 0
    return новыеВетви(дорожка, phase.scenes).length
  }
  let y = верхняя
  const дорожки: ДорожкаКарты[] = заготовки.map((з, i) => {
    if (i > 0) {
      const прошлая = заготовки[i - 1]
      y = y + 22 + прошлая.рядов * прошлая.рядВысота + 18 + ветвейВ(з.ключ) * РЯД_ТОЧЕК
    }
    return { ...з, y }
  })

  const точки: ТочкаКарты[] = точкиСДатой.map((т, i) => {
    const x = поДате(т.planned_date!)
    // Ромб, попавший на дату станции, поднимается на полшага: дата от этого не
    // меняется, а кружок и ромб перестают лежать друг на друге.
    const занято = дорожки[0].станции.some((ст) => (ст.x > x ? ст.x - x : x - ст.x) < R_СТАНЦИИ + R_ТОЧКИ)
    const состояние: Состояние = т.passed ? 'выполнено'
      : т.blocking.length > 0 ? 'блок'
        : т.key === ближайшая?.key ? 'текущее' : 'пусто'
    return {
      ключ: т.key,
      x,
      y: занято ? дорожки[0].y - (R_СТАНЦИИ + R_ТОЧКИ) : дорожки[0].y,
      состояние,
      блокирует: т.blocking.length,
      подсказка: `точка «${т.title}» на ${датаКратко(т.planned_date!)} — `
        + (т.passed
          ? 'пройдена'
          : т.blocking.length > 0 ? `держат: ${т.blocking.join('; ')}` : 'условия точки выполнены'),
      подпись: подписиТочек[i],
    }
  })

  // ── Ветви артефактов: из станции сцены в дорожку мероприятий, пунктиром.
  const ветви: ВетвьКарты[] = []
  дорожки.forEach((дорожка, i) => {
    const описание = списокДорожек.find((д) => д.key === дорожка.ключ)
    if (!описание || описание.of === 'scenes' || i === 0) return
    const низПодписей = дорожки[0].y + 22 + дорожки[0].рядов * дорожки[0].рядВысота
    новыеВетви(описание, phase.scenes).forEach((ветвь, номер) => {
      const откуда = дорожки[0].станции.find((ст) => ст.ключ === ветвь.сцена.key)
      const куда = дорожка.станции.find((ст) => ст.имя.startsWith(`${ветвь.дело.code} `))
      if (!откуда || !куда) return
      ветви.push({
        ключ: `${дорожка.ключ}-${ветвь.дело.code}`,
        откуда: { x: откуда.x, y: дорожки[0].y + R_СТАНЦИИ },
        куда: { x: куда.x, y: дорожка.y - R_ДЕЛА },
        уровень: низПодписей + 14 + номер * РЯД_ТОЧЕК,
        подписьX: (откуда.x + куда.x) / 2,
        подпись: ветвь.артефакт,
      })
    })
  })

  // ── Правая полка: сцены без окна. На оси им места нет — даты нет.
  const полка: ПолкаКарты = {
    x: ШИРИНА - ПОЛКА,
    заголовок: 'план не задан',
    станции: phase.scenes.filter((с) => !с.window).map((с, i) => {
      const состояние = состояниеСцены(с)
      return {
        ключ: с.key,
        имя: `${с.key} · ${с.title}`,
        y: осьY + 26 + i * 20,
        состояние,
        подсказка: `сцена ${с.key} «${с.title}» — ${словоСостояния(состояние)}`
          + '; окно не задано, на оси времени места нет — задайте план работ фазы, и станция встанет на дату',
      }
    }),
  }

  const последняя = дорожки[дорожки.length - 1]
  const низДорожек = последняя.y + 22 + последняя.рядов * последняя.рядВысота + 26
  const низПолки = полка.станции.length > 0
    ? полка.станции[полка.станции.length - 1].y + 26
    : 0
  return {
    недели: дневныеНедели,
    ось: { левое, правое, y: осьY, ширинаДня },
    сегодня: {
      x: сегодняX,
      подпись: датаКратко(сегодня),
      привязка: сегодняX < левое + 60 ? 'start' : сегодняX > правое - 60 ? 'end' : 'middle',
    },
    дорожки,
    точки,
    ветви,
    полка,
    высота: низПолки > низДорожек ? низПолки : низДорожек,
  }
}

/**
 * Ветви дорожки: ОДНА на пару «сцена → дорожка». Двенадцать пунктиров из
 * одной станции — это клубок, а не карта; смысл же один: артефакт этой сцены
 * питает дорожку. Ветвь ведёт к первому мероприятию, которое его ждёт.
 */
function новыеВетви(дорожка: Lane, сцены: Scene[]): { сцена: Scene; дело: Activity; артефакт: string }[] {
  const взятые = new Set<string>()
  const список: { сцена: Scene; дело: Activity; артефакт: string }[] = []
  дорожка.activities.forEach((дело) => {
    const найдено = источникВходов(дело, сцены)
    if (!найдено || !найдено.сцена.window || взятые.has(найдено.сцена.key)) return
    взятые.add(найдено.сцена.key)
    список.push({ сцена: найдено.сцена, дело, артефакт: найдено.артефакт })
  })
  return список
}

/** Скошенный квадрат мероприятия: тот же скос, что у маркера (markers.tsx). */
function скошенный(x: number, y: number, r: number): string {
  return `${x - r},${y - r} ${x + r - 4},${y - r} ${x + r},${y - r + 4} ${x + r},${y + r} ${x - r},${y + r}`
}

/** Ромб точки. */
function ромб(x: number, y: number, r: number): string {
  return `${x},${y - r} ${x + r},${y} ${x},${y + r} ${x - r},${y}`
}

/**
 * Карта фазы (экран 5 шипа 2) — герой продукта: ось времени неделями, линия
 * «сегодня», дорожки метода, станции на датах окон, ромбы точек на своих
 * датах, пунктирные ветви артефактов между дорожками. Клик по станции — сцена.
 */
export function PhaseMap({ phase, onScene }: { phase: Phase; onScene: (key: string) => void }) {
  const сегодня = сегодняДата()
  const карта = useMemo(() => раскладкаКарты(phase, сегодня), [phase, сегодня])

  if (!карта) {
    return (
      <div className="v2-empty">
        План фазы не задан: ни у одной сцены нет окна, ни у одной точки — даты.
        <span className="v2-empty__why">
          Карта стоит на календаре. Задайте даты точек и окна сцен планом работ фазы ниже —
          и маршрут встанет на ось времени.
        </span>
      </div>
    )
  }

  const нажать = (ключ: string) => (событие: { key: string; preventDefault: () => void }) => {
    if (событие.key === 'Enter' || событие.key === ' ') {
      событие.preventDefault()
      onScene(ключ)
    }
  }

  return (
    <div className="v2-pmap">
      <svg className="v2-pmap__svg" viewBox={`0 0 ${ШИРИНА} ${карта.высота}`} role="img"
        aria-label={`карта фазы по оси времени: недель ${карта.недели.length}, дорожек ${карта.дорожки.length}`}>
        {/* Недели сверху: подпись — понедельник недели, засечка — её начало. */}
        {карта.недели.map((н) => (
          <g key={н.дата}>
            <title>{`неделя с ${н.подпись}`}</title>
            <rect className="v2-pmap__tick" x={н.x} y={карта.ось.y - 7} width={1} height={7} />
            <text className="v2-pmap__wk" x={н.x + 3} y={карта.ось.y - 11}>{н.подпись}</text>
          </g>
        ))}
        <rect className="v2-pmap__axis" x={карта.ось.левое} y={карта.ось.y}
          width={карта.ось.правое - карта.ось.левое} height={1} />

        {/* Линия «сегодня» кобальтом — единственное яркое место карты. */}
        <g>
          <title>{`сегодня ${карта.сегодня.подпись}`}</title>
          <rect className="v2-pmap__now" x={карта.сегодня.x} y={карта.ось.y} width={2}
            height={карта.высота - карта.ось.y - 20} />
          <text className="v2-pmap__now-t" x={карта.сегодня.x} y={карта.высота - 6}
            textAnchor={карта.сегодня.привязка}>сегодня {карта.сегодня.подпись}</text>
        </g>

        {/* Ветви артефактов идут до станций, чтобы пунктир лежал под фигурами. */}
        {карта.ветви.map((в) => (
          <g key={в.ключ}>
            <title>{`поток артефакта: ${в.подпись}`}</title>
            <path className="v2-pmap__flow"
              d={`M ${в.откуда.x} ${в.откуда.y} V ${в.уровень} H ${в.куда.x} V ${в.куда.y}`} />
            <text className="v2-pmap__flow-t" x={в.подписьX} y={в.уровень - 5} textAnchor="middle">
              {в.подпись}
            </text>
          </g>
        ))}

        {карта.дорожки.map((дорожка) => (
          <g key={дорожка.ключ}>
            <g>
              <title>{`дорожка «${дорожка.заголовок}»`}</title>
              <text className="v2-pmap__lane-t" x={12}
                y={дорожка.строки.length > 1 ? дорожка.y - 4 : дорожка.y + 4}>
                {дорожка.строки.map((строка, i) => (
                  <tspan key={строка} x={12} dy={i === 0 ? 0 : 15}>{строка}</tspan>
                ))}
              </text>
            </g>
            <rect className="v2-pmap__lane" x={карта.ось.левое} y={дорожка.y - 1}
              width={карта.ось.правое - карта.ось.левое} height={3} />
            {дорожка.станции.map((ст) => (
              <g key={ст.ключ ?? ст.имя} className={ст.ключ ? 'v2-pmap__go' : undefined}
                role={ст.ключ ? 'button' : undefined} tabIndex={ст.ключ ? 0 : undefined}
                onClick={ст.ключ ? () => onScene(ст.ключ!) : undefined}
                onKeyDown={ст.ключ ? нажать(ст.ключ) : undefined}>
                <title>{ст.подсказка}</title>
                {ст.окно && (
                  <rect className={`v2-pmap__win${ст.окно.просрочено ? ' v2-pmap__win--late' : ''}`}
                    x={ст.окно.x} y={дорожка.y - 3} width={ст.окно.ширина} height={6} />
                )}
                {ст.ключ
                  ? <circle className={`v2-pmap__stn v2-pmap__stn--${КЛАСС_СОСТОЯНИЯ[ст.состояние]}`}
                    cx={ст.x} cy={дорожка.y} r={R_СТАНЦИИ} />
                  : <polygon className={`v2-pmap__act v2-pmap__stn--${КЛАСС_СОСТОЯНИЯ[ст.состояние]}`}
                    points={скошенный(ст.x, дорожка.y, R_ДЕЛА)} />}
                <text className="v2-pmap__lbl" x={ст.подпись.x} textAnchor={ст.подпись.привязка}
                  y={дорожка.y + 22 + ст.подпись.ряд * дорожка.рядВысота}>{ст.подпись.текст}</text>
                {ст.роль && (
                  <g>
                    <title>{`роль сцены: ${ст.роль.слово}`}</title>
                    <rect className="v2-pmap__chip" rx={6} height={14}
                      width={ст.роль.чип.length * 7 + 12}
                      x={ст.x - (ст.роль.чип.length * 7 + 12) / 2}
                      y={дорожка.y + 27 + ст.подпись.ряд * дорожка.рядВысота} />
                    <text className="v2-pmap__chip-t" x={ст.x} textAnchor="middle"
                      y={дорожка.y + 37 + ст.подпись.ряд * дорожка.рядВысота}>{ст.роль.чип}</text>
                  </g>
                )}
              </g>
            ))}
          </g>
        ))}

        {/* Точки — ромбы на своих датах на верхней дорожке, подписи над ней. */}
        {карта.точки.map((т) => (
          <g key={т.ключ}>
            <title>{т.подсказка}</title>
            <polygon className={`v2-pmap__gate v2-pmap__stn--${КЛАСС_СОСТОЯНИЯ[т.состояние]}`}
              points={ромб(т.x, т.y, R_ТОЧКИ)} />
            <text className={`v2-pmap__lbl${т.блокирует > 0 ? ' v2-pmap__lbl--bad' : ''}`}
              x={т.подпись.x} textAnchor={т.подпись.привязка}
              y={карта.дорожки[0].y - 22 - т.подпись.ряд * РЯД_ТОЧЕК}>{т.подпись.текст}</text>
          </g>
        ))}

        {/* Правая полка: сцены без окна стоят отдельно, а не поверх датированных. */}
        {карта.полка.станции.length > 0 && (
          <g>
            <rect className="v2-pmap__shelf" x={карта.полка.x} y={карта.ось.y} width={1}
              height={карта.высота - карта.ось.y - 20} />
            <text className="v2-pmap__shelf-t" x={карта.полка.x + 10} y={карта.ось.y + 12}>
              {карта.полка.заголовок}
            </text>
            {карта.полка.станции.map((ст) => (
              <g key={ст.ключ} className="v2-pmap__go" role="button" tabIndex={0}
                onClick={() => onScene(ст.ключ)} onKeyDown={нажать(ст.ключ)}>
                <title>{ст.подсказка}</title>
                <circle className={`v2-pmap__stn v2-pmap__stn--${КЛАСС_СОСТОЯНИЯ[ст.состояние]}`}
                  cx={карта.полка.x + 16} cy={ст.y} r={R_СТАНЦИИ - 2} />
                <text className="v2-pmap__lbl" x={карта.полка.x + 30} y={ст.y + 4}>{ст.имя}</text>
              </g>
            ))}
          </g>
        )}
      </svg>

      {/* Легенда словами: фигура и цвет без слова смысла не несут. */}
      <div className="v2-pmap__legend">
        <span><Маркер род="сцена" подпись="кружок на карте" />сцена</span>
        <span><Маркер род="точка" подпись="ромб на карте" />точка</span>
        <span><Маркер род="мероприятие" подпись="скошенный квадрат на карте" />мероприятие</span>
        <span>заполнено зелёным — выполнено</span>
        <span>контур кобальтом — здесь и сейчас</span>
        <span>серый контур — закрыта</span>
        <span>полоска — окно плана, янтарная — окно просрочено</span>
        <span>красная подпись — держит точку</span>
        <span>пунктир — артефакт уходит на другую дорожку</span>
      </div>
    </div>
  )
}

/** Уровень сцены: мероприятия с потоками. Клик — рабочая поверхность. */
export function SceneMap({ scene, current, onPick }: {
  scene: Scene
  current: string | null
  onPick: (code: string) => void
}) {
  const { nodes, edges } = useMemo(() => {
    const узлы: Node[] = scene.activities.map((дело) => блок(
      `a-${дело.code}`,
      `${дело.code} · ${дело.name}`,
      подписьМероприятия(дело),
      дело.state,
      дело.code === current,
      () => onPick(дело.code),
      дело.goal,
    ))
    const рёбра: Edge[] = scene.activities.slice(1).map((дело, i) => {
      const предыдущее = scene.activities[i]
      return {
        id: `e-${предыдущее.code}-${дело.code}`,
        source: `a-${предыдущее.code}`,
        target: `a-${дело.code}`,
        // Стрелка подписана артефактами: это и есть поток метода.
        label: предыдущее.outputs.map((в) => в.what).slice(0, 2).join(' · '),
        labelStyle: { fontSize: 12, fill: 'var(--ink-soft)' },
        markerEnd: { type: MarkerType.ArrowClosed },
      }
    })
    return { nodes: раскладка(узлы, рёбра, 'LR'), edges: рёбра }
  }, [scene, current])

  if (scene.activities.length === 0) {
    return (
      <div className="v2-empty">
        Мероприятий у сцены пока нет.
        <span className="v2-empty__why">
          Схема сцены порождается из полки процессов ЖЦ: сцена без мероприятий — это сцена,
          которую метод ещё не описал.
        </span>
      </div>
    )
  }

  return (
    <div className="v2-map" style={{ height: 160 }}>
      <ReactFlow nodes={nodes} edges={edges} nodeOrigin={[0.5, 0.5]} fitView fitViewOptions={{ maxZoom: 1, padding: 0.15 }}
        nodesDraggable={false} nodesConnectable={false} elementsSelectable
        onNodeClick={(_, узел) => onPick(узел.id.slice(2))}>
        <Background />
      </ReactFlow>
    </div>
  )
}

function подписьМероприятия(дело: Activity): string {
  const свои = дело.outputs.filter((в) => !в.produced_in)
  const есть = свои.filter((в) => в.satisfied).length
  const счёт = свои.map((в) => `${в.what}: ${в.count}`).slice(0, 2).join(' · ')
  return `${СОСТОЯНИЕ[дело.state]}${свои.length > 0 ? ` · выходов ${есть} из ${свои.length}` : ''}${счёт ? ` · ${счёт}` : ''}`
}
