// Кнопка-пиктограмма (шип 5 §1.5): в таблице действие строки — пиктограмма с
// подсказкой и именем для чтения экрана; в панели действий — пиктограмма и
// слово; при плотности «просторно» слово появляется и в таблице.
// Пиктограмма без слова где бы то ни было — отказ сторожа 8(c): у этой
// кнопки `title` и `aria-label` обязательны и равны слову действия.
import { useContext, type ButtonHTMLAttributes } from 'react'
import { Икон, type Пиктограмма } from '../icons'
import { ПлотностьКонтекст } from './density'

export function ИконКнопка({ икон, слово, сословом, className, ...прочее }: {
  икон: Пиктограмма
  /** Слово действия — глагол: «принять», «к месту», «снять с обоснованием». */
  слово: string
  /** Слово рядом всегда (панель действий); иначе — только при «просторно». */
  сословом?: boolean
} & Omit<ButtonHTMLAttributes<HTMLButtonElement>, 'title' | 'aria-label' | 'children'>) {
  const { просторно } = useContext(ПлотностьКонтекст)
  const виднослово = сословом || просторно
  return (
    <button type="button" {...прочее} className={[виднослово ? 'v2-ib v2-ib--word' : 'v2-ib', className].filter(Boolean).join(' ')}
      title={слово} aria-label={слово}>
      <Икон имя={икон} />
      {виднослово && <span>{слово}</span>}
    </button>
  )
}
