// Плотность экрана для общих компонентов (шип 5): режим роли (мероприятие ·
// сцена · фаза), «просторно» и эксперт-режим — из шапки, одним контекстом.
// Карточка объекта берёт отсюда число колонок граней, кнопка-пиктограмма —
// видно ли слово, вкладки — открыты ли эксперт-вкладки.
import { createContext } from 'react'
import type { Режим } from '../density'

export interface Плотность {
  режим: Режим
  /** «Просторно»: слово рядом с пиктограммой и в таблице, три колонки граней. */
  просторно: boolean
  эксперт: boolean
  /** Учётка — автор правок на месте (карточка объекта); null — вход не выбран. */
  кто?: string | null
}

export const ПлотностьКонтекст = createContext<Плотность>({ режим: 'сцена', просторно: false, эксперт: false })

/** Колонки граней карточки: одна у инженера (мероприятие), две у СИ и РП, три «просторно». */
export function колонокГраней(п: Плотность): 1 | 2 | 3 {
  if (п.просторно) return 3
  return п.режим === 'мероприятие' ? 1 : 2
}
