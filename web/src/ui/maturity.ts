// Словарь один: экраны, каждый со своей копией порядка и подписей, разошлись
// бы молча. Кнопка называет ДЕЙСТВИЕ («утвердить»), а не целевой код.
//
// Пояснения ступеней — ответ на находку живой сессии: разница «утверждён» и
// «базирован» была неочевидна, и лестница у базированного объекта исчезала
// молча, не оставляя следа, что путь пройден.

export const STATUS_ORDER = ['Draft', 'Preliminary', 'Approved', 'Baseline']

export const STATUS_ACTION: Record<string, string> = {
  Preliminary: 'Утвердить предварительно',
  Approved: 'Утвердить',
  Baseline: 'Базировать',
}

/** Что означает ступень — подсказки инженеру, не знающему регламента наизусть. */
export const STATUS_MEANING: Record<string, string> = {
  Draft: 'Черновик: рабочая правка свободна, неполнота допустима',
  Preliminary: 'Предварительно утверждён: согласован для работы, ещё меняется',
  Approved: 'Утверждён: принят как основа дальнейших решений, правка нежелательна',
  Baseline:
    'Базирован: под управлением конфигурацией — правка только новой версией с основанием; ' +
    'контрольные точки проверяют именно эту ступень',
}

/** Куда объект может шагнуть со своего статуса: только вперёд и на одну ступень. */
export function nextStatuses(status: string | null): string[] {
  const i = STATUS_ORDER.indexOf(status ?? 'Draft')
  if (i < 0 || i === STATUS_ORDER.length - 1) return []
  return [STATUS_ORDER[i + 1]]
}
