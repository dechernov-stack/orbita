export function countPhrase(type: string, n: number): string {
  const forms = TYPE_PLURALS[type] ?? [type, type, type]
  const d10 = n % 10
  const d100 = n % 100
  const form = d10 === 1 && d100 !== 11 ? forms[0]
    : d10 >= 2 && d10 <= 4 && (d100 < 12 || d100 > 14) ? forms[1] : forms[2]
  return `${n} ${form}`
}
