// Находка живого прохода ПМИ-3: пачка отклонена, «отклонённые сняты из
// выбора — примите оставшихся», а принять нечего: счётчик показывает ноль.
//
// Причина: черновой id пакета, занятый в системе, при акцепте получает
// свежий, и отказ приходит на НОВОЕ имя. Инженер видит в списке старое —
// снять отметку не с чего, а вычитание «показано минус исключено» уползает
// в ноль, потому что исключённые имена в списке не значатся.
import { describe, expect, it } from 'vitest'

/** Имя строки в списке инженера: перебитый id ему ни о чём не говорит. */
function вСписке(p: { id?: string | null; source_id?: string | null }): string | null {
  return p.source_id ?? p.id ?? null
}

/** Сколько строк реально можно принять — считается по факту, не вычитанием. */
function кПриёму(показано: string[], исключено: Set<string>): number {
  return показано.filter((id) => !исключено.has(id)).length
}

describe('снятие отметок при отказе пачки', () => {
  const показано = ['SV-0101', 'SV-0102', 'SV-0103', 'SV-0104']

  it('отметка снимается с того имени, что стоит в списке', () => {
    // сервер отказал строкам, чьи id были перебиты: SV-0101 → SV-0113 и т. д.
    const problems = [
      { id: 'SV-0113', source_id: 'SV-0101', message: 'граница проекта' },
      { id: 'SV-0115', source_id: 'SV-0103', message: 'граница проекта' },
    ]
    const исключено = new Set(problems.map(вСписке).filter(Boolean) as string[])
    expect([...исключено].sort()).toEqual(['SV-0101', 'SV-0103'])
    expect(кПриёму(показано, исключено)).toBe(2)
  })

  it('счётчик не уползает в ноль от чужих имён', () => {
    // прежнее поведение: в исключённые попадали перебитые имена, которых
    // в списке нет, и вычитание давало ноль при живых строках
    const чужие = new Set(['SV-0113', 'SV-0115'])
    expect(показано.length - чужие.size).toBe(2) // вычитание врало бы
    expect(кПриёму(показано, чужие)).toBe(4) // по факту принять можно все четыре
  })

  it('без перебивки имён поведение прежнее', () => {
    const problems = [{ id: 'SV-0102', message: 'нет трассы' }]
    const исключено = new Set(problems.map(вСписке).filter(Boolean) as string[])
    expect(кПриёму(показано, исключено)).toBe(3)
  })
})
