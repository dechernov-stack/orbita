#!/usr/bin/env python3
"""Сторож «у выхода сцены есть поверхность» (истина 20.09, field_rules.scene_surfaces).

Правило владельца: «у каждого вида, названного выходом сцены в шаблоне фазы,
есть поверхность на этой сцене; сцена с выходом без поверхности — отказ CI».

Как это вышло: сцена 9 требовала машину режимов и операционные сценарии, а
экрана у сцены не было вовсе — условие говорило «назовите режимы аппарата в
сцене 9», и называть их было негде. Маршруты при этом были с шипа G.
Теперь такая дыра ловится сборкой, а не проходом владельца.

Поверхность — ветка в перечне поверхностей клиента: у сцен Pre-A —
`{текущая.key === 'N' && <Экран …>}` в `web/src/v2/work.tsx`, у сцен Phase A —
`if (ключ === 'A…')` в `web/src/v2/phasea.tsx` (шип 3: привязка «сцена →
реестр с отбором», не новый экран). Сцена без выходов поверхности не требует:
её работа — решение, а не запись (например, точка или обзор).

Храповик: сцена из списка долга, у которой поверхность появилась, обязана
быть снята из списка — иначе отказ. Долг только тает.

Самопроверка: выдуманная сцена с выходом ловится.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent

# Известный долг: сцены, у которых выходы названы, а поверхности нет.
#
# Сторож завёлся 20.09 (истина `field_rules.scene_surfaces`) и сразу показал
# размер дыры: Pre-Phase A закрыта целиком (последней была сцена 9), а фаза A
# шла девятью сценами без экранов (A1, A2, A4, A5, A6, A8, A9, A10, A11).
# Шип 3 (23.09) закрыл все девять привязками «сцена → реестр с отбором» в
# `phasea.tsx` — список пуст. Он остаётся механизмом: НОВАЯ сцена без
# поверхности — отказ сборки, а долг, если его снова назвать, только тает.
ДОЛГ: dict[str, set[str]] = {}
ШАБЛОНЫ = КОРЕНЬ / "docs/tz/v2/полки-порождённые"
ЭКРАНЫ = (КОРЕНЬ / "web/src/v2/work.tsx", КОРЕНЬ / "web/src/v2/phasea.tsx")
ПОВЕРХНОСТЬ = re.compile(r"(?:текущая\.key|ключ) === '([0-9A-Za-z]+)'")


def сцены_с_выходами(шаблон: dict) -> dict[str, list[str]]:
    """Сцена → виды, названные её выходами (в мероприятиях сцены)."""
    найдено: dict[str, list[str]] = {}
    for сцена in шаблон.get("scenes", []):
        ключ = str(сцена.get("key"))
        виды: list[str] = []
        for дело in сцена.get("activities", []) or []:
            for выход in дело.get("outputs", []) or []:
                вид = выход.get("kind")
                # Выход, который делает ДРУГАЯ сцена, здесь не в счёт.
                if вид and not выход.get("produced_in"):
                    виды.append(вид)
        if виды:
            найдено[ключ] = sorted(set(виды))
    return найдено


def поверхности(код: str) -> set[str]:
    return set(ПОВЕРХНОСТЬ.findall(код))


def поверхности_экранов() -> set[str]:
    return {к for экран in ЭКРАНЫ if экран.exists() for к in поверхности(экран.read_text(encoding="utf-8"))}


def проверить() -> list[str]:
    есть = поверхности_экранов()
    беды: list[str] = []
    for файл in sorted(ШАБЛОНЫ.glob("ШАБЛОН-ФАЗЫ-*.json")):
        шаблон = json.loads(файл.read_text(encoding="utf-8"))
        долг = ДОЛГ.get(файл.name, set())
        for сцена, виды in сцены_с_выходами(шаблон).items():
            if сцена in есть:
                # Храповик: долг, у которого поверхность уже есть, обязан быть снят из списка.
                if сцена in долг:
                    беды.append(f"{файл.name}: сцена {сцена} записана долгом, а поверхность у неё есть — снимите её из ДОЛГ")
                continue
            if сцена in долг:
                continue
            беды.append(
                f"{файл.name}: сцена {сцена} даёт выходы ({', '.join(виды)}), "
                "а поверхности у неё нет — работать негде"
            )
    return беды


def долг() -> list[str]:
    """Известные дыры — их видно каждый прогон, чтобы не забывались."""
    названо: list[str] = []
    for файл, сцены in ДОЛГ.items():
        путь = ШАБЛОНЫ / файл
        if not путь.exists():
            continue
        все = сцены_с_выходами(json.loads(путь.read_text(encoding="utf-8")))
        for сцена in sorted(сцены):
            if сцена in все:
                названо.append(f"{файл}: сцена {сцена} — выходы {', '.join(все[сцена])}")
    return названо


def main() -> int:
    беды = проверить()
    if беды:
        print("поверхность сцены: выход есть, работать негде (field_rules.scene_surfaces):")
        for б in беды:
            print("  ", б)
        print("   заведите ветку сцены в web/src/v2/work.tsx (Pre-A) или web/src/v2/phasea.tsx (Phase A) либо поправьте шаблон фазы")
        return 1
    # Самопроверка: сцена с выходом и без поверхности обязана ловиться.
    поддельная = {"scenes": [{"key": "выдумка", "activities": [{"outputs": [{"kind": "requirement"}]}]}]}
    assert сцены_с_выходами(поддельная) == {"выдумка": ["requirement"]}, "самопроверка: выход не опознан"
    assert "выдумка" not in поверхности_экранов(), "самопроверка: поверхность найдена у выдумки"
    # Самопроверка храповика: поверхности Phase A читаются из phasea.tsx.
    assert "A4" in поверхности_экранов(), "самопроверка: ветка сцены A4 в phasea.tsx не найдена"
    шаблонов = len(list(ШАБЛОНЫ.glob("ШАБЛОН-ФАЗЫ-*.json")))
    экранов = len(поверхности_экранов())
    известно = долг()
    print(f"поверхности сцен: новых дыр нет (шаблонов {шаблонов}, поверхностей {экранов})")
    if известно:
        print(f"   известный долг — {len(известно)} сцен без поверхности:")
        for строка in известно:
            print("     ", строка)
    return 0


if __name__ == "__main__":
    sys.exit(main())
