#!/usr/bin/env python3
"""Расчёты моделей проекта-примера — ОТДЕЛЬНО от сборщика и без единого
числа-ответа в тексте.

Правило примера (ЗАДАЧА-CODE-ПРОЕКТ-ПРИМЕР §«Правила честности» п. 4):
модель даёт ответ РАСЧЁТОМ по введённым параметрам. Поэтому здесь только
формулы: на вход — параметры узлов дерева состава (те же, что лежат в
анкетах примера), на выход — величина, единица и строка «чем посчитано»
с подставленными входами. Строка «чем посчитано» и есть расчёт-источник,
который стережёт `tools/validate_example_models.py`: выход без неё в
проект не попадает.

Прокси помечается на выходе (`proxy=True`) — там, где вместо расчёта
взята типовая величина класса (Cd шара-цилиндра, к примеру).

Самопроверка (сверка с независимо известными величинами) — в
`tools/validate_example_models.py`; здесь только счёт.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

# ── мировые постоянные (СИ) ───────────────────────────────────────────────
MU = 3.986004418e14          # гравитационный параметр Земли, м³/с²
R_EARTH = 6_378_137.0        # экваториальный радиус, м
G0 = 9.80665                 # ускорение свободного падения, м/с²
SOLAR_CONST = 1361.0         # солнечная постоянная, Вт/м²
J2 = 1.08262668e-3           # вторая зональная гармоника
K_BOLTZMANN_DBW = -228.6     # 10·lg(k), дБВт/(К·Гц)


@dataclass
class Out:
    """Выход модели: величина, единица и чем посчитана."""

    name: str
    value: float
    unit: str
    how: str
    proxy: bool = False
    digits: int = 3

    def rounded(self) -> float:
        if self.value == 0:
            return 0.0
        порядок = math.floor(math.log10(abs(self.value)))
        знаков = max(0, self.digits - 1 - порядок)
        return round(self.value, знаков)


@dataclass
class Model:
    """Результат расчёта одной модели набора."""

    code: str
    outputs: list[Out] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


# ── общая орбитальная геометрия ───────────────────────────────────────────

def период(высота_км: float) -> float:
    """Период кругового витка по третьему закону Кеплера, с."""
    a = R_EARTH + высота_км * 1000.0
    return 2 * math.pi * math.sqrt(a**3 / MU)


def узловой_дрейф_град_сут(высота_км: float, наклонение_град: float) -> float:
    """Прецессия восходящего узла от J2, °/сут (проверка ССО)."""
    a = R_EARTH + высота_км * 1000.0
    n = math.sqrt(MU / a**3)
    i = math.radians(наклонение_град)
    dω = -1.5 * J2 * (R_EARTH / a) ** 2 * n * math.cos(i)
    return math.degrees(dω) * 86400.0


def наклонная_дальность_км(высота_км: float, угол_места_град: float) -> float:
    """Наклонная дальность до КА при заданном угле места, км (плоская тригонометрия сферы)."""
    h = высота_км * 1000.0
    eps = math.radians(угол_места_град)
    r = R_EARTH + h
    # d = -R·sin ε + √(R²·sin²ε + h² + 2·R·h)
    d = -R_EARTH * math.sin(eps) + math.sqrt((R_EARTH * math.sin(eps)) ** 2 + h * h + 2 * R_EARTH * h)
    return d / 1000.0


def полуугол_покрытия_град(высота_км: float, угол_места_град: float) -> float:
    """Центральный полуугол зоны видимости, ° (λ в геометрии покрытия)."""
    h = высота_км * 1000.0
    eps = math.radians(угол_места_град)
    r = R_EARTH + h
    return math.degrees(math.acos(R_EARTH / r * math.cos(eps)) - eps)


# ── М1 · геометрия построения ─────────────────────────────────────────────

def м1_построение(подгруппы: list[dict], угол_места_град: float = 10.0) -> Model:
    """М1: что даёт построение — период, зона видимости, доля покрытия, интервал возврата.

    `подгруппы`: [{name, planes, per_plane, altitude_km, inclination_deg}].
    Интервал возврата считается по доле поверхности, накрытой мгновенно:
    средняя пауза между пролётами ≈ период / (число КА · доля витка,
    в течение которой точка видит хоть один аппарат).
    """
    m = Model("М1")
    всего = 0
    for g in подгруппы:
        n = g["planes"] * g["per_plane"]
        всего += n
        h, i = g["altitude_km"], g["inclination_deg"]
        T = период(h)
        lam = полуугол_покрытия_град(h, угол_места_град)
        d = наклонная_дальность_км(h, угол_места_град)
        # доля поверхности сферы в шапке полуугла λ: (1 − cos λ)/2
        доля_шапки = (1 - math.cos(math.radians(lam))) / 2
        мгновенно = 1 - (1 - доля_шапки) ** n
        m.outputs += [
            Out(f"{g['name']}: период витка", T, "с",
                f"T = 2π·√(a³/μ), a = R⊕ + {h} км = {(R_EARTH / 1000 + h):.0f} км"),
            Out(f"{g['name']}: полуугол зоны видимости (ε ≥ {угол_места_град:g}°)", lam, "°",
                f"λ = arccos(R⊕/(R⊕+h)·cos ε) − ε при h = {h} км, ε = {угол_места_град:g}°"),
            Out(f"{g['name']}: наклонная дальность (ε = {угол_места_град:g}°)", d, "км",
                f"d = −R⊕·sin ε + √(R⊕²·sin²ε + h² + 2·R⊕·h), h = {h} км"),
            Out(f"{g['name']}: мгновенная доля покрытия", мгновенно * 100, "%",
                f"1 − (1 − f)ⁿ при f = (1 − cos λ)/2 = {доля_шапки * 100:.2f}%, n = {n} КА, λ = {lam:.2f}°"),
        ]
        if мгновенно > 0:
            # средний интервал между пролётами для точки: T·(1 − p)/p,
            # p — доля времени, когда точка видит хоть один аппарат
            p = 1 - (1 - доля_шапки) ** n
            интервал = T / 60 * (1 - p) / p if p < 1 else 0.0
            m.outputs.append(
                Out(f"{g['name']}: средний интервал ожидания пролёта", интервал, "мин",
                    f"T·(1 − p)/p при T = {T / 60:.1f} мин, p = {p * 100:.1f}%"))
    m.outputs.append(
        Out("Всего аппаратов в построении", всего, "шт",
            " + ".join(f"{g['planes']}×{g['per_plane']}" for g in подгруппы)))
    return m


# ── М2а · энергобаланс аппарата ───────────────────────────────────────────

def м2а_энергобаланс(
    площадь_бс_м2: float, кпд_бс: float, bol_вт: float,
    ёмкость_ач: float, напряжение_в: float, dod: float,
    мощность_средняя_вт: float, мощность_пиковая_вт: float,
    высота_км: float,
) -> Model:
    """М2а: сходится ли энергобаланс — генерация, запас батареи, тень витка."""
    m = Model("М2а")
    расчётная_bol = площадь_бс_м2 * кпд_бс * SOLAR_CONST
    энергия = ёмкость_ач * напряжение_в
    доступно = энергия * dod
    T = период(высота_км)
    # доля витка в тени: шапка тени по геометрии цилиндра (наихудший случай, β = 0)
    r = R_EARTH + высота_км * 1000.0
    доля_тени = math.asin(R_EARTH / r) / math.pi
    тень_мин = T * доля_тени / 60
    расход_в_тени = мощность_средняя_вт * тень_мин / 60
    глубина = расход_в_тени / энергия
    m.outputs += [
        Out("Генерация БС на начало ресурса (расчёт)", расчётная_bol, "Вт",
            f"P = S·η·S⊙ = {площадь_бс_м2} м² · {кпд_бс} · {SOLAR_CONST} Вт/м²"),
        Out("Расхождение расчёта с паспортной BOL", расчётная_bol - bol_вт, "Вт",
            f"расчёт {расчётная_bol:.0f} Вт − паспорт {bol_вт:.0f} Вт "
            f"(паспортная величина учитывает потери коммутации и угол падения)"),
        Out("Энергия батареи", энергия, "Вт·ч",
            f"E = C·U = {ёмкость_ач} А·ч · {напряжение_в} В"),
        Out("Разрешённый съём (DoD)", доступно, "Вт·ч",
            f"E·DoD = {энергия:.0f} Вт·ч · {dod}"),
        Out("Длительность тени витка (β = 0, наихудшая)", тень_мин, "мин",
            f"T·asin(R⊕/(R⊕+h))/π при T = {T / 60:.1f} мин, h = {высота_км} км"),
        Out("Съём за тень при средней нагрузке", расход_в_тени, "Вт·ч",
            f"P̄·t = {мощность_средняя_вт} Вт · {тень_мин:.1f} мин"),
        Out("Фактическая глубина разряда за виток", глубина * 100, "%",
            f"съём {расход_в_тени:.1f} Вт·ч / ёмкость {энергия:.0f} Вт·ч"),
        Out("Запас батареи против допустимого DoD", (dod - глубина) / dod * 100, "%",
            f"(DoD {dod} − факт {глубина:.3f}) / DoD {dod}"),
        Out("Отношение пиковой нагрузки к генерации", мощность_пиковая_вт / расчётная_bol, "—",
            f"{мощность_пиковая_вт} Вт / {расчётная_bol:.0f} Вт — пик покрывается батареей"),
    ]
    return m


# ── М3а · спрос ───────────────────────────────────────────────────────────

def м3а_спрос(слои: list[dict]) -> Model:
    """М3а: сколько сообщений в сутки даёт карта спроса.

    `слои`: [{name, terminals, messages_per_day, bytes}] — популяции из
    карты спроса полки. Ничего не домысливается: сколько слоёв дано,
    столько и посчитано.
    """
    m = Model("М3а")
    всего_сообщений = 0.0
    всего_байт = 0.0
    for s in слои:
        сообщений = s["terminals"] * s["messages_per_day"]
        байт = сообщений * s["bytes"]
        всего_сообщений += сообщений
        всего_байт += байт
        m.outputs.append(
            Out(f"{s['name']}: сообщений в сутки", сообщений, "шт/сут",
                f"{s['terminals']} терминалов · {s['messages_per_day']} сообщ./сут"))
    m.outputs += [
        Out("Сообщений в сутки, всего", всего_сообщений, "шт/сут",
            "сумма по слоям карты спроса: " + ", ".join(s["name"] for s in слои)),
        Out("Полезный трафик в сутки", всего_байт / 1e6, "Мбайт/сут",
            "Σ(сообщений · длина сообщения) по слоям: "
            + ", ".join(f"{s['name']} — {s['bytes']} байт" for s in слои)),
        Out("Средняя интенсивность", всего_сообщений / 86400, "сообщ./с",
            f"{всего_сообщений:.0f} сообщ./сут / 86400 с"),
    ]
    return m


# ── М6 · бюджет линии ─────────────────────────────────────────────────────

def м6_линия(
    частота_мгц: float, eirp_терминала_дбвт: float, чувствительность_дбм: float,
    высота_км: float, угол_места_град: float, каналов: int,
    запас_на_потери_дб: float = 3.0,
) -> Model:
    """М6: замыкается ли линия «терминал → КА» и с каким запасом."""
    m = Model("М6")
    d_км = наклонная_дальность_км(высота_км, угол_места_град)
    λ_м = 299_792_458.0 / (частота_мгц * 1e6)
    fspl = 20 * math.log10(4 * math.pi * d_км * 1000 / λ_м)
    приём_дбвт = eirp_терминала_дбвт - fspl - запас_на_потери_дб
    порог_дбвт = чувствительность_дбм - 30
    запас = приём_дбвт - порог_дбвт
    m.outputs += [
        Out("Наклонная дальность линии", d_км, "км",
            f"геометрия при h = {высота_км} км, ε = {угол_места_град:g}°"),
        Out("Потери в свободном пространстве", fspl, "дБ",
            f"FSPL = 20·lg(4πd/λ) при d = {d_км:.0f} км, f = {частота_мгц:g} МГц"),
        Out("Мощность на входе приёмника КА", приём_дбвт, "дБВт",
            f"EIRP {eirp_терминала_дбвт:g} дБВт − FSPL {fspl:.1f} дБ − прочие потери {запас_на_потери_дб:g} дБ"),
        Out("Порог приёмника", порог_дбвт, "дБВт",
            f"чувствительность {чувствительность_дбм:g} дБм − 30 дБ (перевод дБм → дБВт)"),
        Out("Запас линии «вверх»", запас, "дБ",
            f"приём {приём_дбвт:.1f} дБВт − порог {порог_дбвт:.1f} дБВт"),
        Out("Ёмкость приёмника по каналам", каналов, "шт",
            f"из анкеты узла ПН: одновременно демодулируемых каналов {каналов} "
            f"на частоте {частота_мгц:g} МГц"),
    ]
    return m


# ── М10 · топливо и манёвры ───────────────────────────────────────────────

def м10_топливо(
    сухая_масса_кг: float, стартовая_масса_кг: float,
    dv_мс: float, isp_с: float, тяга_мн: float, манёвры: list[dict],
) -> Model:
    """М10: сколько топлива требует программа манёвров и сходится ли масса."""
    m = Model("М10")
    сумма_манёвров = sum(x["dv"] for x in манёвры)
    масса_топлива = сухая_масса_кг * (math.exp(dv_мс / (isp_с * G0)) - 1)
    время_с = dv_мс * сухая_масса_кг / (тяга_мн / 1000.0)
    m.outputs += [
        Out("Δv по таблице манёвров", сумма_манёвров, "м/с",
            " + ".join(f"{x['name']} {x['dv']:g}" for x in манёвры)),
        Out("Масса рабочего тела", масса_топлива, "кг",
            f"m = m_сух·(exp(Δv/(Isp·g₀)) − 1) при m_сух = {сухая_масса_кг} кг, "
            f"Δv = {dv_мс:g} м/с, Isp = {isp_с:g} с"),
        Out("Суммарная длительность работы двигателя", время_с / 86400, "сут",
            f"t = Δv·m/F при F = {тяга_мн:g} мН, m = {сухая_масса_кг} кг"),
        Out("Разница стартовой и сухой массы", стартовая_масса_кг - сухая_масса_кг, "кг",
            f"паспорт: {стартовая_масса_кг} − {сухая_масса_кг} кг"),
        Out("Запас массы сверх рабочего тела", (стартовая_масса_кг - сухая_масса_кг) - масса_топлива, "кг",
            f"разница масс {стартовая_масса_кг - сухая_масса_кг:g} кг − рабочее тело {масса_топлива:.2f} кг"),
    ]
    return m


# ── М12 · наземные станции ────────────────────────────────────────────────

def м12_станции(
    станции: list[dict], подгруппы: list[dict],
    угол_места_град: float, скорость_фидера_мбитс: float,
) -> Model:
    """М12: сколько сеансов и объёма дают выбранные площадки.

    Геометрия: площадка видит аппарат, пока тот в шапке полуугла λ. Для
    оболочки из n равномерно разведённых аппаратов доля времени, когда
    виден хоть один, p = 1 − (1 − f)ⁿ, f = (1 − cos λ)/2. Средний сеанс —
    проход шапки: t ≈ (2λ/360°)·T. Отсюда сеансов в сутки = p·86400/t.

    Широта площадки — ворота, а не поправка: аппарат наклонения i вообще
    не поднимается над горизонтом площадки при |φ| > i + λ. Равномерность
    по широте — приближение первого порядка, и оно подписано на выходе.
    """
    m = Model("М12")
    длительности = []
    for st in станции:
        φ = abs(st["lat"])
        сеансов_всего = 0.0
        видят = []
        for g in подгруппы:
            h, i = g["altitude_km"], g["inclination_deg"]
            n = g["planes"] * g["per_plane"]
            lam = полуугол_покрытия_град(h, угол_места_град)
            T = период(h)
            if φ > i + lam:
                continue
            f = (1 - math.cos(math.radians(lam))) / 2
            p = 1 - (1 - f) ** n
            сеанс_мин = (2 * lam / 360.0) * T / 60
            длительности.append(сеанс_мин)
            сеансов_всего += p * 1440.0 / сеанс_мин
            видят.append(f"{g['name']} (i = {i:g}°, λ = {lam:.1f}°)")
        сеанс_ср = sum(длительности) / len(длительности) if длительности else 0.0
        объём_гбайт = сеансов_всего * сеанс_ср * 60 * скорость_фидера_мбитс / 8 / 1000
        m.outputs.append(
            Out(f"{st['name']}: сеансов в сутки", сеансов_всего, "шт/сут",
                f"Σ p·1440/t по видимым оболочкам при φ = {st['lat']:g}°, ε ≥ {угол_места_град:g}°; "
                + ("видят: " + "; ".join(видят) if видят
                   else "ни одна оболочка не поднимается над горизонтом этой широты")))
        m.outputs.append(
            Out(f"{st['name']}: объём сброса в сутки", объём_гбайт, "Гбайт/сут",
                f"сеансов {сеансов_всего:.1f} · сеанс {сеанс_ср:.1f} мин · "
                f"{скорость_фидера_мбитс:g} Мбит/с / 8 / 1000"))
    if длительности:
        m.outputs.append(
            Out("Средняя длительность сеанса", sum(длительности) / len(длительности), "мин",
                f"t = (2λ/360°)·T, усреднено по {len(длительности)} видимым "
                f"оболочкам при ε ≥ {угол_места_град:g}°"))
    return m


# ── сравнение вариантов построения с отсевом по Парето ────────────────────

def сравнение(варианты: list[dict], порог_ожидания_мин: float, угол_места_град: float = 10.0) -> dict:
    """Сравнение построений: ожидание пролёта против числа аппаратов.

    Отсев — порогом задержки; из прошедших строится множество Парето
    (меньше ожидание и меньше аппаратов одновременно — доминирование).
    """
    строки = []
    for v in варианты:
        всего = sum(g["planes"] * g["per_plane"] for g in v["подгруппы"])
        p = 0.0
        for g in v["подгруппы"]:
            n = g["planes"] * g["per_plane"]
            lam = полуугол_покрытия_град(g["altitude_km"], угол_места_град)
            p += n * (1 - math.cos(math.radians(lam))) / 2
        p = min(0.999, p)
        T = период(v["подгруппы"][0]["altitude_km"])
        ожидание = T / 60 * (1 - p) / p
        строки.append({
            "name": v["name"],
            "satellites": всего,
            "wait_min": ожидание,
            "coverage_pct": p * 100,
            "how": f"p = Σ n·(1 − cos λ)/2 = {p * 100:.1f}%; ожидание = T·(1 − p)/p",
        })
    прошли = [s for s in строки if s["wait_min"] <= порог_ожидания_мин]
    отсев = [s for s in строки if s["wait_min"] > порог_ожидания_мин]
    парето = []
    for s in прошли:
        доминируем = any(
            o is not s and o["wait_min"] <= s["wait_min"] and o["satellites"] <= s["satellites"]
            and (o["wait_min"] < s["wait_min"] or o["satellites"] < s["satellites"])
            for o in прошли
        )
        if not доминируем:
            парето.append(s)
    return {"rows": строки, "passed": прошли, "rejected": отсев, "pareto": парето,
            "threshold_min": порог_ожидания_мин}


# ── М6 · масса и компоновка ───────────────────────────────────────────────

def м6_масса(
    сухая_кг: float, стартовая_кг: float, всего_ка: int,
    доля_на_пуск: float, масса_пн_рн_кг: float, адаптер_кг: float = 0.0,
) -> Model:
    """М6: влезаем ли в лимит носителя и в ограничение доли группировки.

    Свёртка простая и оттого проверяемая: масса построения — сумма по
    вхождениям, масса пуска — доля от неё по ограничению «не более N%
    штатной группировки в одном пуске».
    """
    m = Model("М6")
    построение = стартовая_кг * всего_ка
    на_пуск_ка = math.floor(всего_ка * доля_на_пуск)
    масса_пуска = стартовая_кг * на_пуск_ка + адаптер_кг
    m.outputs += [
        Out("Стартовая масса построения", построение, "кг",
            f"{стартовая_кг} кг × {всего_ка} КА"),
        Out("Сухая масса построения", сухая_кг * всего_ка, "кг",
            f"{сухая_кг} кг × {всего_ка} КА"),
        Out("Аппаратов в одном пуске (ограничение доли)", на_пуск_ка, "шт",
            f"⌊{всего_ка} × {доля_на_пуск_текст(доля_на_пуск)}⌋"),
        Out("Масса полезного груза пуска", масса_пуска, "кг",
            f"{стартовая_кг} кг × {на_пуск_ка} КА"
            + (f" + адаптер {адаптер_кг} кг" if адаптер_кг else "")),
        Out("Запас до лимита носителя", масса_пн_рн_кг - масса_пуска, "кг",
            f"лимит РН {масса_пн_рн_кг} кг − масса пуска {масса_пуска:.0f} кг"),
        Out("Пусков на развёртывание", math.ceil(всего_ка / max(на_пуск_ка, 1)), "шт",
            f"⌈{всего_ка} / {на_пуск_ка}⌉"),
    ]
    return m


def доля_на_пуск_текст(доля: float) -> str:
    return f"{доля * 100:g}%"


# ── М11 · стоимость и сроки ───────────────────────────────────────────────

def м11_стоимость(этапы: list[dict], всего_ка: int) -> Model:
    """М11: во что обходится программа — свёртка оценок этапов.

    `этапы`: [{name, low, high, unit}] — карточки оценок стоимости проекта.
    Ничего не домысливается: сколько оценок заведено, столько и сложено;
    оценка с нулевым диапазоном считается незаполненной и называется.
    """
    m = Model("М11")
    заполненные = [э for э in этапы if (э["low"] or 0) > 0 or (э["high"] or 0) > 0]
    пустые = [э["name"] for э in этапы if э not in заполненные]
    низ = sum(э["low"] or 0 for э in заполненные)
    верх = sum(э["high"] or 0 for э in заполненные)
    m.outputs += [
        Out("Нижняя граница программы", низ, "MRUB",
            "сумма нижних границ по " + ", ".join(э["name"] for э in заполненные)),
        Out("Верхняя граница программы", верх, "MRUB",
            "сумма верхних границ по " + ", ".join(
                f"{э['name']} — {э['high']:g}" for э in заполненные)),
        Out("Ширина диапазона", (верх - низ) / max(низ, 1e-9) * 100, "%",
            f"(верх {верх:.0f} − низ {низ:.0f}) / низ {низ:.0f}"),
    ]
    if всего_ка:
        m.outputs.append(
            Out("Удельная оценка на аппарат (по нижней границе)", низ / всего_ка, "MRUB",
                f"{низ:.0f} MRUB / {всего_ка} КА — грубая параметрика, не смета"))
    if пустые:
        m.notes.append("оценки без диапазона (не сложены): " + ", ".join(пустые))
    return m


# ── М6 · масса и компоновка ───────────────────────────────────────────────

def м6_масса(
    сухая_кг: float, стартовая_кг: float, аппаратов: int,
    доля_на_пуск: float, масса_пн_кг: float, масса_адаптера_кг: float,
) -> Model:
    """М6: влезаем ли в лимит носителя и в ограничение доли на пуск.

    Ограничение «не более доли штатной группировки в одном пуске» (RQ-P-10)
    переводится в число аппаратов и массу под обтекателем — это и есть
    вопрос, на который М6 отвечает.
    """
    m = Model("М6")
    на_пуск = math.floor(аппаратов * доля_на_пуск)
    масса_пуска = на_пуск * стартовая_кг + масса_адаптера_кг
    пусков = math.ceil(аппаратов / на_пуск) if на_пуск else 0
    m.outputs += [
        Out("Сухая масса аппарата", сухая_кг, "кг",
            f"параметр mass_dry узла КА (анкета Ф-06) = {сухая_кг} кг"),
        Out("Стартовая масса аппарата", стартовая_кг, "кг",
            f"параметр mass_wet узла КА (анкета Ф-06) = {стартовая_кг} кг; "
            f"разница с сухой — {стартовая_кг - сухая_кг:g} кг"),
        Out("Доля полезной нагрузки в сухой массе", масса_пн_кг / сухая_кг * 100, "%",
            f"{масса_пн_кг} кг ПН / {сухая_кг} кг сухой массы"),
        Out("Стартовая масса построения", аппаратов * стартовая_кг, "кг",
            f"{аппаратов} КА · {стартовая_кг} кг"),
        Out("Аппаратов в одном пуске (ограничение доли)", на_пуск, "шт",
            f"⌊{аппаратов} · {доля_на_пуск}⌋ — ограничение «не более "
            f"{доля_на_пуск * 100:g}% группировки в пуске»"),
        Out("Масса под обтекателем в одном пуске", масса_пуска, "кг",
            f"{на_пуск} КА · {стартовая_кг} кг + адаптер {масса_адаптера_кг} кг"),
        Out("Пусков на развёртывание", пусков, "шт",
            f"⌈{аппаратов}/{на_пуск}⌉ при ограничении доли на пуск"),
    ]
    return m
