#!/usr/bin/env python3
"""Сторож расчётов проекта-примера (ловушка 1 задания: «подделать расчёт
числом — брак»).

Две проверки, обе на файле `tools/example_models.py`:

1. **Выход модели имеет расчёт-источник.** Каждый `Out(...)` обязан нести
   непустую строку «чем посчитано», и эта строка обязана быть собранной
   (f-строкой с подстановкой входов), а не литералом-описанием. Выход,
   у которого «как посчитано» — просто текст без единого входа, ничем не
   отличается от нарисованного числа.

2. **Числа сходятся с независимо известными величинами.** Период витка,
   солнечно-синхронный дрейф, наклонная дальность, формула Циолковского,
   энергия батареи — величины, которые можно проверить справочником;
   расхождение больше допуска означает, что формулу сломали.

    python3 tools/validate_example_models.py
"""
from __future__ import annotations

import ast
import math
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import example_models as M  # noqa: E402

ФАЙЛ = КОРЕНЬ / "tools/example_models.py"


def проверить_расчёт_источник() -> list[str]:
    """Каждый Out несёт «чем посчитано», и это подстановка входов."""
    беды: list[str] = []
    дерево = ast.parse(ФАЙЛ.read_text(encoding="utf-8"))
    всего = 0
    for узел in ast.walk(дерево):
        if not (isinstance(узел, ast.Call) and isinstance(узел.func, ast.Name)
                and узел.func.id == "Out"):
            continue
        всего += 1
        имя = ast.unparse(узел.args[0])[:60] if узел.args else "?"
        if len(узел.args) < 4:
            беды.append(f"строка {узел.lineno}: выход {имя} без строки «чем посчитано»")
            continue
        how = узел.args[3]
        if isinstance(how, ast.Constant):
            беды.append(
                f"строка {узел.lineno}: у выхода {имя} «чем посчитано» — литерал "
                "без подстановки входов; выход без расчёта-источника неотличим "
                "от нарисованного числа")
        elif isinstance(how, ast.JoinedStr):
            if not any(isinstance(ч, ast.FormattedValue) for ч in how.values):
                беды.append(f"строка {узел.lineno}: у выхода {имя} в «чем посчитано» "
                            "нет ни одного подставленного входа")
    if всего < 20:
        беды.append(f"выходов в расчётах всего {всего} — модуль расчётов подменён?")
    return беды


def почти(получено: float, ожидалось: float, допуск: float, что: str) -> str | None:
    if ожидалось == 0:
        отклонение = abs(получено)
    else:
        отклонение = abs(получено - ожидалось) / abs(ожидалось)
    if отклонение > допуск:
        return (f"{что}: получено {получено:.6g}, ожидалось {ожидалось:.6g} "
                f"(отклонение {отклонение * 100:.2f}% при допуске {допуск * 100:g}%)")
    return None


def проверить_числа() -> list[str]:
    """Сверка с величинами, известными независимо от этого кода."""
    беды: list[str] = []

    # Период круговой орбиты 550 км — 95,6 мин (справочник НОО)
    беды.append(почти(M.период(550) / 60, 95.63, 0.002, "период витка на 550 км, мин"))
    # Период на высоте 0 (орбита у поверхности) — 84,4 мин, «время Шулера»
    беды.append(почти(M.период(0) / 60, 84.49, 0.002, "период у поверхности, мин"))
    # Солнечно-синхронная орбита 600 км: наклонение 97,79° даёт дрейф 0,9856 °/сут
    беды.append(почти(M.узловой_дрейф_град_сут(600, 97.79), 0.9856, 0.02,
                      "прецессия ССО 600 км, °/сут"))
    # Наклонная дальность при ε = 10°, h = 550 км — 1816 км (стандартная геометрия)
    беды.append(почти(M.наклонная_дальность_км(550, 10), 1815.6, 0.002,
                      "наклонная дальность, км"))
    # В зените наклонная дальность равна высоте
    беды.append(почти(M.наклонная_дальность_км(550, 90), 550.0, 1e-6,
                      "наклонная дальность в зените, км"))
    # Полуугол покрытия при ε = 0 и h = 550 км — 22,98°, что даёт радиус
    # следа 22,98° · 111,3 км/° ≈ 2560 км: справочная величина следа НОО
    беды.append(почти(M.полуугол_покрытия_град(550, 0), 22.98, 0.005,
                      "полуугол покрытия при нулевом угле места, °"))
    беды.append(почти(M.полуугол_покрытия_град(550, 0) * 111.32, 2558, 0.01,
                      "радиус следа на поверхности, км"))

    # Циолковский: 78 кг, Δv 120 м/с, Isp 1200 с → 0,799 кг рабочего тела
    м10 = {o.name: o for o in M.м10_топливо(78, 84, 120, 1200, 10,
                                            [{"name": "всё", "dv": 120}]).outputs}
    беды.append(почти(м10["Масса рабочего тела"].value,
                      78 * (math.exp(120 / (1200 * 9.80665)) - 1), 1e-9,
                      "масса рабочего тела по Циолковскому, кг"))

    # Энергия батареи 30 А·ч × 28 В = 840 Вт·ч — арифметика, а не подгонка
    м4 = {o.name: o for o in M.м2а_энергобаланс(1.2, 0.30, 340, 30, 28, 0.3,
                                                110, 240, 550).outputs}
    беды.append(почти(м4["Энергия батареи"].value, 840.0, 1e-9, "энергия батареи, Вт·ч"))
    беды.append(почти(м4["Генерация БС на начало ресурса (расчёт)"].value,
                      1.2 * 0.30 * 1361, 1e-9, "генерация СБ, Вт"))

    # Масса: 84 кг × 36 КА = 3024 кг; в пуск идёт не более 25% группировки
    м6 = {o.name: o for o in M.м6_масса(78, 84, 36, 0.25, 12, 45).outputs}
    беды.append(почти(м6["Стартовая масса построения"].value, 3024.0, 1e-9,
                      "стартовая масса построения, кг"))
    беды.append(почти(м6["Аппаратов в одном пуске (ограничение доли)"].value, 9, 1e-9,
                      "аппаратов в пуске"))

    # Сравнение вариантов: порог отсекает хотя бы один и фронт Парето не пуст
    подгруппы = [dict(name="A", planes=4, per_plane=6, altitude_km=550, inclination_deg=52)]
    итог = M.сравнение(
        [dict(name="плотный", подгруппы=[dict(name="x", planes=5, per_plane=8,
                                              altitude_km=550, inclination_deg=52)]),
         dict(name="редкий", подгруппы=подгруппы)], 60.0)
    if not итог["rejected"]:
        беды.append("сравнение построений: порог задержки не отсеял ни одного варианта")
    if not итог["pareto"]:
        беды.append("сравнение построений: фронт Парето пуст")

    return [b for b in беды if b]


def main() -> int:
    беды = проверить_расчёт_источник() + проверить_числа()
    if беды:
        print("расчёты примера: НЕ в порядке", file=sys.stderr)
        for b in беды:
            print("  ·", b, file=sys.stderr)
        return 1
    print("расчёты примера: выходы несут расчёт-источник, числа сходятся "
          "с независимо известными величинами")
    return 0


if __name__ == "__main__":
    sys.exit(main())
