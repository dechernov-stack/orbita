#!/usr/bin/env python3
"""Сверка живого разбора с урожаем Р05 — первый измеритель качества
атомизации (ЗАДАНИЕ-CODE-ЧАСЫ §6).

Р05 — урожай владельца по той же записке: 101 кандидат двенадцати
классов. Живой разбор даёт факты своих видов. Прямого равенства между
ними нет и быть не может — это разные модели («кандидат сущности»
против «атомарного факта»), — поэтому сверяются ДВЕ вещи, которые
сопоставимы честно:

  · ПОКРЫТИЕ КЛАССОВ: для каждого класса Р05 (стейкхолдер, нужда,
    цель, сервис, ограничение, норматив, риск, вопрос, находка,
    география, веха, бюджет) есть ли в живом разборе факты, которые
    его закрывают. Класс без единого факта — пропуск;
  · ПОКРЫТИЕ РАЗДЕЛОВ: какие разделы записки задействовал живой разбор.
    Прямо вычесть якоря Р05 из живых НЕЛЬЗЯ — нумерация разная: у Р05
    она секционная (s0–s11 по разделам шаблона), у канона Д1 — сквозная
    по всем заголовкам (s1…s46). Поэтому раздел опознаётся ПО ЗАГОЛОВКУ:
    заголовок канона сопоставляется с оглавлением записки (`--note`).
    Без записки блок печатает счётчики и молчит о пропусках, а не
    выдаёт разную нумерацию за расхождение.

Отчёт — «найдено сверх · пропущено · совпало» в
`docs/tz/v2/отчёты/СВЕРКА-РАЗБОРА-С-Р05.md`.

    python3 tools/compare_harvest.py <файл-живого-разбора.json>
    python3 tools/compare_harvest.py --stand http://localhost:8080/api PJ-V2-01 SD-0004

Живой разбор берётся либо файлом (ответ `/v2/intake/atomize`), либо со
стенда — чтобы сверку можно было повторить, а не пересказать.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from collections import Counter
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
Р05 = КОРЕНЬ / "docs/tz/manual-run-4/пакеты/Р05-урожай-записки.json"
ОТЧЁТ = КОРЕНЬ / "docs/tz/v2/отчёты/СВЕРКА-РАЗБОРА-С-Р05.md"

# Класс кандидата Р05 → виды фактов живого разбора, которые его закрывают.
# Соответствие не «один к одному»: класс — это будущая сущность, факт —
# утверждение документа, и один класс закрывается несколькими видами.
СООТВЕТСТВИЕ: dict[str, tuple[str, ...]] = {
    "stakeholder": ("relation", "capability", "assessment"),
    "need": ("capability", "assessment", "framing"),
    "goal": ("quantity", "assessment", "framing"),
    "service": ("capability", "quantity"),
    "constraint": ("framing", "obligation"),
    "normative_ref": ("obligation",),
    "risk": ("assessment", "assumption", "event"),
    "open_question": ("assumption", "assessment"),
    "finding": ("assessment",),
    "geography": ("framing", "relation"),
    "milestone": ("event", "quantity"),
    "budget": ("quantity", "assumption"),
    "property": ("quantity",),
}

ПО_РУССКИ: dict[str, str] = {
    "stakeholder": "стороны миссии",
    "need": "потребности",
    "goal": "цели",
    "service": "сервисы",
    "constraint": "ограничения",
    "normative_ref": "нормативы",
    "risk": "риски",
    "open_question": "открытые вопросы",
    "finding": "находки",
    "geography": "география",
    "milestone": "вехи",
    "budget": "оценки ресурсов",
    "property": "характеристики",
}


def раздел(якорь: str) -> str:
    """Раздел документа из якоря: `s3#2` и `s3` — один раздел `s3`."""
    м = re.match(r"(s\d+)", якорь or "")
    return м.group(1) if м else ""


def якоря_р05(урожай: dict) -> set[str]:
    """Якоря Р05: они секционные (s0–s11) и лежат по-разному у классов."""
    найдено: set[str] = set()
    for пункт in урожай.get("items", []):
        for я in пункт.get("anchors", []) or []:
            if isinstance(я, dict):
                найдено.add(раздел(я.get("anchor", "")))
            elif isinstance(я, str):
                найдено.add(раздел(я))
        for б in пункт.get("block", []) or []:
            найдено.add(раздел(б))
    return {я for я in найдено if я}


def оглавление(записка: Path) -> list[str]:
    """Разделы верхнего уровня записки: `## N. Название`."""
    строки = записка.read_text(encoding="utf-8").splitlines()
    return [с.lstrip("# ").strip() for с in строки if с.startswith("## ")]


def разделы_живые(живые: list[dict], канон: dict[str, str], оглавл: list[str]) -> set[str]:
    """
    Разделы записки, задействованные живым разбором.

    Якорь ведёт к блоку канона; блок принадлежит ближайшему заголовку
    ВЕРХНЕГО уровня — его и считаем. Так две нумерации сходятся в одном
    измерении: названии раздела.
    """
    задействованы: set[str] = set()
    for ф in живые:
        заголовок = канон.get(раздел(ф.get("anchor") or ""))
        if заголовок and заголовок in оглавл:
            задействованы.add(заголовок)
    return задействованы


def живой_из_файла(путь: Path) -> list[dict]:
    данные = json.loads(путь.read_text(encoding="utf-8"))
    return данные.get("facts", данные if isinstance(данные, list) else [])


def живой_со_стенда(base: str, project: str, material: str) -> list[dict]:
    адрес = f"{base}/v2/facts?project={project}"
    with urllib.request.urlopen(адрес, timeout=120) as r:
        данные = json.loads(r.read().decode())
    строки = данные.get("items", данные if isinstance(данные, list) else [])
    return [ф for ф in строки if not material or ф.get("material") == material]


def свести(
    живые: list[dict],
    урожай: dict,
    канон: dict[str, str] | None = None,
    оглавл: list[str] | None = None,
) -> dict:
    канон = канон or {}
    оглавл = оглавл or []
    классы = Counter(п.get("class", "") for п in урожай.get("items", []))
    виды = Counter(ф.get("kind", "") for ф in живые)
    якоряЖ = {раздел(ф.get("anchor") or "") for ф in живые}
    якоряЖ.discard("")
    якоряР = якоря_р05(урожай)
    разделыЖ = разделы_живые(живые, канон, оглавл) if оглавл else set()

    покрытие = {}
    for класс, сколько in классы.items():
        подходящие = СООТВЕТСТВИЕ.get(класс, ())
        есть = sum(виды.get(в, 0) for в in подходящие)
        покрытие[класс] = {
            "кандидатов": сколько,
            "виды": подходящие,
            "фактов": есть,
            "закрыт": есть > 0,
        }
    закрытых = sum(1 for з in покрытие.values() if з["закрыт"])
    return {
        "классов": len(классы),
        "закрытых": закрытых,
        "доля": закрытых / len(классы) if классы else 0.0,
        "покрытие": покрытие,
        "фактов": len(живые),
        "кандидатов": sum(классы.values()),
        "виды": dict(viz(виды)),
        "якоря_живые": sorted(якоряЖ, key=ключЯкоря),
        "якоря_р05": sorted(якоряР, key=ключЯкоря),
        "разделы_всего": len(оглавл),
        "разделы_задействованы": sorted(разделыЖ),
        "разделы_молчат": [р for р in оглавл if р not in разделыЖ],
    }


def viz(счётчик: Counter) -> list[tuple[str, int]]:
    return sorted(счётчик.items(), key=lambda п: -п[1])


def ключЯкоря(я: str) -> tuple[int, str]:
    м = re.match(r"s(\d+)", я)
    return (int(м.group(1)) if м else 999, я)


def отчёт(свод: dict, источник: str) -> str:
    строки = [
        "# Сверка живого разбора с урожаем Р05",
        "",
        f"Источник живого разбора: {источник}. Урожай владельца: "
        f"`docs/tz/manual-run-4/пакеты/Р05-урожай-записки.json`.",
        "",
        "Прямого равенства между разборами нет: Р05 — кандидаты сущностей, "
        "живой разбор — атомарные факты. Сверяется то, что сопоставимо: "
        "закрыт ли каждый класс кандидатов фактами подходящих видов и какие "
        "разделы записки назвал каждый разбор.",
        "",
        f"**Итог: классов закрыто {свод['закрытых']} из {свод['классов']} "
        f"({свод['доля'] * 100:.0f} %)**; фактов живого разбора "
        f"{свод['фактов']}, кандидатов Р05 {свод['кандидатов']}.",
        "",
        "## Покрытие классов",
        "",
        "| Класс Р05 | Кандидатов | Закрывающие виды фактов | Фактов | Состояние |",
        "|---|---|---|---|---|",
    ]
    for класс, з in sorted(свод["покрытие"].items(), key=lambda п: -п[1]["кандидатов"]):
        строки.append(
            f"| {ПО_РУССКИ.get(класс, класс)} | {з['кандидатов']} | "
            f"{', '.join(з['виды']) or '—'} | {з['фактов']} | "
            f"{'закрыт' if з['закрыт'] else '**пропуск**'} |",
        )
    строки += [
        "",
        "## Виды фактов живого разбора",
        "",
        " · ".join(f"{в}: {n}" for в, n in свод["виды"].items()) or "—",
        "",
        "## Покрытие разделов записки",
        "",
        "Нумерация якорей у двух разборов разная (Р05 — секционная s0–s11, "
        "канон Д1 — сквозная по заголовкам), поэтому вычитать их друг из "
        "друга нельзя. Раздел опознаётся по заголовку.",
        "",
        f"- блоков канона назвал живой разбор: {len(свод['якоря_живые'])}",
        f"- блоков назвал Р05: {len(свод['якоря_р05'])}",
    ]
    if свод["разделы_всего"]:
        строки += [
            f"- **разделов записки задействовано: "
            f"{len(свод['разделы_задействованы'])} из {свод['разделы_всего']}**",
            f"- молчат: {'; '.join(свод['разделы_молчат']) or 'нет — задействованы все'}",
        ]
    else:
        строки += [
            "- сопоставление разделов не делалось: запиской (`--note`) "
            "сверка не запускалась",
        ]
    строки += [
        "",
        "## Как повторить",
        "",
        "```bash",
        "python3 tools/compare_harvest.py --stand http://localhost:8080/api PJ-V2-01 SD-0004",
        "```",
    ]
    return "\n".join(строки) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("файл", nargs="?", help="ответ /v2/intake/atomize в JSON")
    ap.add_argument("--stand", nargs=3, metavar=("BASE", "PROJECT", "MATERIAL"),
                    help="взять факты со стенда")
    ap.add_argument("--note", help="файл записки: по нему разделы опознаются заголовком")
    ap.add_argument("--canon", help="канон материала (ответ /v2/intake/canon) в JSON")
    ap.add_argument("--out", default=str(ОТЧЁТ))
    args = ap.parse_args()

    if args.stand:
        живые = живой_со_стенда(*args.stand)
        источник = f"стенд {args.stand[0]}, проект {args.stand[1]}, материал {args.stand[2]}"
    elif args.файл:
        живые = живой_из_файла(Path(args.файл))
        источник = f"файл `{Path(args.файл).name}`"
    else:
        print("нечего сверять: дайте файл разбора либо --stand", file=sys.stderr)
        return 2
    if not живые:
        print("фактов нет: сверять нечего — сначала разбор материала", file=sys.stderr)
        return 1

    урожай = json.loads(Р05.read_text(encoding="utf-8"))
    # Канон нужен, чтобы у якоря был заголовок: без него разделы записки
    # не опознать, и сверка честно об этом молчит.
    оглавл = оглавление(Path(args.note)) if args.note else []
    канон: dict[str, str] = {}
    if args.canon:
        блоки = json.loads(Path(args.canon).read_text(encoding="utf-8")).get("blocks", [])
        # Блок принадлежит ближайшему заголовку ВЕРХНЕГО уровня: факт из
        # «2.1. Нужды» задействует раздел «2. Обоснование потребности», а не
        # подзаголовок. Иначе разделы кажутся молчащими, когда они говорят.
        верхний = ""
        for б in блоки:
            текст = б.get("text", "")
            if б.get("kind") == "heading" and текст in оглавл:
                верхний = текст
            канон[раздел(б.get("anchor", ""))] = верхний
    свод = свести(живые, урожай, канон, оглавл)
    путь = Path(args.out)
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(отчёт(свод, источник), encoding="utf-8")
    print(f"сверка: классов закрыто {свод['закрытых']} из {свод['классов']} "
          f"({свод['доля'] * 100:.0f} %), фактов {свод['фактов']} против "
          f"{свод['кандидатов']} кандидатов → {путь.relative_to(КОРЕНЬ)}")
    if свод["разделы_всего"]:
        print(f"разделов записки задействовано: "
              f"{len(свод['разделы_задействованы'])} из {свод['разделы_всего']}")
        if свод["разделы_молчат"]:
            print("молчат: " + "; ".join(свод["разделы_молчат"]))
    else:
        print("разделы записки не сопоставлялись: запустите с --note и --canon")
    return 0


if __name__ == "__main__":
    sys.exit(main())
