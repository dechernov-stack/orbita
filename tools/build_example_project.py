def шаг_модели(st: Стенд, ж: Журнал, p: str) -> dict:
    """ADR-050: модель даёт ответ РАСЧЁТОМ по параметрам узлов.

    Каждый выход несёт строку «расчёт: …» с формулой и подставленными
    входами — это и есть расчёт-источник, который стережёт
    `tools/validate_example_models.py`.
    """
    ж.шаг("Модели системы: расчёты (Петрова, инженер)")
    записи = {}
    for о in объекты(st, "system_model", p):
        if о["status"] == "Cancelled":
            continue
        полный = st.get(f"/objects/{о['id']}")
        записи[полный["doc"].get("code", "")] = (о["id"], полный["doc"], полный["version"])
    ж.факт(f"записей моделей на месте: {len(записи)}")

    # новые записи набора заводятся ОДИН раз
    for код, шапка in НОВЫЕ_МОДЕЛИ.items():
        if код in записи:
            continue
        doc = dict(шапка, code=код, status="not_built",
                   lifecycle={"status": "Draft", "version": "1"})
        новый = st.post(f"/edit/system_model?project={p}",
                        {"doc": doc, "author": ИСТОЧНИК}, кто=ИНЖЕНЕР)
        полный = st.get(f"/objects/{новый['id']}")
        записи[код] = (новый["id"], полный["doc"], полный["version"])
        ж.факт(f"{код} «{шапка['name'][:44]}» — новая запись набора, часть "
               f"{', '.join(шапка['feeds'][:1])}")

    посчитано, без_записи = 0, []
    for код, (что, посчитать) in РАСЧЁТЫ.items():
        цель = записи.get(код)
        if цель is None:
            без_записи.append(код)
            continue
        ид, d, версия = цель
        выходы = выходы_модели(посчитать())
        if лёг_так_же(d.get("outputs"), выходы) and d.get("status") == "computed":
            ж.факт(f"{код} «{d.get('name', '')[:38]}»: расчёт совпал — правки нет")
            continue
        st.patch(f"/edit/{ид}?project={p}", {
            "changes": {"outputs": выходы, "status": "computed",
                        "tool": "расчёт по параметрам узлов "
                                "(tools/example_models.py)"},
            "base_version": версия, "author": ИСТОЧНИК}, кто=ИНЖЕНЕР)
        посчитано += 1
        ж.факт(f"{код} «{d.get('name', '')[:38]}» ({что}): выходов {len(выходы)}, "
               f"первый — {выходы[0]['name']}: {выходы[0]['value']['value']} "
               f"{выходы[0]['value']['unit']}")
    if без_записи:
        ж.факт("расчёт есть, записи в наборе нет: " + ", ".join(без_записи))

    # самолечение: следы прежней (ошибочной) раскладки в чужих записях
    for код, (ид, d, версия) in записи.items():
        if код in РАСЧЁТЫ:
            continue
        чужие = [o for o in (d.get("outputs") or [])
                 if str(o.get("note", "")).startswith(ПРИЗНАК_РАСЧЁТА)]
        if not чужие:
            continue
        прототип = прототип_модели(st, код)
        st.patch(f"/edit/{ид}?project={p}", {
            "changes": {"outputs": прототип.get("outputs", []),
                        "status": прототип.get("status", "not_built"),
                        "tool": прототип.get("tool", "")},
            "base_version": версия, "author": ИСТОЧНИК}, кто=ИНЖЕНЕР)
        ж.факт(f"{код}: чужой расчёт снят, запись возвращена к эталону полки")

    сравнение = ММ.сравнение(ВАРИАНТЫ, ПОРОГ_ОЖИДАНИЯ_МИН)
    ж.факт(f"моделей посчитано: {посчитано} из {len(РАСЧЁТЫ)}")
    ж.факт(f"сравнение построений: порог ожидания {ПОРОГ_ОЖИДАНИЯ_МИН:g} мин · "
           f"прошло {len(сравнение['passed'])} · отсеяно {len(сравнение['rejected'])} · "
           f"на фронте Парето {len(сравнение['pareto'])}")
    for s in сравнение["rows"]:
        метка = ("отсеян порогом" if s in сравнение["rejected"]
                 else "Парето" if s in сравнение["pareto"] else "доминируем")
        ж.факт(f"    {s['name']}: {s['satellites']} КА · ожидание "
               f"{s['wait_min']:.0f} мин · покрытие {s['coverage_pct']:.0f}% — {метка}")
    return сравнение


