class Отказ(RuntimeError):
    def __init__(self, код: int, тело: str, где: str):
        super().__init__(f"{код} {где}: {тело[:900]}")
        self.код, self.тело, self.где = код, тело, где


class Стенд:
    """Три сессии — три человека. Автор пишется из учётки, не из тела."""

    def __init__(self, base: str, сухо: bool = False):
        self.base = base.rstrip("/")
        self.сухо = сухо
        self._открыватели: dict[str, urllib.request.OpenerDirector] = {}

    def _кто(self, login: str):
        if login not in self._открыватели:
            jar = http.cookiejar.CookieJar()
            op = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(jar))
            req = urllib.request.Request(
                self.base + "/auth/stand-login",
                data=json.dumps({"login": login}).encode(),
                headers={"Content-Type": "application/json; charset=utf-8"},
                method="POST")
            with op.open(req):
                pass
            self._открыватели[login] = op
        return self._открыватели[login]

    def вызов(self, method: str, path: str, тело=None, кто: str = РП,
              байты: bytes | None = None, тип: str = "application/json; charset=utf-8",
              сырой: bool = False):
        if self.сухо and method != "GET":
            return {"—": "сухой прогон"}
        data = байты if байты is not None else (
            json.dumps(тело, ensure_ascii=False).encode() if тело is not None else None)
        req = urllib.request.Request(self.base + path, data=data,
                                     headers={"Content-Type": тип}, method=method)
        try:
            with self._кто(кто).open(req) as r:
                b = r.read()
                if сырой:
                    return b
                return json.loads(b.decode()) if b else {}
        except urllib.error.HTTPError as e:
            raise Отказ(e.code, e.read().decode(errors="replace"), f"{method} {path}") from None

    # сокращения
    def get(self, path, кто=РП, **kw):
        return self.вызов("GET", path, кто=кто, **kw)

    def post(self, path, тело=None, кто=РП, **kw):
        return self.вызов("POST", path, тело, кто=кто, **kw)

    def patch(self, path, тело=None, кто=РП):
        return self.вызов("PATCH", path, тело, кто=кто)


class Журнал:
    """Журнал сборки: честные числа — сколько, чего, кем."""

    def __init__(self):
        self.строки: list[str] = []
        self.вопросы: list[str] = []

    def шаг(self, имя: str):
        self.строки.append(f"\n## {имя}")
        print(f"\n── {имя}")

    def факт(self, текст: str):
        self.строки.append(f"- {текст}")
        print(f"   {текст}")

    def вопрос(self, текст: str):
        self.вопросы.append(текст)
        self.строки.append(f"- **вопрос владельцу:** {текст}")
        print(f"   ? {текст}")


