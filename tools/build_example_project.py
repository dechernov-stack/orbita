def шаг_единицы(st: Стенд, ж: Журнал, p: str) -> None:
    """Ф-03/Ф-15: единицы пакета обязаны быть в справочнике. «1/сут» —
    та же частота, только суточная: добавляется входной единицей, а не
    новой размерностью, и правка справочника делается зряче."""
    ж.шаг("Справочник единиц: «1/сут» (Иванов, ведущий СИ)")
    реестр = объекты(st, "unit_registry", "LIB")
    if not реестр:
        ж.факт("справочника единиц на полке нет — единицы пакетов не проверить")
        return
    ид = реестр[0]["id"]
    полный = st.get(f"/objects/{ид}")
    doc, версия = полный["doc"], полный["version"]
    размерности = doc.get("dimensions", [])
    частота = next((d for d in размерности if d.get("canon") == "Hz"), None)
    if частота is None:
        ж.факт("размерности частоты в справочнике нет — «1/сут» вносить некуда")
        return
    if any("1/сут" in (i.get("spellings") or []) or i.get("unit") == "1/d"
           for i in частота.get("inputs", [])):
        ж.факт("«1/сут» уже в справочнике — правки нет")
        return
    последствия = st.get(f"/views/registry-impact?type=unit_registry&project={p}")
    ж.факт("последствия правки справочника: " + последствия.get("warning", "—"))
    частота.setdefault("inputs", []).append({
        "unit": "1/d", "factor": 1 / 86400,
        "spellings": ["1/сут", "раз в сутки", "сообщений в сутки"],
    })
    st.patch(f"/edit/{ид}?project={p}",
             {"changes": {"dimensions": размерности}, "base_version": версия,
              "author": ИСТОЧНИК}, кто=ВЕДУЩИЙ)
    ж.факт("«1/сут» добавлена входной единицей размерности «частота» "
           "(1/86400 Гц) — новой размерности не заводилось")


