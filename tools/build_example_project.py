def дополнить_верификацию(st: Стенд, ж: Журнал, p: str, ид: str, счёт: list[int]) -> bool:
    """Добавить закрывающее событие, если плана закрытия у требования нет."""
    полный = st.get(f"/objects/{ид}")
    d = полный["doc"]
    события = list(d.get("verification_events") or [])
    if any(e.get("closes") for e in события):
        return False
    метод, подход = ЗАКРЫВАЮЩЕЕ.get(d.get("category", ""), ЗАКРЫВАЮЩЕЕ["functional"])
    счёт[0] += 1
