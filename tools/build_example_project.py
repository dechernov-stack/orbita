def шаг_риски(st: Стенд, ж: Журнал, p: str) -> None:
    """Р09: реестр рисков со шкалами NPR 8000.4; сроки — точками фазы."""
    ж.шаг("Риски (Петрова, инженер)")
    вставить(st, ж, p, "Р09-риски.json", ИНЖЕНЕР, "risk")
    живые = [o for o in объекты(st, "risk", p) if o["status"] != "Cancelled"]
    док = {o["id"]: st.get(f"/objects/{o['id']}") for o in живые}
    со_сроком = sum(1 for f in док.values() if f["doc"].get("due"))
    ж.факт(f"рисков в реестре: {len(живые)}, со сроком: {со_сроком}")
    закрыто = 0
    for начало_формулировки, остаток in ЗАКРЫТЫЕ_РИСКИ.items():
        цель = next((ид for ид, f in док.items()
                     if (f["doc"].get("statement") or "").lower()
                     .startswith(начало_формулировки)
                     and f["doc"].get("status") != "closed"), None)
        if цель is None:
            continue
        исходный = док[цель]["doc"]
        # остаточная оценка не может быть выше исходной: мероприятие снижает
        # вероятность, последствие остаётся — риск закрыт, а не забыт
        st.patch(f"/edit/{цель}?project={p}", {"changes": {
            "status": "closed",
            "residual": {"probability": 1, "impact": исходный.get("impact", 1)},
            "actions": (исходный.get("actions") or []) + [остаток],
        }, "base_version": док[цель]["version"], "author": ИСТОЧНИК}, кто=ИНЖЕНЕР)
        закрыто += 1
        ж.факт(f"{цель} закрыт: {остаток[:110]}")
    всего_закрытых = sum(1 for f in док.values()
                         if f["doc"].get("status") == "closed") + закрыто
    ж.факт(f"закрыто рисков в этот проход: {закрыто}; всего закрытых: {всего_закрытых}")



