def слова(текст: str) -> set[str]:
    """Значимые слова имени: по ним имя из документа узнаётся в стороне."""
    очищенный = "".join(c if c.isalpha() or c.isspace() else " " for c in текст.lower())
    return {w for w in очищенный.split() if len(w) >= 4}


def совпадение(имя: str, стороны: dict[str, str]) -> tuple[str | None, set[str]]:
    """Сторона, чьё имя делит с документом больше всего значимых слов.
    Ни одного общего слова — пары нет: наугад назначать носителя нельзя."""
    if not имя:
        return None, set()
    если_точно = стороны.get(имя)
    if если_точно:
        return если_точно, слова(имя)
    из_документа = слова(имя)
    лучшая, лучшие = None, set()
    for н, ид in стороны.items():
        общие = из_документа & слова(н)
        if len(общие) > len(лучшие):
            лучшая, лучшие = ид, общие
    return (лучшая, лучшие) if лучшие else (None, set())


