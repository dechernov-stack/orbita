def шаг_дерево(st: Стенд, ж: Журнал, p: str) -> None:
    """В2.1: дерево состава — ВХОЖДЕНИЯ. Каркас даёт определения, дерево
    строит инженер: один корень, аппарат входит двумя подгруппами."""
    ж.шаг("Дерево состава: вхождения (Петрова, инженер)")
    живые = [o for o in объекты(st, "component", p) if o["status"] != "Cancelled"]
    doc = {o["id"]: st.get(f"/objects/{o['id']}")["doc"] for o in живые}
    дети: dict[str, list[str]] = {}
    for d in doc.values():
        дети.setdefault(d.get("parent") or "", []).append(d["id"])
    корни = дети.get("", [])
    if len(корни) != 1:
        ж.факт(f"корней в каркасе {len(корни)} — дерево не строится, "
               "требуется один (ADR-044)")
        return
    уже = [o for o in объекты(st, "component_usage", p) if o["status"] != "Cancelled"]
    if уже:
        ж.факт(f"вхождений уже {len(уже)} — дерево построено ранее")
        return

    создано = [0]

    def вхождение(опр: str, родитель: str | None, кратность: int, роль: str | None) -> str:
        тело = {"definition_ref": опр, "quantity": кратность}
        if родитель:
            тело["parent_usage"] = родитель
        if роль:
            тело["role"] = роль
        ответ = st.post(f"/edit/component_usage?project={p}",
                        {"doc": тело, "author": ИСТОЧНИК}, кто=ИНЖЕНЕР)
        создано[0] += 1
        return ответ["id"]

    def поддерево(опр: str, родитель: str | None, кратность: int, роль: str | None):
        cu = вхождение(опр, родитель, кратность, роль)
        for ребёнок in sorted(дети.get(опр, [])):
            код = doc[ребёнок].get("code", "")
