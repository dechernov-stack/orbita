def шаг_способности(st: Стенд, ж: Журнал, p: str) -> None:
    """ADR-053: способность привязывает ЧЕЛОВЕК — по предложению службы,
    а где предложений нет — своим основанием."""
    ж.шаг("Способности → цели и нужды (Иванов, ведущий СИ)")
    _КАРТА_ПРОЕКТА.pop(p, None)
    вид = st.get(f"/views/capabilities/matches?project={p}")
    привязано, без_основания = 0, []
    for строка in вид.get("capabilities", []):
        oc, код = строка["id"], строка.get("code", "")
        if строка.get("linked"):
            continue
        кандидаты = строка.get("matches", [])[:2]
        if кандидаты:
            refs = [{"ref": k["ref"], "rationale":
                     f"предложение службы по формулировке ({k.get('percent', 0)}%), "
                     f"подтверждено инженером"} for k in кандидаты]
        elif код in ОСНОВАНИЯ_СПОСОБНОСТЕЙ:
            refs = []
            for r, почему in ОСНОВАНИЯ_СПОСОБНОСТЕЙ[код]:
                цель_ref = свой(st, p, r)
                if цель_ref is None:
                    ж.факт(f"{код}: основание {r} в проекте не найдено — связь "
                           "не ставится")
                    continue
                refs.append({"ref": цель_ref, "rationale": почему})
            if not refs:
                без_основания.append(код or oc)
                continue
        else:
            без_основания.append(код or oc)
            continue
        st.post(f"/views/capabilities/{oc}/trace?project={p}",
                {"refs": refs, "author": ИСТОЧНИК}, кто=ВЕДУЩИЙ)
        привязано += 1
    ж.факт(f"способностей привязано: {привязано}; "
           f"службой предложено {sum(1 for c in вид.get('capabilities', []) if c.get('matches'))}, "
           f"остальные — основанием инженера")
    if без_основания:
        ж.факт("без основания остались: " + ", ".join(без_основания))


