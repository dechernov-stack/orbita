def шаг_полки(st: Стенд, ж: Журнал, p: str) -> None:
    """Ш2: полки берутся ПОЛНЫМ набором — пример показывает всё дерево."""
    ж.шаг("Полки библиотеки (Иванов, ведущий СИ)")
    полки = st.get(f"/library/shelves?project={p}")
    for f in полки:
        if f["id"] in ВЫТЕСНЕННЫЕ:
            ж.факт(f"{f['id']} «{f['name'][:44]}» — вытеснена редакцией 3, не берётся "
                   "(два каркаса дали бы два дерева)")
            continue
        было = f.get("applied", {}).get("count", 0) if f.get("applied") else 0
        try:
            окно = st.get(f"/library/fragments/{f['id']}/take-window?project={p}")
        except Отказ as e:
            ж.факт(f"{f['id']} «{f['name'][:40]}»: окно взятия недоступно — {e.тело[:120]}")
            continue
        всего = len(окно.get("items", []))
        взято = sum(1 for i in окно.get("items", []) if i.get("taken"))
        if взято >= всего > 0:
            ж.факт(f"{f['id']} «{f['name'][:44]}»: уже взята целиком ({всего})")
            continue
        try:
            итог = st.post(f"/library/fragments/{f['id']}/apply?project={p}",
                           {"select_all": True}, кто=ВЕДУЩИЙ)
        except Отказ as e:
            ж.факт(f"{f['id']} «{f['name'][:40]}»: отказ взятия — {e.тело[:160]}")
            continue
        создано = len(итог.get("created", []))
        было_же = len(итог.get("existing", []))
        ж.факт(f"{f['id']} «{f['name'][:44]}»: создано {создано}, уже было {было_же}")


