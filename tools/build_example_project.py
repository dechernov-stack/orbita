    цепи = {o["id"]: st.get(f"/objects/{o['id']}")["doc"]
            for o in объекты(st, "function_chain", p) if o["status"] != "Cancelled"}
    покрыты = set()
    for o in объекты(st, "requirement", p):
        if o["status"] == "Cancelled":
            continue
        покрыты.update(st.get(f"/objects/{o['id']}")["doc"].get("realized_by") or [])
    голые = [c for c in цепи if c not in покрыты]
    if not голые:
        ж.факт("цепочек без сценарного требования нет")
        return
    # цель ищется по ТЕКСТУ, а не по номеру: акцепт перебивает занятые id,
    # и жёсткая ссылка ушла бы в чужой проект
