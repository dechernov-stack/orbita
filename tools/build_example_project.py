def шаг_базирование(st: Стенд, ж: Журнал, p: str) -> None:
    """К MCR проектные требования базируются: дальше правка — процедурой."""
    ж.шаг("Базирование проектных требований (Иванов, ведущий СИ)")
    дерево = st.get(f"/views/requirement-tree?project={p}")
    проектные = [r["id"] for r in дерево["rows"]
                 if r.get("level") == "project" and r.get("status") != "Baseline"]
    счёт = [0]
    дополнено = sum(1 for ид in проектные
                    if дополнить_верификацию(st, ж, p, ид, счёт))
    if дополнено:
        ж.факт(f"планов верификации дополнено закрывающим событием: {дополнено}")
    if not проектные:
        ж.факт("проектные требования уже базированы — перевода нет")
        return
    итог = st.post(f"/objects/promote-batch?project={p}",
                   {"ids": проектные, "status": "Baseline", "author": ИСТОЧНИК},
                   кто=ВЕДУЩИЙ)
    не_прошли = итог.get("failed", [])
    ж.факт(f"базировано: {len(итог.get('promoted', []))} из {len(проектные)}")
    for f in не_прошли[:6]:
        ж.факт(f"    {f['id']} не базировано: {f.get('reason', '')[:160]}")


def шаг_точки(st: Стенд, ж: Журнал, p: str) -> None:
    """Фаза двигается ТОЛЬКО прохождением точки — и фиксирует её DA."""
    ж.шаг("Точки MCR и KDP-A (Чернов, РП · DA)")
    паспорт = st.get(f"/objects/{p}")["doc"]
    пройдены = {m["gate"] for m in паспорт.get("milestones", []) if m.get("held")}
    for точка, дата in (("MCR", ДАТА_MCR), ("KDP-A", ДАТА_KDPA)):
        if точка in пройдены:
            ж.факт(f"{точка}: уже зафиксирована — повтора нет")
            continue
        разрывы = st.get(f"/gates/{точка}/issues?project={p}")
        if not разрывы["ready"]:
            ж.факт(f"{точка}: не готова — {len(разрывы['issues'])} разрывов: "
                   + "; ".join(разрывы["issues"][:3]))
            continue
        итог = st.post(f"/gates/{точка}/pass?project={p}", {
            "rationale": f"комплект точки {точка} рассмотрен {дата}: постановка "
                         "согласована, требования базированы, модели дали ответы, "
                         "документы выпущены; решение — переход к следующей фазе",
            "author": ИСТОЧНИК}, кто=РП)
        ж.факт(f"{точка}: зафиксирована {дата} — {str(итог)[:120]}")
    фаза = st.get(f"/objects/{p}")["doc"].get("phase")
    ж.факт(f"фаза проекта после фиксаций: {фаза}")
    следующая = st.get(f"/views/gate-readiness?project={p}")
    ж.факт(f"следующая точка — {следующая['gate']}: открыто "
           f"{следующая['open_total']}, из них блокирующих "
           f"{следующая['blocking_open']} (честные разрывы примера)")


def шаг_обмен(st: Стенд, ж: Журнал, p: str) -> None:
    """ADR-049: обмен наружу — StrictDoc и ReqIF, снимок базирования."""
    ж.шаг("Обмен: .sdoc, ReqIF, снимок базирования, выгрузка знаний")
    АРТЕФАКТЫ.mkdir(parents=True, exist_ok=True)
    for имя, путь, файл in (
        ("StrictDoc (.sdoc)", f"/export/sdoc?project={p}", "требования.sdoc"),
        ("ReqIF", f"/export/reqif?project={p}", "требования.reqif"),
    ):
        try:
            тело = st.get(путь, сырой=True)
            (АРТЕФАКТЫ / файл).write_bytes(тело)
            ж.факт(f"{имя}: {файл}, {len(тело)} байт")
        except Отказ as e:
            ж.факт(f"{имя}: не выгружен — {e.тело[:160]}")
    # Снимок базирования делается ОДИН раз на состав базированного: он
    # датирован, и повтор клал бы рядом второй такой же с новым временем
    отметка = АРТЕФАКТЫ / "снимок-базирования.txt"
    базированных = sorted(o["id"] for o in объекты(st, "requirement", p)
                          if o["status"] == "Baseline")
    состав = " ".join(базированных)
    if отметка.exists() and отметка.read_text(encoding="utf-8").split("\n")[-1] == состав:
        ж.факт(f"снимок базирования уже сделан на тот же состав "
               f"({len(базированных)} требований) — повтора нет")
    else:
        try:
            снимок = st.post(f"/export/sdoc/baseline?project={p}",
                             {"author": ИСТОЧНИК}, кто=ВЕДУЩИЙ)
            отметка.write_text(
                f"снимок базирования проекта {p}\n"
                f"каталог: {снимок.get('dir', '')}\n"
                f"файлы: {снимок.get('sdoc', '')}, {снимок.get('sgra', '')}\n"
                f"сделал: {снимок.get('author', '')} · {снимок.get('at', '')}\n"
                f"базировано требований: {len(базированных)}\n"
                f"{состав}", encoding="utf-8")
            ж.факт(f"снимок базирования: {str(снимок)[:160]}")
        except Отказ as e:
            ж.факт(f"снимок базирования не сделан — {e.тело[:160]}")
    try:
        пакет_знаний = st.get(f"/views/knowledge-export/bundle.zip?project={p}", сырой=True)
        (АРТЕФАКТЫ / "выгрузка-знаний.zip").write_bytes(пакет_знаний)
        ж.факт(f"выгрузка знаний: выгрузка-знаний.zip, {len(пакет_знаний)} байт")
    except Отказ as e:
        ж.факт(f"выгрузка знаний не собрана — {e.тело[:160]}")




