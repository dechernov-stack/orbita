def шаг_противоречие(st: Стенд, ж: Журнал, p: str) -> None:
    """ADR-045: противоречие держит базирование, пока не разрешено словами.

    Пара берётся живая: «только короткие сообщения» (RQ-P-07) против
    предложения о видеопакетах. Предложение заводится как требование —
    иначе противоречить нечему, — и тут же разрешается решением РП.
    """
    ж.шаг("Противоречие требований и его разрешение (Иванов, ведущий СИ)")
    _КАРТА_ПРОЕКТА.pop(p, None)
    живые = [o for o in объекты(st, "requirement", p) if o["status"] != "Cancelled"]
    док = {o["id"]: st.get(f"/objects/{o['id']}")["doc"] for o in живые}
    коротко = next((i for i, d in док.items()
                    if "код поставки: RQ-P-07" in d.get("tags", [])), None)
    if коротко is None:
        ж.факт("требования «только короткие сообщения» в проекте нет — пары не будет")
        return
    if any(r.get("kind") == "conflicts_with" for r in док[коротко].get("relations", [])):
        ж.факт(f"{коротко}: противоречие уже записано и разрешено")
        return
    видео = next((i for i, d in док.items()
                  if "видеопакет" in (d.get("statement") or "")), None)
    if видео is None:
        гипотеза = dict(ГИПОТЕЗА)
        # нитка названа номером поставки: в проекте он мог быть перебит
        нить = свой(st, p, ГИПОТЕЗА["traces_up"][0]["ref"])
        if нить is None:
            ж.факт("нужды-основания для предложения о видеопакетах в проекте "
                   "нет — гипотеза не заводится")
            return
        гипотеза["traces_up"] = [{"ref": нить}]
        создано = st.post(f"/edit/requirement?project={p}",
                          {"doc": гипотеза, "author": ИСТОЧНИК}, кто=ИНЖЕНЕР)
        видео = создано["id"]
        ж.факт(f"{видео}: заведено предложение о видеопакетах — то, с чем "
               "ограничение коротких сообщений и спорит")
    основание = ("одно требование ограничивает абонентскую линию короткими "
                 "сообщениями (ограничение Р8 и нужда массовой экономики), "
                 "другое требует видеопакетов — на одной линии они несовместимы")
    решение = (f"разрешено {ДАТА_MCR} в пользу коротких сообщений: видеоканал "
               "выведен за границы первой очереди и рассматривается отдельным "
               "решением по фидерной линии (основание — ограничение Р8)")
    for ид, пара in ((коротко, видео), (видео, коротко)):
        текущий = st.get(f"/objects/{ид}")
        связи = list(текущий["doc"].get("relations", []))
        связи.append({"ref": пара, "kind": "conflicts_with",
                      "rationale": основание, "resolution": решение})
        st.patch(f"/edit/{ид}?project={p}",
                 {"changes": {"relations": связи},
                  "base_version": текущий["version"], "author": ИСТОЧНИК},
                 кто=ВЕДУЩИЙ)
    ж.факт(f"{коротко} ↔ {видео}: две связи conflicts_with с обоснованием, "
           "противоречие разрешено словами — ворота оно не держит")


def следующий(st: Стенд, треб: dict, слово: str) -> str | None:
    for ид, о in sorted(треб.items()):
        if слово.lower() in (о.get("title") or "").lower():
            return ид
    return None


def шаг_анкеты(st: Стенд, ж: Журнал, p: str) -> None:
    """Ф-06: параметры узлов — те самые входы, которыми считают модели."""
    ж.шаг("Состав: параметры узлов (Петрова, инженер)")
    узлы = {}
    for о in объекты(st, "component", p):
        d = st.get(f"/objects/{о['id']}")["doc"]
        узлы[d.get("code", "")] = (о["id"], d)
    заполнено, пропущено = 0, []
    for код, значения in ЗНАЧЕНИЯ.items():
        если = узлы.get(код)
        if не_узел(если, код, ж):
            continue
        ид, d = если
        ждут = {e["key"]: e for e in d.get("expects", [])}
        for ключ, (величина, почему) in значения.items():
            if ключ not in ждут:
                пропущено.append(f"{код}.{ключ}")
                continue
            st.вызов("POST", f"/objects/{ид}/params/{ключ}?project={p}", {
                "value": величина, "unit": ждут[ключ].get("unit", "") or "1",
                "provenance": происхождение(почему),
                "formula": f"демо-значение примера: {почему}",
            }, кто=ИНЖЕНЕР)
            заполнено += 1
        for ключ, (низ, верх, почему) in ДИАПАЗОНЫ.get(код, {}).items():
            if ключ not in ждут:
                continue
            st.вызов("POST", f"/objects/{ид}/params/{ключ}?project={p}", {
                "value": (низ + верх) / 2, "unit": ждут[ключ].get("unit", ""),
                "provenance": происхождение(почему),
                "formula": f"середина диапазона {низ:g}–{верх:g} "
                           f"{ждут[ключ].get('unit', '')} ({почему})",
            }, кто=ИНЖЕНЕР)
            заполнено += 1
    ж.факт(f"параметров заполнено: {заполнено}")
    if пропущено:
        ж.факт(f"ключей таблицы, которых узел не спрашивает: {len(пропущено)} — "
               + ", ".join(пропущено[:6]))
    for t in TBR:
        если = узлы.get(t["node"])
        if not если:
            continue
        ид, d = если
        ждут = {e["key"] for e in d.get("expects", [])}
        if t["key"] not in ждут:
            continue
        единица = next(e.get("unit", "") for e in d.get("expects", [])
                       if e["key"] == t["key"])
        st.вызов("POST", f"/objects/{ид}/params/{t['key']}?project={p}", {
            "unit": единица or "1",
            "provenance": {"source": "manual", "author": ИСТОЧНИК},
            "formula": f"TBR: {t['why']}; владелец — {t['owner']}, "
                       f"срок — точка {t['due']}",
        }, кто=ИНЖЕНЕР)
        ж.факт(f"TBR {t['node']}.{t['key']} — владелец {t['owner']}, точка {t['due']}")


