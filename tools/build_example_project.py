    ж.факт("не берётся из урожая намеренно: цели, нужды и сервисы (их даёт связная "
           "пара Р02/Р03), ограничения (Р8/Р9 названы заданием на Ш1), "
           "риски/вопросы/находки (класс вне раскладки — адрес назначает инженер)")


