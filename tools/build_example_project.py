def код_поставки(элемент: dict) -> str:
    for t in элемент.get("tags", []) or []:
        if t.startswith("код поставки: "):
            return t.split(": ", 1)[1]
    return элемент.get("id", "")


def отпечаток(doc: dict) -> str:
    """След строки пакета в проекте: код поставки, а где его нет —
    формулировка. Без него повтор пакета удваивал бы реестр (риски кодов
    поставки не несут — поймано на живом прогоне примера)."""
    код = код_поставки(doc)
    свой = (doc.get("statement") or doc.get("name") or "").strip()[:120]
    return код if код and not код.startswith(("RSK-", "ND-", "SV-", "MG-")) else свой or код


def следы_в_проекте(st: Стенд, p: str, тип: str) -> set[str]:
    """Следы строк, уже осевших в проекте: повтор пакета их не трогает."""
    следы = set()
    for o in объекты(st, тип, p):
        if o["status"] == "Cancelled":
            continue
        следы.add(отпечаток(st.get(f"/objects/{o['id']}")["doc"]))
    return следы


def вставить(st: Стенд, ж: Журнал, p: str, файл: str, кто: str, тип: str,
             отсев: set[str] = frozenset()) -> int:
    """Пакет → правки инженера → предложения → акцепт. Повтор не дублирует."""
    данные = пакет(файл)
    _КАРТА_ПРОЕКТА.pop(p, None)
    карта = карта_номеров(st, p)
    было = следы_в_проекте(st, p, тип)
    элементы, пропущено, правок = [], 0, []
    for it in данные.get("items", []):
        код = код_поставки(it)
        if код in отсев:
            continue
        if отпечаток(it) in было:
            пропущено += 1
            continue
        общая = ПРАВКИ_ВСЕХ.get(файл)
        if общая:
            общая[1](it)
        правка = ПРАВКИ.get(файл, {}).get(код)
        if правка:
            почему, применить = правка
            применить(it)
            for нить in it.get("traces_up", []):
                свой_ref = карта.get(нить.get("ref", ""))
                if свой_ref:
                    нить["ref"] = свой_ref
            правок.append(f"{код}: {почему}")
        элементы.append(it)
    if not элементы:
        ж.факт(f"{файл}: всё уже в проекте ({пропущено} строк) — повтор ничего не создал")
        return 0
    данные["items"] = элементы
    if ПРАВКИ_ВСЕХ.get(файл):
        ж.факт(f"{файл}: правка инженера во всех строках — {ПРАВКИ_ВСЕХ[файл][0]}")
    for стр in правок:
        ж.факт(f"{файл}: правка инженера — {стр}")

    отчёт = st.post(f"/ai/packet?project={p}",
                    {"raw": json.dumps(данные, ensure_ascii=False),
                     "author": ИСТОЧНИК}, кто=кто)
    показано = [s["item"] for s in отчёт.get("shown", [])]
    доработка = отчёт.get("rework", {}).get("rework", [])
    сломано = отчёт.get("malformed", [])
    if not показано:
        ж.факт(f"{файл}: предложено {отчёт.get('proposed')} — чистых нет "
               f"(доработка {len(доработка)}, отсев по форме {len(сломано)})")
        for стр in доработка[:4] + сломано[:4]:
            ид = стр.get("item", {}).get("id", "?")
            ж.факт(f"    {ид}: " + "; ".join(стр.get("issues", стр.get("errors", [])))[:150])
        return 0

    # Г-01: чужие ссылки инженер сопоставляет ЯВНО — служба предлагает по
    # смыслу, подтверждает человек; без пары связь не ставится
    карта, без_пары = {}, []
    _КАРТА_ПРОЕКТА.pop(p, None)          # карта могла устареть после акцепта
    карта_п = карта_номеров(st, p)
    решение = dict(ПЕРЕБИТЫЕ)
    for старый, целевой in СОПОСТАВЛЕНИЕ.get(файл, {}).items():
        # цель названа НОМЕРОМ ПОСТАВКИ: в проекте он мог быть перебит
        решение[старый] = карта_п.get(целевой, целевой)
    разбор = st.post(f"/views/link-mapping?project={p}", {"items": показано}, кто=кто)
    for л in разбор.get("links", []):
        если = л.get("suggested")
        if л["ref"] in решение:
            карта[л["ref"]] = решение[л["ref"]]
        elif если:
            карта[л["ref"]] = если["id"]
        else:
            без_пары.append(л["ref"])
    if карта:
        ж.факт(f"{файл}: чужих ссылок {разбор.get('foreign')} — сопоставлено "
               + ", ".join(f"{a}→{b}" for a, b in list(карта.items())[:6]))
    if без_пары:
        ж.факт(f"{файл}: без пары остались {len(без_пары)} ссылок — "
               + ", ".join(без_пары[:5]))

    итог = st.post(f"/ai/accept-batch?project={p}",
                   {"items": показано, "package_id": файл,
                    "llm": отчёт.get("model", "пакет"), "call": отчёт.get("call"),
                    "link_mapping": карта, "author": ИСТОЧНИК}, кто=кто)
    for пара in итог.get("remapped", []):
        ПЕРЕБИТЫЕ[пара["from"]] = пара["to"]
    записано = итог.get("written", len(показано))
    ж.факт(f"{файл}: предложено {отчёт.get('proposed')} · записано {записано} · "
           f"в доработку {len(доработка)} · отсев по форме {len(сломано)}"
           + (f" · уже было {пропущено}" if пропущено else "")
           + (f" · ловушек задания не вставлялось {len(отсев)}" if отсев else ""))
    for стр in доработка[:5]:
        ид = код_поставки(стр.get("item", {})) or "?"
        ж.факт(f"    доработка {ид}: " + "; ".join(стр.get("issues", []))[:150])
    for стр in сломано[:5]:
        ид = код_поставки(стр.get("item", {})) or "?"
        ж.факт(f"    отсев {ид}: " + "; ".join(стр.get("errors", []))[:150])
    return записано


def шаг_постановка(st: Стенд, ж: Журнал, p: str) -> None:
    """О2–О3: цели, нужды, сервисы — связными пакетами владельца."""
    ж.шаг("Постановка: цели, нужды, сервисы (Петрова, инженер)")
