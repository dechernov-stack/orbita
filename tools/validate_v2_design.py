#!/usr/bin/env python3
"""Сторож дизайна v2 (ДИЗАЙН-ПРИНЦИПЫ-V2) — правила проверяются, а не
объявляются.

Приёмка дизайна требует обхода экрана, где каждый элемент называется по
вопросу теста действия. Обход руками делается один раз; чтобы правило
жило дальше, проверяемая его часть вынесена сюда:

  1. Три размера шрифта и ни одного между ними (§5): 15 · 14 · 12.
     В коде — только через токены либо этими числами.
  2. Один цвет акцента (§5): второй копии акцента в исходниках нет —
     цвет приходит токеном, а не шестнадцатеричным литералом.
  3. Тест действия (§1): у каждого блока экрана мероприятия И у каждой
     панели любого экрана v2 стоит `data-why` из трёх допустимых
     ответов. Блок без ответа — брак: элемент, который не может назвать,
     зачем он на экране, на экране не нужен.
  4. Запрет третьей колонки на экране инженера (§4): развёрнутая рейка
     ложится поверх поверхности, а не рядом с ней.

Состав экрана по ролям проверяется тестом `web/src/v2/density.test.ts`:
это решение, а не разметка, и его место — в тестах.

    python3 tools/validate_v2_design.py
"""
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
V2 = КОРЕНЬ / "web/src/v2"
ТОКЕНЫ = V2 / "tokens.css"
МЕРОПРИЯТИЕ = V2 / "activity.tsx"

РАЗРЕШЁННЫЕ_РАЗМЕРЫ = {"12", "14", "15"}
ОТВЕТЫ = {"работа", "почему-нельзя", "следующий-клик"}


def размеры(беды: list[str]) -> None:
    """§5: три размера. Числа берутся из CSS и инлайновых стилей схем."""
    for файл in sorted(V2.glob("*.css")) + sorted(V2.glob("*.tsx")):
        текст = файл.read_text(encoding="utf-8")
        for м in re.finditer(r"font-size:\s*([0-9]+)px", текст):
            if м.group(1) not in РАЗРЕШЁННЫЕ_РАЗМЕРЫ:
                беды.append(f"{файл.name}: размер {м.group(1)}px вне трёх "
                            f"({', '.join(sorted(РАЗРЕШЁННЫЕ_РАЗМЕРЫ))})")
        for м in re.finditer(r"fontSize:\s*([0-9]+)", текст):
            if м.group(1) not in РАЗРЕШЁННЫЕ_РАЗМЕРЫ:
                беды.append(f"{файл.name}: fontSize {м.group(1)} вне трёх")


def акцент(беды: list[str]) -> None:
    """§5: один цвет акцента. Литерал цвета живёт только в токенах."""
    for файл in sorted(V2.glob("*.tsx")) + sorted(V2.glob("*.ts")):
        текст = файл.read_text(encoding="utf-8")
        for м in re.finditer(r"#[0-9a-fA-F]{3,8}\b", текст):
            беды.append(f"{файл.name}: цвет литералом «{м.group(0)}» — "
                        "цвет приходит токеном (--accent, --line, --ink…)")


def панели(беды: list[str]) -> list[str]:
    """
    §1 на ВСЕХ экранах: панель — верхний ярус любого экрана v2, и она
    обязана назвать, зачем она там.

    Раньше тест действия стерёгся только на эталонном экране мероприятия,
    а новые экраны заводились без него — правило жило на одном экране, а
    объявлено было для всех.
    """
    проверено: list[str] = []
    for файл in sorted(V2.glob("*.tsx")):
        текст = файл.read_text(encoding="utf-8")
        if 'className="v2-panel"' not in текст:
            continue
        проверено.append(файл.name)
        for строка in текст.splitlines():
            if 'className="v2-panel"' in строка and "data-why" not in строка:
                беды.append(f"{файл.name}: панель без data-why — "
                            f"«{строка.strip()[:60]}»")
    return проверено


def тест_действия(беды: list[str]) -> None:
    """§1: каждый блок экрана мероприятия называет, зачем он там."""
    if not МЕРОПРИЯТИЕ.exists():
        беды.append("нет web/src/v2/activity.tsx — экрана мероприятия не найдено")
        return
    # Литеральный ответ обязан быть одним из трёх; вычисляемый — приходить
    # из состава экрана (поле `зачем`), а не из произвольного выражения.
    # Правило общее: ответ вне трёх вопросов — брак на любом экране.
    for файл in sorted(V2.glob("*.tsx")):
        свой = файл.read_text(encoding="utf-8")
        for м in re.finditer(r'data-why="([^"]*)"', свой):
            if м.group(1) not in ОТВЕТЫ:
                беды.append(f"{файл.name}: ответ «{м.group(1)}» вне трёх вопросов "
                            "теста действия")
        for м in re.finditer(r"data-why=\{([^}]*)\}", свой):
            if "зачем" not in м.group(1):
                беды.append(f"{файл.name}: ответ «{м.group(1).strip()}» не из состава "
                            "экрана: тест действия проверяется, а не подразумевается")
    текст = МЕРОПРИЯТИЕ.read_text(encoding="utf-8")
    # Блоки состава обязаны нести атрибут: считаем по классам верхнего яруса
    for класс in ("v2-act2__ctx", "v2-act2__surface", "v2-act2__foot"):
        куски = re.findall(rf"className=[^\n]*{класс}[^\n]*(?:\n[^\n]*){{0,3}}", текст)
        if not куски:
            беды.append(f"activity.tsx: блока .{класс} нет — состав экрана неполон")
            continue
        if not any("data-why" in к for к in куски):
            беды.append(f"activity.tsx: блок .{класс} без data-why — "
                        "элемент не назвал, зачем он на экране")
    # Пункты рейки несут ответ из состава: пункт без данных туда не выходит
    if "data-why={п.зачем}" not in текст:
        беды.append("activity.tsx: пункты рейки без data-why — рейка обязана "
                    "называть, зачем каждый счётчик на экране")


def третья_колонка(беды: list[str]) -> None:
    """§4: у инженера максимум поверхность + узкая рейка."""
    текст = ТОКЕНЫ.read_text(encoding="utf-8")
    for м in re.finditer(r"\.v2-act2\s*\{[^}]*grid-template-columns:\s*([^;]+);", текст):
        дорожек = len(м.group(1).split())
        if дорожек > 2:
            беды.append(f"tokens.css: экран мероприятия в {дорожек} колонки — "
                        "разрешены поверхность и рейка")
    работа = (V2 / "work.tsx").read_text(encoding="utf-8")
    if "v2-two-cols" in работа:
        беды.append("work.tsx: две колонки ленты и рамки — лента ушла в режим фазы")


def main() -> int:
    беды: list[str] = []
    размеры(беды)
    акцент(беды)
    экраны = панели(беды)
    тест_действия(беды)
    третья_колонка(беды)
    if беды:
        print("дизайн v2 нарушен:", file=sys.stderr)
        for б in беды:
            print(f"  · {б}", file=sys.stderr)
        return 1
    # Счёт — по экранам, на которых правило ПРОВЕРЕНО, а не по числу
    # файлов в каталоге: иначе отчёт хвалится тем, чего не смотрел.
    print(f"дизайн v2: три размера, один акцент, состав экрана назван "
          f"(панели названы на {len(экраны)} экранах: {', '.join(экраны)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
