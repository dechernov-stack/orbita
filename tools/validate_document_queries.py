#!/usr/bin/env python3
"""Сторож «печать просит поле, которое есть у вида».

Владелец 21.09 показал §3 FAD: одиннадцать строк ограничений, и в каждой
«Ограничение — —» и «Категория — —». Причина не в данных: запрос документа
просил поля `text` и `category`, а у вида `constraint` по истине схем поля
зовутся `statement` и `type`. Пустая колонка не кричит — она просто печатает
прочерк, и документ уходит на точку пустым.

Проверяется: у каждого запроса шаблона документа (`kind: query`) вид из
`select` существует в истине схем, а поля колонок, отбора (`where`) и разворота
(`expand`) — это поля ЭТОГО вида, путь внутрь его поля либо одно из служебных
имён, которые печать считает сама.

Самопроверка: выдуманное поле ловится.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ШАБЛОНЫ = КОРЕНЬ / "docs/tz/v2/полки-порождённые"
ИСТИНА = КОРЕНЬ / "docs/tz/v2/СХЕМЫ-ПОЛЕЙ-V2.yaml"

# Имена, которые печать считает сама, а не берёт из документа сущности.
СЛУЖЕБНЫЕ = {"code", "status", "level_max", "unresolved", "code_prefix",
             "criticality_min", "carrier_kind", "target_kind"}

# Названный долг — освобождение запроса поимённо, пока истина и полка не сошлись.
# Пусто: каталог процессов (единственный долг, 21.09) приведён к истине 22.09 —
# полка хранит каталог записями, одна на процесс. Долг закрылся — снят.
ДОЛГ: set[tuple[str, str]] = set()   # каталог процессов приведён к истине 22.09: запись = процесс


def подполя(тип: str) -> set[str]:
    """Имена полей ВНУТРИ структуры поля: «[{gate*,date*}]» → gate, date."""
    т = (тип or "").strip()
    м = (re.match(r"^\[\{(.+)\}\]\s*(?:≥\s*\d+)?\s*(?:\(.*\))?$", т)
         or re.match(r"^[a-z_]+\{(.+)\}$", т)
         or re.match(r"^\{(.+)\}$", т))
    if not м:
        return set()
    найдено = set()
    глубина = 0
    кусок = ""
    for символ in м.group(1) + ",":
        if символ in "{[(":
            глубина += 1
        elif символ in "}])":
            глубина -= 1
        if символ == "," and глубина == 0:
            # «unit*=млн ₽» — имя поля с умолчанием: умолчание в имя не входит.
            # «usage*→component_usage(КА)» — имя до стрелки: стрелка значит ссылку.
            имя = кусок.split(":")[0].split("=")[0].split("→")[0].strip().rstrip("*?")
            if имя:
                найдено.add(имя)
            кусок = ""
        else:
            кусок += символ
    return найдено


def виды_истины() -> tuple[dict[str, set[str]], dict[str, dict[str, str]]]:
    """Вид → его поля (с ядром) и вид → поле → тип: для разворота и путей."""
    sys.path.insert(0, str(КОРЕНЬ / "tools/v2"))
    import yaml  # noqa: PLC0415 — зависимость только у генераторов
    from gen_schemas import развернуть_группы  # noqa: PLC0415

    истина = yaml.safe_load(ИСТИНА.read_text(encoding="utf-8"))
    ядро = {f["name"] for f in истина.get("core_fields", [])}
    виды: dict[str, set[str]] = {}
    типы: dict[str, dict[str, str]] = {}
    for вид in развернуть_группы(истина["kinds"]):
        поля = {f["name"] for f in (вид.get("fields") or [])}
        виды[вид["code"]] = поля | ядро | СЛУЖЕБНЫЕ
        типы[вид["code"]] = {f["name"]: (f.get("type") or "") for f in (вид.get("fields") or [])}
    return виды, типы


def запросы(шаблон: dict) -> list[tuple[str, str, dict]]:
    """Все запросы шаблона: (документ, раздел, элемент)."""
    найдено = []
    док = шаблон.get("code", шаблон.get("doc", "?"))
    for раздел in шаблон.get("sections", []) or []:
        for элемент in раздел.get("elements", []) or []:
            if элемент.get("kind") == "query":
                найдено.append((док, раздел.get("no", "?"), элемент))
    return найдено


def беды_шаблона(
    файл: pathlib.Path,
    виды: dict[str, set[str]],
    типы: dict[str, dict[str, str]],
) -> list[str]:
    шаблон = json.loads(файл.read_text(encoding="utf-8"))
    беды: list[str] = []
    for док, раздел, элемент in запросы(шаблон):
        вид = элемент.get("select", "")
        поля = виды.get(вид)
        if поля is None:
            беды.append(f"{док} {раздел}: вида «{вид}» в истине схем нет")
            continue
        разворот = элемент.get("expand")
        if (док, раздел) in ДОЛГ:
            continue
        if разворот:
            # Разворот: строка — элемент СПИСКА, и колонки адресуют его поля.
            if разворот not in поля:
                беды.append(f"{док} {раздел}: у вида «{вид}» нет поля разворота «{разворот}»")
                continue
            свои = подполя(типы.get(вид, {}).get(разворот, ""))
            где = f"внутри «{вид}.{разворот}»"
        else:
            свои = поля
            где = f"у вида «{вид}»"
        спрошены = [к.get("field", "") for к in элемент.get("columns", []) or []]
        спрошены += [] if разворот else list((элемент.get("where") or {}).keys())
        for поле in спрошены:
            if not поле or поле.startswith("link:"):
                continue
            части = поле.split(".")
            корень = части[0]
            if корень not in свои and корень not in СЛУЖЕБНЫЕ:
                известно = ", ".join(sorted(п for п in свои if п not in СЛУЖЕБНЫЕ))
                беды.append(f"{док} {раздел}: {где} нет поля «{корень}» (истина знает: {известно[:110]})")
                continue
            # Путь внутрь структуры: «range.min» — min обязан быть в типе range.
            if len(части) > 1 and not разворот:
                внутри = подполя(типы.get(вид, {}).get(корень, ""))
                if внутри and части[1] not in внутри:
                    беды.append(
                        f"{док} {раздел}: у «{вид}.{корень}» нет поля «{части[1]}» "
                        f"(истина знает: {', '.join(sorted(внутри))})"
                    )
    return беды


def беды_шаблона_без_долга(
    адрес: tuple[str, str],
    виды: dict[str, set[str]],
    типы: dict[str, dict[str, str]],
) -> list[str]:
    """Беды ОДНОГО освобождённого раздела: долг, который закрылся, — снимают."""
    док, раздел = адрес
    файл = ШАБЛОНЫ / f"ШАБЛОН-{док.upper()}.json"
    if not файл.exists():
        return [f"{док}: шаблона нет"]
    глобальный = ДОЛГ.copy()
    ДОЛГ.clear()
    try:
        return [б for б in беды_шаблона(файл, виды, типы) if б.startswith(f"{док} {раздел}:")]
    finally:
        ДОЛГ.update(глобальный)


def main() -> int:
    виды, типы = виды_истины()
    беды: list[str] = []
    for файл in sorted(ШАБЛОНЫ.glob("ШАБЛОН-*.json")):
        беды += беды_шаблона(файл, виды, типы)
    if беды:
        print("печать просит поле, которого у вида нет (колонка напечатает прочерк):")
        for б in беды:
            print("  ", б)
        print("   поправьте tools/v2/gen_document_templates.py и перегенерируйте шаблоны")
        return 1
    assert подполя("[{gate*,date*}]") == {"gate", "date"}, "самопроверка: разворот не разобран"
    assert подполя("{min*,max*,unit*}") == {"min", "max", "unit"}, "самопроверка: структура не разобрана"
    assert "выдумка" not in виды.get("constraint", set()), "самопроверка: выдуманное поле считается своим"
    лишние = {д for д in ДОЛГ if not беды_шаблона_без_долга(д, виды, типы)}
    assert not лишние, f"долг закрылся сам — снимите освобождение: {sorted(лишние)}"
    запросов = sum(len(запросы(json.loads(ф.read_text(encoding="utf-8"))))
                   for ф in ШАБЛОНЫ.glob("ШАБЛОН-*.json"))
    долг = ', '.join(f'{д} {р}' for д, р in sorted(ДОЛГ)) or 'нет'
    print(f"запросы печати: {запросов} — поля есть у своих видов; названный долг: {долг}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
