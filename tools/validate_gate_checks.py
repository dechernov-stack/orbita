#!/usr/bin/env python3
"""Сторож критериев готовности: у каждого — тест НА ОТКАЗ.

Правило владельца 08.09, после двух дефектов одного класса: «проверка,
которая молча проходит». Срок хранился идентификатором, а условие искало
по коду — ни один срок не находился, и точка объявляла себя готовой,
ничего не проверив. Порог «Б1: увод не более 5 лет» читался как число 1 из
обозначения норматива. Оба поймались живьём, а не тестами: тесты
проверяли, что критерий ПРОПУСКАЕТ, и молчали о том, что он не умеет
держать.

Правило: критерий, у которого нет теста с фикстурой «обязан вернуть
не выполнено», не регистрируется. Пустой результат проверки ≠ «выполнено».

Ищутся:
  · критерии — ветками `"имя" ->` в оценщике и в модулях `*Checks.kt`;
  · тест на отказ — по ПРИЧИНЕ отказа: из ветки критерия берутся слова его
    сообщения `CheckResult.no("…")`, и хотя бы одно устойчивое сочетание
    обязано встретиться в тестах ядра v2. Искать по имени критерия
    нельзя: тесты ходят через маршрут фазы и проверяют человеческую
    формулировку помехи, а не служебный ключ.

    python3 tools/validate_gate_checks.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ЯДРО = КОРЕНЬ / "core/v2"

# Критерии оценщика, у которых отрицательная ветка — часть самого движка,
# а не предметное правило: их держат тесты процесса, не предметные.
СЛУЖЕБНЫЕ = {"scene_done", "gate_passed", "accepted"}

ОТРИЦАНИЕ = re.compile(
    r"assertFalse|!\s*\w*\.?passed|CheckResult\.no|не выполнен|держит|отказ|"
    r"разрыв|не закрыт|блокир|ещё не|без пары|не назван|не найден",
    re.IGNORECASE,
)


def критерии() -> dict[str, Path]:
    """Имя критерия → файл, где он объявлен."""
    найдено: dict[str, Path] = {}
    for файл in sorted(ЯДРО.rglob("*.kt")):
        if "/src/test/" in str(файл) or "/build/" in str(файл):
            continue
        if not (файл.name.endswith("Checks.kt") or файл.name == "DomainGateEvaluator.kt"):
            continue
        текст = файл.read_text(encoding="utf-8")
        for м in re.finditer(r'^\s*"([a-z_]+)"\s*->', текст, re.M):
            найдено.setdefault(м.group(1), файл)
    return найдено


# Две формы отказа: CheckResult.no("…") в модулях и голая строка в
# оценщике (там null — «выполнено», строка — причина).
ПРИЧИНА = re.compile(
    r'CheckResult\.no\(\s*\n?\s*"([^"]{12,})"'
    r'|else\s*->?\s*\n?\s*"([^"]{12,})"',
    re.S,
)


def причины(текст: str, имя: str) -> list[str]:
    """Сообщения отказа из ветки критерия «имя»."""
    начало = re.search(rf'^\s*"{re.escape(имя)}"\s*->', текст, re.M)
    if not начало:
        return []
    хвост = текст[начало.end():]
    следующая = re.search(r'^\s{12}"[a-z_]+"\s*->|^\s*else\s*->', хвост, re.M)
    ветка = хвост[: следующая.start()] if следующая else хвост
    return [м.group(1) or м.group(2) for м in ПРИЧИНА.finditer(ветка)]


def опора(сообщение: str) -> str:
    """
    Устойчивый кусок причины: первые слова до подстановки.

    Сообщения несут числа и коды («узлов ${…} из $нужно»), и искать их
    целиком бессмысленно — ищется начало фразы, которое в тесте видно.
    """
    кусок = сообщение.split("$")[0].strip(" :,—-")
    return кусок[:40]


def тесты() -> list[tuple[Path, str]]:
    собрано = []
    for файл in sorted(ЯДРО.rglob("*.kt")):
        if "/src/test/" not in str(файл) or "/build/" in str(файл):
            continue
        собрано.append((файл, файл.read_text(encoding="utf-8")))
    return собрано


def проверен_на_отказ(имя: str, опоры: list[str], тексты: list[tuple[Path, str]]) -> bool:
    """
    Отказ критерия виден в тестах: либо по имени рядом с отрицанием, либо
    по формулировке причины — её тест и проверяет.
    """
    for _, текст in тексты:
        for м in re.finditer(re.escape(имя), текст):
            окно = текст[max(0, м.start() - 700): м.end() + 700]
            if ОТРИЦАНИЕ.search(окно):
                return True
        for кусок in опоры:
            if len(кусок) >= 12 and кусок in текст:
                return True
    return False


def main() -> int:
    объявлены = критерии()
    if not объявлены:
        print("критериев не найдено — сторож ослеп", file=sys.stderr)
        return 1
    тексты = тесты()
    без: list[str] = []
    for имя, файл in sorted(объявлены.items()):
        if имя in СЛУЖЕБНЫЕ:
            continue
        опоры = [опора(с) for с in причины(файл.read_text(encoding="utf-8"), имя)]
        if not проверен_на_отказ(имя, опоры, тексты):
            подсказка = f" (причина: «{опоры[0]}…»)" if опоры else " (у критерия нет сообщения отказа)"
            без.append(
                f"{имя} ({файл.relative_to(КОРЕНЬ)}): нет теста, где критерий ОБЯЗАН отказать{подсказка}",
            )
    if без:
        print("критерии готовности без теста на отказ:", file=sys.stderr)
        for б in без:
            print("  · " + б, file=sys.stderr)
        print("  пустой результат проверки ≠ «выполнено»: критерий, который "
              "никогда не держал, однажды пропустит всё", file=sys.stderr)
        return 1
    print(f"критерии готовности: {len(объявлены) - len(СЛУЖЕБНЫЕ)} предметных, "
          f"у каждого есть тест на отказ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
