# Роли стороны — перечень истины схем (`stakeholder.role`). Русские слова здесь
# ровно те, которыми истина онтологии называет эти же роли в правиле покрытия
# (`need.coverage_expected`): перевод перечня, а не правило. Роль, которой в
# правиле не названо, обрывает генерацию — молча остаться без покрытия она не может.
РОЛИ_СТОРОНЫ = {
    "заказчик": "customer",
    "регулятор": "regulator",
    "оператор": "operator",
    "потребитель": "consumer",
    "поставщик": "supplier",
    "партнёр": "partner",
    "учреждаемый": "established",
}

# Чем нужда закрывается — перечень из той же строки истины.
ВИДЫ_ПОКРЫТИЯ = ("service", "constraint", "programme", "requirement")


def карта_покрытия(истина: dict) -> dict:
    """Роль носителя → чем закрывается его нужда, из `need.coverage_expected`.

    Истина: «по умолчанию из роли носителя (заказчик/оператор/потребитель/
    учреждаемый → service; регулятор → constraint; поставщик/партнёр →
    programme); инженер правит». Разбирается здесь, чтобы в коде не было
    второй копии правила: выход сцены 6 считает только нужды с `service`.
    """
    текст = str((((истина.get("concepts") or {}).get("need") or {}).get("fields") or {}).get("coverage_expected", ""))
    if not текст.strip():
        raise Отказ("need.coverage_expected: правила покрытия в истине нет — выход сцены 6 считать нечем")
    внутри = текст[текст.find("(") + 1:текст.rfind(")")] if "(" in текст and ")" in текст else ""
    if not внутри.strip():
        raise Отказ(f"need.coverage_expected: карта «роли → вид покрытия» не найдена в «{текст[:80]}»")
    карта_ролей: dict = {}
    for часть in внутри.split(";"):
        if "→" not in часть:
            continue
        роли, вид = (часть.split("→", 1)[0], часть.split("→", 1)[1].strip())
        if вид not in ВИДЫ_ПОКРЫТИЯ:
            raise Отказ(f"need.coverage_expected: вид покрытия «{вид}» вне перечня {list(ВИДЫ_ПОКРЫТИЯ)}")
        for слово in роли.replace("·", "/").split("/"):
            имя = слово.strip()
            if not имя:
                continue
            код = РОЛИ_СТОРОНЫ.get(имя)
            if код is None:
                raise Отказ(f"need.coverage_expected: роль «{имя}» не из перечня истины схем {sorted(РОЛИ_СТОРОНЫ)}")
            карта_ролей[код] = вид
    нет = [р for р in РОЛИ_СТОРОНЫ.values() if р not in карта_ролей]
    if нет:
        raise Отказ(f"need.coverage_expected: роль {sorted(нет)} без вида покрытия — сцена 6 её нужды не посчитает")
    return карта_ролей


class Отказ(Exception):
    """Истина онтологии не разобрана — генерация не состоялась."""


def голова_роли(роль) -> str:
    """Роль без условия: «charter (только при явном разделе …)» → charter.

    Условие в скобках — законная часть истины (17.09: требования из устава
    читаются только при явном разделе), но перечень ролей закрыт, и сверяется
    с ним сама роль. Условие уезжает в Kotlin отдельным полем словами.
    """
    return str(роль).split("(", 1)[0].strip()


def условие_роли(роль) -> str:
    текст = str(роль)
    return текст[текст.find("(") + 1:].rstrip(")").strip() if "(" in текст else ""


def строка(значение) -> str:
    """Значение YAML → строковый литерал Kotlin."""
    текст = "" if значение is None else str(значение)
    экранированное = (
        текст.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("$", "\\$")
        .replace("\n", "\\n")
    )
    return f'"{экранированное}"'


def список(значения) -> str:
    if not значения:
        return "emptyList()"
    return "listOf(" + ", ".join(строка(x) for x in значения) + ")"


def карта(пары: dict, отступ: str) -> str:
    if not пары:
        return "emptyMap()"
    строки = ["mapOf("]
    for ключ, значение in пары.items():
        строки.append(f"{отступ}    {строка(ключ)} to {строка(значение)},")
    строки.append(f"{отступ})")
    return "\n".join(строки)


def правило_отбора(правило: dict, понятие: str) -> str:
    неизвестные = [к for к in правило if к not in dict(ПОРЯДОК_ОТБОРА)]
    if неизвестные:
        raise Отказ(
            f"понятие «{понятие}»: отбор фактов описан ключом {sorted(неизвестные)}, "
            "которого генератор не знает — допишите его в ПОРЯДОК_ОТБОРА и в FactRule"
        )
    части = []
    for ключ, имя in ПОРЯДОК_ОТБОРА:
        if ключ not in правило:
            continue
        значение = правило[ключ]
        если_список = ключ in СПИСОЧНЫЕ_ОТБОРА
        части.append(f"{имя} = " + (список(значение) if если_список else строка(значение)))
    return "FactRule(" + ", ".join(части) + ")"


def проверить(истина: dict) -> None:
    """Отказ вместо тихого пропуска: разобранное обязано быть полным."""
    неизвестные_разделы = [к for к in истина if к not in ИЗВЕСТНЫЕ_РАЗДЕЛЫ]
    if неизвестные_разделы:
        raise Отказ(
            f"раздел {sorted(неизвестные_разделы)} генератору неизвестен — "
            "в Kotlin он не попадёт; допишите перенос раздела"
        )
    ранги = истина.get("authority_ranks") or {}
    неизвестные = [р for р in ранги if р not in РАНГИ]
    if неизвестные:
        raise Отказ(f"ранг доверия {sorted(неизвестные)} вне перечня {list(РАНГИ)}")
    пропущенные = [р for р in РАНГИ if р not in ранги]
    if пропущенные:
        raise Отказ(f"ранг доверия {пропущенные} не описан в онтологии")

    понятия = истина.get("concepts") or {}
    if not понятия:
        raise Отказ("в онтологии нет ни одного понятия — формировать нечего")
    for код, понятие in понятия.items():
        лишние = [к for к in понятие if к not in ИЗВЕСТНЫЕ_КЛЮЧИ]
        if лишние:
            raise Отказ(f"понятие «{код}» описано ключом {sorted(лишние)} вне перечня")
        нет = [к for к in ОБЯЗАТЕЛЬНЫЕ_КЛЮЧИ if к not in понятие]
        if нет:
            raise Отказ(
                f"понятие «{код}» не объявило {нет}; пустой перечень пишется явно «[]» — "
                "умолчания здесь нет, иначе правило потеряется молча"
            )
        опознание = понятие.get("identity")
        if опознание:
            for ключ in ("key", "semantic", "threshold"):
                if ключ not in опознание:
                    raise Отказ(f"понятие «{код}»: в identity нет «{ключ}» — узнать дубль нечем")
            if not опознание["key"]:
                raise Отказ(f"понятие «{код}»: identity.key пуст — ключ дубля не назван")
            порог = float(опознание["threshold"])
            if not 0 < порог <= 1:
                raise Отказ(f"понятие «{код}»: порог близости {порог} вне (0, 1]")
        # Роль документа — перечень закрытый и общий с истиной схем: роль вне
        # его материалу проставить нельзя, а значит правило с ней не сработает
        # никогда — молча и навсегда.
        чужие = [р for р in (понятие.get("allowed_roles") or []) if голова_роли(р) not in РОЛИ_ДОКУМЕНТОВ]
        if чужие:
            raise Отказ(
                f"понятие «{код}»: allowed_roles называет {sorted(чужие)} вне перечня "
                f"{list(РОЛИ_ДОКУМЕНТОВ)} — такой роли у материала не бывает"
            )
        общие = set(понятие.get("computed_fields") or {}) & set(понятие.get("fields") or {})
        if общие:
            raise Отказ(
                f"понятие «{код}»: поле {sorted(общие)} названо и в fields, и в "
                "computed_fields — либо его заполняет модель, либо считает система"
            )

    # Перечни ролей и влияний живут в истине СХЕМ, а её этот генератор не
    # читает: совпадение перечней стережёт тест онтологии. Здесь — только
    # форма: у каждой названной роли влияние названо.
    пустые = [р for р, з in (истина.get("influence_map") or {}).items() if not str(з).strip()]
    if пустые:
        raise Отказ(f"influence_map: у роли {sorted(пустые)} влияние не названо")

    роли = истина.get("document_roles") or {}
    неизвестные_роли = [р for р in роли if р not in РОЛИ_ДОКУМЕНТОВ]
    if неизвестные_роли:
        raise Отказ(f"роль документа {sorted(неизвестные_роли)} вне перечня {list(РОЛИ_ДОКУМЕНТОВ)}")
    for раздел in ("prompt_render", "goal_hierarchy", "charter_prism"):
        if раздел in истина and not истина[раздел]:
            raise Отказ(f"раздел «{раздел}» объявлен пустым — правило потеряется молча")


