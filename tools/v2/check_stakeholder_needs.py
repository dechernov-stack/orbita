#!/usr/bin/env python3
"""Сторож постановки: помета — не отказ (остановка ПМИ-6, 14.09).

До 14.09 сторож возвращал 1, если в проекте была сторона без нужды: правило
поставки 12.09 требовало превращать интерес стороны в нужду. Это правило и
набило «Постановку» мусором — строка РОЛИ стороны становилась нуждой
(ND-0002…ND-0009 из колонки «Интерес»/«Роль»). Правило снято: онтология
говорит «сторона без нужды — помета к воротам, не отказ» (note у понятия
stakeholder), а нужда рождается из ФАКТА по `need.from_facts`. Сторож обязан
различать помету и отказ — иначе он сторожит снятое правило.

ОТКАЗ (код 1) — то, что ворота обязаны были не пропустить:
  · нужда без стороны-владельца: онтология требует связь owns→stakeholder,
    а понятие с незакрытой обязательной связью — предложение, не сущность;
  · нужда, списанная с поля «interest» своей стороны: текст роли/интереса
    остаётся ПОЛЕМ СТОРОНЫ и утверждением нужды не становится;
  · принятое из неподтверждённого источника: факт ранга «сомнительный» с
    диспозицией adopted, у которого человек не подтвердил источники
    (evidence=corroborated);
  · сторона пакета не найдена в проекте — недобор сторон записки.

ПОМЕТА (код 0, печатается) — то, что человек видит на воротах и решает сам:
  · сторона без нужды;
  · сторона без влияния;
  · общая нужда §2.1 пакета, не найденная в проекте;
  · сторона проекта вне пакета — проверьте предикат роли: автор
    нормативного акта стороной не становится.

Правило берётся СО СТЕНДА (GET /v2/ontology/formation): второй копии
онтологии в питоне нет. Правило не прочитано — сторож не судит, а отказывается
(код 2): молчаливо зелёная проверка хуже несделанной.

  python3 tools/v2/check_stakeholder_needs.py --project PJ-… [--base URL]
                                              [--packet файл | --no-packet]
"""
from __future__ import annotations

import argparse
import http.cookiejar
import json
import pathlib
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import stand_session  # noqa: E402

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent.parent
ПАКЕТ = КОРЕНЬ / "docs/tz/v2/поставка-09-12/ПАКЕТ-СТОРОНЫ-И-НУЖДЫ.json"

# Значения данных, с которыми сторож сверяет ответы стенда. Ранг — из
# `authority_ranks` онтологии, диспозиция и свидетельство — из истины схем
# вида «факт»; наружу они приходят этими кодами, и снаружи сравнивать не с чем.
РАНГ_СОМНИТЕЛЬНЫЙ = "doubtful"
ПРИНЯТ = "adopted"
ПОДТВЕРЖДЁН = "corroborated"

# Доля общих слов, при которой нужда проекта считается той же, что нужда
# пакета. Мера приблизительная и потому даёт ПОМЕТУ, не отказ.
ДОЛЯ_СЛОВ = 0.6

_opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))


def вызов(base: str, путь: str):
    """GET со стенда. Не ответил — сторож не судит (код 2), а не «не выполнена»."""
    з = urllib.request.Request(base + путь, headers={"Content-Type": "application/json; charset=utf-8"})
    try:
        with _opener.open(з, timeout=60) as о:
            return json.loads(о.read().decode() or "{}")
    except urllib.error.HTTPError as e:
        print(f"GET {путь} → {e.code}: {e.read().decode()[:300]}", file=sys.stderr)
        raise SystemExit(2)


def норм(s: str) -> str:
    return re.sub(r"[^\wа-яё]+", " ", (s or "").lower().replace("ё", "е")).strip()


def слова(текст: str) -> set[str]:
    """Значимые слова утверждения: короткие служебные для сверки бесполезны."""
    return {с for с in норм(текст).split() if len(с) > 3}


def тот_же_смысл(эталон: str, тексты: list[str]) -> bool:
    """Есть ли среди текстов тот же по словам. Приблизительно — значит помета."""
    э = слова(эталон)
    if not э:
        return False
    return any(len(э & слова(т)) / len(э) >= ДОЛЯ_СЛОВ for т in тексты)


def та_же_сторона(имя_пакета: str, имена: list[str]) -> bool:
    """Сторона пакета среди имён проекта: пакет несёт связки «А / Б»."""
    части = [норм(ч) for ч in re.split(r"\s*/\s*", имя_пакета)]
    цель = норм(имя_пакета)
    return any(н == цель or н in части or (len(н) > 8 and н in цель) for н in имена)


def списана_с_поля(утверждение: str, поле: str) -> bool:
    """
    Нужда — это текст поля стороны? Сверка дословная (после нормализации):
    «похоже» здесь было бы догадкой, а догадка не может быть отказом.
    """
    а, б = норм(утверждение), норм(поле)
    if not а or not б:
        return False
    короткое, длинное = sorted((а, б), key=len)
    return а == б or (len(короткое) >= 20 and короткое in длинное)


def онтология(base: str, проект: str) -> dict:
    """Понятия со стенда: правило образования живёт там, а не здесь."""
    данные = вызов(base, f"/v2/ontology/formation?project={urllib.parse.quote(проект)}")
    понятия = {п.get("code"): п for п in данные.get("concepts", [])}
    for нужное in ("stakeholder", "need"):
        if нужное not in понятия:
            print(f"онтология стенда не знает понятия «{нужное}» — сверять нечем", file=sys.stderr)
            raise SystemExit(2)
    return понятия


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", default="http://localhost:8080/api")
    ap.add_argument("--project", required=True)
    ap.add_argument("--packet", default=str(ПАКЕТ))
    ap.add_argument(
        "--no-packet", action="store_true",
        help="не сверять с пакетом записки: проект собран не из неё",
    )
    a = ap.parse_args()
    stand_session.войти(a.base, _opener, "chernov")

    понятия = онтология(a.base, a.project)
    сторона_понятие, нужда_понятие = понятия["stakeholder"], понятия["need"]

    проект = urllib.parse.quote(a.project)
    стороны = вызов(a.base, f"/v2/entities?project={проект}&kind=stakeholder").get("items", [])
    нужды = вызов(a.base, f"/v2/entities?project={проект}&kind=need").get("items", [])
    факты = вызов(a.base, f"/v2/facts?project={проект}").get("items", [])

    сторона_по_id = {с["id"]: с for с in стороны}
    по_стороне: dict[str, list] = {с["id"]: [] for с in стороны}
    for н in нужды:
        for владелец in н.get("owned_by") or []:
            по_стороне.setdefault(владелец, []).append(н)

    отказы: list[tuple[str, list[str]]] = []
    пометы: list[tuple[str, list[str]]] = []
    справки: list[str] = []

    # --- отказ 1: обязательная связь понятия «нужда» не закрыта --------------
    # Какую связь требовать — говорит онтология стенда, не этот файл.
    обязательные = [т.split(" if ")[0].strip() for т in нужда_понятие.get("must_link", [])]
    нужен_владелец = any(т.startswith("owns→") for т in обязательные)
    прочие = [т for т in обязательные if not т.startswith("owns→")]
    if прочие:
        справки.append(f"связи {' · '.join(прочие)} этим сторожем не проверяются: их не видно в перечне сущностей")
    if нужен_владелец:
        без_стороны = [н for н in нужды if not (н.get("owned_by") or [])]
        if без_стороны:
            отказы.append((
                "нужда без стороны-владельца (онтология: must_link owns→stakeholder)",
                [f"{н['code']} «{(н['doc'].get('statement') or '')[:90]}»" for н in без_стороны],
            ))

    # --- отказ 2: нужда списана с поля стороны -------------------------------
    # Текст роли/интереса — поле стороны (онтология: stakeholder.fields.interest).
    поля_стороны = [п for п in ("interest", "role") if п in (сторона_понятие.get("fields") or {})]
    списанные: list[str] = []
    for н in нужды:
        утверждение = н["doc"].get("statement") or ""
        for владелец in н.get("owned_by") or []:
            сторона = сторона_по_id.get(владелец)
            if not сторона:
                continue
            for поле in поля_стороны:
                if списана_с_поля(утверждение, сторона["doc"].get(поле) or ""):
                    списанные.append(
                        f"{н['code']} ← {сторона['code']} «{сторона['doc'].get('name')}» · поле «{поле}»"
                    )
    if списанные:
        отказы.append((
            "нужда списана с поля стороны — текст роли/интереса остаётся полем, нуждой не становится",
            списанные,
        ))

    # --- отказ 3: принятое из неподтверждённого источника --------------------
    # Ранг «сомнительный» не даёт сущностей, пока человек не подтвердил
    # источники: подтверждённый факт несёт evidence=corroborated.
    неподтверждённые = [
        ф for ф in факты
        if (ф.get("authority") or "") == РАНГ_СОМНИТЕЛЬНЫЙ
        and (ф.get("disposition") or "") == ПРИНЯТ
        and (ф.get("evidence") or "") != ПОДТВЕРЖДЁН
    ]
    if неподтверждённые:
        отказы.append((
            "принято из неподтверждённого источника (ранг «сомнительный» без подтверждения источников)",
            [
                f"{ф.get('id')} [{ф.get('kind')}] материал {ф.get('material')} · "
                f"{(ф.get('predicate') or '')[:70]}"
                for ф in неподтверждённые
            ],
        ))

    # --- пометы: неполнота, которую видит человек на воротах -----------------
    без_нужд = [с for с in стороны if not по_стороне.get(с["id"])]
    if без_нужд:
        пометы.append((
            сторона_понятие.get("note") or "сторона без нужды — помета к воротам, не отказ",
            [f"{с['code']} «{с['doc'].get('name')}»" for с in без_нужд],
        ))
    без_влияния = [с for с in стороны if not с["doc"].get("influence")]
    if без_влияния:
        пометы.append((
            "сторона без влияния: влияние выводится из предиката роли — его в фактах не нашлось",
            [f"{с['code']} «{с['doc'].get('name')}»" for с in без_влияния],
        ))

    # --- пакет записки -------------------------------------------------------
    if not a.no_packet:
        пакет = json.loads(pathlib.Path(a.packet).read_text(encoding="utf-8"))
        имена = [норм(с["doc"].get("name", "")) for с in стороны]
        не_найдены = [и["name"] for и in пакет["items"] if not та_же_сторона(и["name"], имена)]
        if не_найдены:
            отказы.append((
                f"сторона пакета не найдена в проекте — недобор сторон записки ({len(не_найдены)} из {len(пакет['items'])})",
                [и[:90] for и in не_найдены],
            ))
        лишние = [
            с for с in стороны
            if not any(та_же_сторона(и["name"], [норм(с["doc"].get("name", ""))]) for и in пакет["items"])
        ]
        if лишние:
            пометы.append((
                "сторона проекта вне пакета — проверьте предикат роли: автор нормативного акта стороной не становится",
                [f"{с['code']} «{с['doc'].get('name')}»" for с in лишние],
            ))
        # Нужды пакета: общие §2.1 остаются ожиданием; строки колонки
        # «роль/интерес» — больше нет, их место — поле стороны.
        # Одна и та же общая нужда стоит у нескольких сторон пакета — сверяется
        # формулировка, поэтому повторы сводятся в одну строку.
        общие: dict[str, str] = {}
        из_колонки = []
        for и in пакет["items"]:
            for н in и.get("needs", []):
                if н.get("shared"):
                    общие.setdefault(норм(н["statement"]), н["statement"])
                else:
                    из_колонки.append(н)
        тексты = [н["doc"].get("statement") or "" for н in нужды]
        нет_общих = [с for с in общие.values() if not тот_же_смысл(с, тексты)]
        if нет_общих:
            пометы.append((
                f"общая нужда §2.1 не найдена в проекте (совпадение по словам ≥ {int(ДОЛЯ_СЛОВ * 100)} %)",
                [и[:90] for и in нет_общих],
            ))
        справки.append(
            f"строк пакета из колонки «роль/интерес» — {len(из_колонки)}: нуждами они больше не ожидаются, "
            "их место — поле «interest» стороны"
        )

    # --- вывод ---------------------------------------------------------------
    print(f"проект {a.project}: сторон {len(стороны)}, нужд {len(нужды)}, фактов {len(факты)}")
    for строка in справки:
        print("  справка:", строка)
    if пометы:
        print("\nПОМЕТЫ (к воротам, не отказ):")
        for заголовок, строки in пометы:
            print(f"  · {заголовок}")
            for с in строки:
                print("      ", с)
    if отказы:
        print("\nОТКАЗЫ (ворота не удержали):")
        for заголовок, строки in отказы:
            print(f"  · {заголовок}")
            for с in строки:
                print("      ", с)
    число = sum(len(строки) for _, строки in отказы)
    print(
        "\nмера:",
        "выполнена — отказов нет; пометы к воротам отказом не считаются"
        if not отказы else f"НЕ выполнена — отказов {число} в {len(отказы)} правилах",
    )
    return 1 if отказы else 0


if __name__ == "__main__":
    sys.exit(main())
