ТОКЕНЫ = [
    ("--paper: #F4F6F8;", "бумага"),
    ("--surface: #FFFFFF;", "поверхность"),
    ("--graphite: #C9D0D8;", "графит"),
    ("--ink: #182130;", "чернила"),
    ("--muted: #5C6675;", "приглушённый"),
    ("--cobalt: #2A4BD7;", "кобальт"),
    ("--green: #1F7A4D;", "зелёный"),
    ("--amber: #B7791F;", "янтарь"),
    ("--red: #C43A2B;", "красный"),
    ('--font: "Golos Text"', "гарнитура"),
    ("font-variant-numeric: tabular-nums;", "табличные цифры"),
    ("--radius: 0;", "радиус панелей"),
    ("--radius-input: 6px;", "радиус ввода"),
    ("height: 40px; padding: 0 16px;", "шапка 40 px"),
    ("white-space: normal; /* полные подписи", "рейка без усечений"),
]
ТЕНЬ = re.compile(r"box-shadow:\s*\d|box-shadow:\s*-?\d|box-shadow:\s*0 \d+px \d+px rgba")


def токены(css: str) -> list[str]:
    беды = [f"tokens.css: нет токена «{имя}» ({кусок})" for кусок, имя in ТОКЕНЫ if кусок not in css]
    for строка in css.splitlines():
        if ТЕНЬ.search(строка) and "--focus" not in строка and "inset" not in строка:
            беды.append(f"tokens.css: тень «{строка.strip()[:60]}» — глубина линией и белым на бумаге, теней нет")
    return беды


# Шип 5 §8 (a): ряд из трёх и более кнопок-ссылок в строке формы — самодельное
# второе меню; второе меню одно — компонент «Вкладки» (ui/tabs.tsx).
СТРОКА_ФОРМЫ = re.compile(r'<div className="v2-form v2-form--row"[^>]*>')
КНОПКА = re.compile(r"<button\b(?:[^>{}]|\{[^{}]*(?:\{[^{}]*\}[^{}]*)*\})*>", re.S)


def самодельное_меню(путь: Path, текст: str) -> list[str]:
    беды = []
    for м in СТРОКА_ФОРМЫ.finditer(текст):
        начало_строки = текст.rfind("\n", 0, м.start()) + 1
        отступ = м.start() - начало_строки
        конец = текст.find("\n" + " " * отступ + "</div>", м.end())
        блок = текст[м.end(): конец if конец > 0 else м.end() + 4000]
        ссылок = sum(1 for к in КНОПКА.finditer(блок) if "v2-link" in к.group(0))
        if re.search(r"\.map\([^)]*\)\s*=>\s*\(?\s*<button[^>]*v2-link", блок, re.S):
            ссылок += 3
        if ссылок >= 3:
            номер = текст.count("\n", 0, м.start()) + 1
            беды.append(f"{путь.relative_to(КОРЕНЬ)}:{номер}: ряд из {ссылок} кнопок-ссылок как меню — второе меню одно: «Вкладки» (шип 5 §1.1)")
    return беды


# Шип 5 §8 (c): пиктограмма без слова где бы то ни было — отказ; у кнопки с
# <Икон> обязаны быть и title, и aria-label (слово действия).
def пиктограмма_без_слова(путь: Path, текст: str) -> list[str]:
    беды = []
    for м in КНОПКА.finditer(текст):
        закрытие = текст.find("</button>", м.end())
        if закрытие < 0:
            continue
        тело = текст[м.end():закрытие]
        if "<Икон" not in тело:
            continue
        тег = м.group(0)
        if "aria-label=" not in тег and "title=" not in тег:
            номер = текст.count("\n", 0, м.start()) + 1
            беды.append(f"{путь.relative_to(КОРЕНЬ)}:{номер}: <Икон> в кнопке без aria-label и title — пиктограмма без слова (шип 5 §1.5)")
    return беды


# Шип 5 §8 (b): строка группы — `<tr>` с ячейкой на всю ширину (`colSpan`)
# внутри таблицы — отказ: группа — своей полосой над своей таблицей
# (ui/band.tsx), после §3 исключений нет. Можно только строку карточки
# (`v2-card-row`, карточка вниз от строки) и строку пустого реестра (`v2-empty`).
ЯЧЕЙКА_НА_ВСЮ = re.compile(r"<t[dh]\b[^>]*\bcolSpan=")


def строка_группы(путь: Path, текст: str) -> list[str]:
    беды = []
    for м in ЯЧЕЙКА_НА_ВСЮ.finditer(текст):
        тег_ячейки = текст[м.start(): текст.find(">", м.start()) + 1]
        начало = текст.rfind("<tr", 0, м.start())
        тег_строки = текст[начало: текст.find(">", начало) + 1] if начало >= 0 else ""
        if "v2-card-row" in тег_строки or "v2-empty" in тег_ячейки:
            continue
        номер = текст.count("\n", 0, м.start()) + 1
        беды.append(f"{путь.relative_to(КОРЕНЬ)}:{номер}: строка группы с colSpan внутри таблицы — группа своей полосой (шип 5 §1.2, §8 b)")
    return беды


# Шип 5 §8 (d): длина файла экрана — храповик. Известные нарушители поимённо
# с числом строк: рост — отказ, уменьшение — вписать новое число (храповик
# затягивается); новый экран длиннее предела — отказ. `knowledgefield.tsx`
# ушёл из списка в §3: поле знаний разложено по `knowledge/*.tsx`.
ПРЕДЕЛ_ЭКРАНА = 600
НАРУШИТЕЛИ: dict[str, int] = {
    "processmap.tsx": 816,
    "scenes.tsx": 809,
}


def длина_экранов(файлы: dict[Path, str]) -> list[str]:
    беды = []
    for путь, текст in файлы.items():
        if ".test." in путь.name:
            continue
        имя = путь.relative_to(WEB).as_posix() if путь.is_relative_to(WEB) else путь.name
        строк = текст.count("\n")
        было = НАРУШИТЕЛИ.get(имя)
        if было is None and строк > ПРЕДЕЛ_ЭКРАНА:
            беды.append(f"{имя}: {строк} строк — экран длиннее {ПРЕДЕЛ_ЭКРАНА}: разложить по файлам (шип 5 §8 d)")
        elif было is not None and строк > было:
            беды.append(f"{имя}: {строк} строк при храповике {было} — известный нарушитель растёт (шип 5 §8 d)")
        elif было is not None and строк < было:
            беды.append(f"{имя}: {строк} строк, в храповике {было} — впишите новое число: храповик затягивается (шип 5 §8 d)")
    return беды


# Шип 5 §8 (e): подсказка длиннее 160 знаков — простыня в подсказке: отказ.
# Подсказка — `title=`, слово кнопки-пиктограммы (`слово=` уходит в title и
# aria-label) и `hint:` вкладки (уходит в title). Считается текст литералов,
# склеенных `+`; у тернарного выбора — каждая ветка своей строкой; вставки
# `${…}` шаблона не считаются.
ПРЕДЕЛ_ПОДСКАЗКИ = 160
ПОДСКАЗКА = re.compile(r"(?<![\w-])(?:title=|слово=|hint:\s*)")


def _литералы(выражение: str) -> list[int]:
    """Длины групп литералов, склеенных `+`: каждая группа — одна возможная подсказка."""
    группы: list[int] = []
    текущая: int | None = None
    ждём_плюс = False
    i = 0
    while i < len(выражение):
        с = выражение[i]
        if с in "'\"`":
            кавычка, i, длина = с, i + 1, 0
            while i < len(выражение) and выражение[i] != кавычка:
                if выражение[i] == "\\":
                    i += 2
                    длина += 1
                    continue
                if кавычка == "`" and выражение.startswith("${", i):
                    глубина, i = 1, i + 2
                    while i < len(выражение) and глубина:
                        глубина += {"{": 1, "}": -1}.get(выражение[i], 0)
                        i += 1
                    continue
                длина += 1
                i += 1
            i += 1
            текущая = длина if текущая is None or not ждём_плюс else текущая + длина
            ждём_плюс = False
            continue
        if с == "+" and текущая is not None:
            ждём_плюс = True
        elif not с.isspace():
            if текущая is not None and not ждём_плюс:
                группы.append(текущая)
                текущая = None
            elif текущая is not None and ждём_плюс and с not in "(":
                ждём_плюс = False
        i += 1
    if текущая is not None:
        группы.append(текущая)
    return группы


def _значение(текст: str, начало: int) -> str:
    """Значение атрибута или свойства от `начало`: литерал в кавычках либо выражение до конца скобки."""
    if начало >= len(текст):
        return ""
    с = текст[начало]
    if с in "'\"":
        конец = текст.find(с, начало + 1)
        return текст[начало: конец + 1]
    if с == "{":
        глубина, i = 0, начало
        while i < len(текст):
            глубина += {"{": 1, "}": -1}.get(текст[i], 0)
            i += 1
            if глубина == 0:
                break
        return текст[начало + 1: i - 1]
    # свойство объекта: до запятой или закрывающей скобки на своём уровне
    глубина, i = 0, начало
    while i < len(текст):
        ч = текст[i]
        if ч in "([{":
            глубина += 1
        elif ч in ")]}":
            if глубина == 0:
                break
            глубина -= 1
        elif ч == "," and глубина == 0:
            break
        i += 1
    return текст[начало:i]


def длинные_подсказки(путь: Path, текст: str) -> list[str]:
    беды = []
    for м in ПОДСКАЗКА.finditer(текст):
        длины = _литералы(_значение(текст, м.end()))
        if длины and max(длины) > ПРЕДЕЛ_ПОДСКАЗКИ:
            номер = текст.count("\n", 0, м.start()) + 1
            беды.append(f"{путь.relative_to(КОРЕНЬ)}:{номер}: подсказка {max(длины)} знаков — простыня: не длиннее {ПРЕДЕЛ_ПОДСКАЗКИ} (шип 5 §8 e)")
    return беды


def проверить(css: str, файлы: dict[Path, str]) -> list[str]:
    беды: list[str] = []
    for путь, текст in файлы.items():
        if ".test." in путь.name:
            continue
        беды += капслок(путь, текст)
        беды += декор(путь, текст)
        беды += самодельное_меню(путь, текст)
        беды += пиктограмма_без_слова(путь, текст)
        беды += строка_группы(путь, текст)
        беды += длинные_подсказки(путь, текст)
    беды += усечение(css, файлы)
    беды += третья_колонка(css)
    return [б for б in беды if not any(и in б for и in ИСКЛЮЧЕНИЯ)]


