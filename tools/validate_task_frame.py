#!/usr/bin/env python3
"""Сторож рамки ведения (круг 3, приёмка): у рамки НЕТ собственных форм.

Рамка — режим, а не экран: она рисует одну строку степпера, а всё рабочее
приходит встроенным экраном системы с преднастройкой шага. Собственная форма
внутри рамки означала бы вторую реализацию того же ввода — и расхождение
поведения в тот же день, когда экран поправят.

Правило: в `web/src/ui/TaskFrame.tsx` не должно быть полей ввода, выбора и
таблиц. Кнопки степпера и перехода — можно, это навигация.
"""
import re
import sys
from pathlib import Path

РАМКА = Path(__file__).resolve().parent.parent / "web/src/ui/TaskFrame.tsx"
ЗАПРЕЩЕНО = ["<input", "<textarea", "<select", "<table", "<form"]

if not РАМКА.exists():
    print(f"рамка ведения: {РАМКА.name} не найден — пропуск")
    sys.exit(0)

текст = РАМКА.read_text(encoding="utf-8")
находки = []
for line_no, line in enumerate(текст.splitlines(), 1):
    for тег in ЗАПРЕЩЕНО:
        if тег in line:
            находки.append(f"  {РАМКА.name}:{line_no}: {тег} — {line.strip()[:70]}")

if находки:
    print("рамка ведения: у неё завелась собственная форма (правило круга 3):")
    print("\n".join(находки))
    print("  всё рабочее обязано приходить ВСТРОЕННЫМ экраном с преднастройкой шага")
    sys.exit(1)

# и обратная сторона: рамка обязана оставлять выход
if "обзор" not in текст:
    print("рамка ведения: нет выхода в обзор — рамка стала клеткой")
    sys.exit(1)

print("рамка ведения: собственных форм нет, выход в обзор на месте")
