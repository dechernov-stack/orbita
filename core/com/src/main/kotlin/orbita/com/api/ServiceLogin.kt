// Служебный вход инструментов стенда (загрузчик полок, прогон) — по слову
// владельца: «каждый раз ждать с Telegram — не дело». Не бэкдор в опасном
// смысле, а служебный доступ, который владелец заводит сам:
//
//  * СВОЯ личность («служебный orbita-tools», не «Чернов Д.») — журнал видит
//    машину, а не человека;
//  * ОТЗЫВ одной строкой — снял ORBITA_SERVICE_KEY из .env, рестарт, и ключ
//    мёртв (сессии служебной учётки не переживают старт);
//  * только режим telegram; ключ не задан — маршрута нет вовсе.
//
// Прод-переброску (ворота Conductor, Approve в UI) ключ НЕ трогает — это другая
// система, и туда стенд-ключ не дотягивается в принципе. Сравнение ключа —
// та же MessageDigest.isEqual, что у HMAC-проверки сессии рядом.
package orbita.com.api

import java.security.MessageDigest

internal object ServiceLogin {

    /** Логин и имя служебной личности: своя, не заимствованная у владельца. */
    const val LOGIN = "service:orbita-tools"
    const val NAME = "служебный orbita-tools"

    enum class Итог {
        /** Маршрута нет: не режим telegram либо ключ не задан в .env стенда. */
        ВЫКЛ,

        /** Ключ предъявлен, но не тот. */
        ОТКАЗ,

        /** Ключ совпал — заводить сессию служебной личности. */
        ОК,
    }

    /**
     * Пускать ли по предъявленному ключу. `key` — секрет из окружения стенда,
     * `предъявлен` — что прислал инструмент (заголовок X-Orbita-Service или тело).
     */
    fun решение(telegramMode: Boolean, key: String?, предъявлен: String?): Итог = when {
        !telegramMode || key.isNullOrBlank() -> Итог.ВЫКЛ
        !предъявлен.isNullOrBlank() &&
            MessageDigest.isEqual(предъявлен.toByteArray(), key.toByteArray()) -> Итог.ОК
        else -> Итог.ОТКАЗ
    }
}
