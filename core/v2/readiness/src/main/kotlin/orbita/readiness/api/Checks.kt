// Точка расширения оценщика: условия, которые ЗНАЮТ модули выше слоем.
//
// Оценщик живёт в L1 и не может зависеть от требований и архитектуры (L3):
// зависимости идут только вниз. Но правило «носитель требования той же
// природы, что уровень» живёт там, где живёт само требование, — и
// дублировать его здесь значило бы завести второй источник истины.
// Поэтому оценщик спрашивает: «знаешь такое условие?» — и получает ответ
// от того, кто вправе его знать. Собирает эту связку граница (Boundary).
package orbita.readiness.api

/** Ответ проверки: выполнено или нет, и почему нет — словами. */
data class CheckResult(val passed: Boolean, val why: String? = null) {
    companion object {
        val ok = CheckResult(true)
        fun no(why: String) = CheckResult(false, why)
    }
}

/**
 * Дополнительные условия ворот.
 *
 * `null` означает «не знаю такого условия» — и это НЕ «выполнено»:
 * оценщик пойдёт дальше и, если условие не узнал никто, честно скажет,
 * что правило не реализовано.
 */
fun interface ExtraChecks {
    fun of(project: String, check: String): CheckResult?
}
