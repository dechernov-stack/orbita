// Промпт второй ступени сверки: «то же самое, сказанное другими словами?»
//
// Ступень 1 (ключ идентичности понятия) уже отработала и БЕСПЛАТНО закрыла
// всё, что решается по данным. Сюда попадает только то, где ключ не сложился
// или не совпал, — и потому промпт не спрашивает «разбери поле», а спрашивает
// об одном: не о том ли самом речь, и не спорит ли внесённое с принятым.
//
// Правила образования берутся из ОНТОЛОГИИ-ФОРМИРОВАНИЯ и идут В ПРОМПТ:
// чем понятие узнаётся по смыслу, какой у него порог близости и что считается
// противоречием. Свободного текста о понятиях здесь не сочиняется — истина
// одна, и промпт собирается из неё (ПОЛЕ-ЗНАНИЙ-V2-СИНТЕЗ §3).
//
// Права службы названы прямо (СВЕРКА-РУЧНОГО-ВВОДА): предлагает — слить ·
// уточнить · связать · пометить противоречие. НЕ вправе: сливать сама, менять
// принятое, выбирать победителя, придумывать основание. Ответ без названного
// ПОЛЯ отличия сервер отбрасывает: «похоже» без «чем именно» — брак.
package orbita.ai.internal

import orbita.kernel.schema.GeneratedKinds
import orbita.knowledge.api.Authority
import orbita.knowledge.schema.GeneratedOntology

/**
 * Строка ввода, ушедшая на вторую ступень.
 *
 * @property localId местный номер строки ввода — им ответ возвращается в ту
 *   же строку экрана, пока сущности ещё нет
 * @property note чем ступень 1 объяснила свой вопрос: «ключ не сложился»
 */
data class SemanticCandidate(
    val localId: String,
    val concept: String,
    val fields: Map<String, String>,
    val note: String = "",
)

/**
 * Запись среза поля: принятая сущность либо факт — то, С ЧЕМ сравнивают.
 *
 * Сравнение идёт ТОЛЬКО с записями среза: код вне среза — придуманное
 * основание, и сервер такую находку отбрасывает.
 *
 * @property authority ранг доверия факта; у принятой сущности пусто — ранг
 *   есть свойство основания, а не принятого понятия
 */
data class SliceEntry(
    val code: String,
    val kind: String,
    val text: String,
    val authority: String = "",
)

object ReconcilePrompt {

    /**
     * Версия шаблона. Идёт В ТЕКСТ промпта: журнал кэширует ответ отпечатком
     * промпта, и правка шаблона обязана этот отпечаток менять — иначе новая
     * редакция вопроса молча отвечалась бы старым ответом.
     */
    const val VERSION: String = "reconcile/v1"

    /**
     * Промпт второй ступени по срезу поля.
     *
     * @param omitted сколько записей поля осталось за потолком среза; человеку
     *   и модели это говорится словами, а не скрывается
     */
    fun of(
        projectName: String,
        candidates: List<SemanticCandidate>,
        accepted: List<SliceEntry>,
        facts: List<SliceEntry>,
        omitted: Int = 0,
    ): String {
        require(candidates.isNotEmpty()) {
            "вторую ступень спрашивать не о чем: ни одной строки ввода — вызова быть не должно"
        }
        val правила = candidates.map { it.concept }.distinct().joinToString("\n") { блокПонятия(it) }
        val введено = candidates.joinToString("\n") { блокКандидата(it) }
        val принятое = accepted.joinToString("\n") { "  · ${it.code} · ${it.kind} · ${it.text}" }
            .ifBlank { "  (принятых записей этих понятий в проекте нет)" }
        val поле = facts.joinToString("\n") { строкаФакта(it) }
            .ifBlank { "  (фактов в срезе нет)" }
        val хвост =
            if (omitted <= 0) ""
            else "\nЗа потолком среза осталось $omitted записей поля: они в сравнение не входят — " +
                "о том, чего нет в срезе, не рассуждай."

        return """
Ты — ВТОРАЯ ступень сверки ручного ввода в поле знаний инженерного проекта.

Первая ступень уже отработала на данных: ключ идентичности понятия не совпал
ни с одной принятой записью. Твой вопрос один — не то же ли это САМОЕ,
сказанное другими словами, и не спорит ли внесённое с принятым.

Версия шаблона: $VERSION

## Проект
$projectName

## Правила образования понятий (онтология проекта)
$правила
## Внесено экспертом (ранг «${Authority.word(Authority.EXPERT)}», якоря нет)
$введено
## Срез поля — сравнивать только с ним
Принятые записи:
$принятое
Факты поля (код · ранг доверия · утверждение):
$поле$хвост

## Что ты не вправе делать
1. Не сливаешь, не правишь принятое и не заводишь сущностей: ты показываешь,
   решает человек.
2. В противоречии победителя не выбираешь — называешь ОБА значения; ранг
   подсказывает человеку, а не тебе.
3. Оснований не придумываешь: `target` — код ИЗ СРЕЗА выше, другого не бывает.
4. Ничего не додумываешь: чего в срезе нет, того нет.

## Требования к ответу — нарушение делает находку непригодной
Верни ТОЛЬКО массив JSON, без пояснений до и после него.
[
  {
    "local_id": "номер строки ввода из раздела «Внесено экспертом»",
    "target": "код записи из среза",
    "question": "duplicate | contradiction | connection",
    "verdict": "augment | contradict | confirm",
    "confidence": 0.0,
    "compared_fields": ["поле", "поле"],
    "difference": {"field": "поле", "mine": "значение внесённого", "theirs": "значение принятого"},
    "why": "одной строкой: почему это то же самое либо в чём спор"
  }
]
Правила ответа:
· `question` и `verdict` идут парой: duplicate → augment (то же самое иными
  словами) · contradiction → contradict (об одном и том же сказано разное) ·
  connection → confirm (факт среза подтверждает внесённое — основание к
  привязке). Другой пары не бывает.
· `compared_fields` и `difference` ОБЯЗАТЕЛЬНЫ у каждой находки: «похоже» без
  «чем именно» сервер отбрасывает и показывает человеку как брак ответа.
  `difference.field` — имя поля из правил понятия выше, `mine` и `theirs` —
  значения сторон их собственными словами.
· `confidence` — близость смысла от 0 до 1. Ниже порога понятия находка
  отбрасывается: не завышай, лучше промолчать.
· Совпадений нет — верни ПУСТОЙ массив. Записей «новое» не возвращай: о новом
  сервер знает без тебя.
· Нехватку обязательных связей не ищи — её считает сервер по онтологии.
""".trimIndent()
    }

    /** Правила понятия — из онтологии, дословно: второй копии правил в коде нет. */
    private fun блокПонятия(concept: String): String {
        val понятие = GeneratedOntology.of(concept)
        val конфликт = понятие.conflictOn.joinToString(" · ").ifBlank { "(конфликтных полей не названо)" }
        val поля = понятие.fields.keys.joinToString(" · ").ifBlank { "(полей не названо)" }
        return """
Понятие «${словами(concept)}» ($concept)
  · чем узнаётся по смыслу: ${понятие.identity.semantic}
  · порог близости: ${понятие.identity.threshold} — ниже него это НЕ дубль
  · противоречием считается различие в полях: $конфликт
  · поля понятия: $поля
""".trimIndent() + "\n"
    }

    private fun блокКандидата(кандидат: SemanticCandidate): String {
        val поля = кандидат.fields.entries
            .filter { it.value.isNotBlank() }
            .joinToString("\n") { (поле, значение) -> "    $поле: $значение" }
            .ifBlank { "    (полей не названо)" }
        val помета = кандидат.note.ifBlank { "ключ идентичности совпадения не дал" }
        return "${кандидат.localId} · ${словами(кандидат.concept)} (${кандидат.concept})\n" +
            "$поля\n    ступень 1: $помета"
    }

    private fun строкаФакта(запись: SliceEntry): String {
        val ранг = Authority.word(запись.authority).ifBlank { "ранг не проставлен" }
        return "  · ${запись.code} · $ранг · ${запись.text}"
    }

    /**
     * Понятие словами. Словарь понятий здесь не заводится: слово берётся у
     * вида из истины схем — вторая копия названий разошлась бы с экраном.
     */
    private fun словами(concept: String): String =
        GeneratedKinds.byCode[concept]?.title ?: concept
}
