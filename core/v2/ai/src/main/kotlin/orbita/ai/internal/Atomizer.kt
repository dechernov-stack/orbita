// Д2б — атомизация: канон документа → факты с якорями (главный вызов).
//
// Правила честности §6 приходят В ПРОМПТ, а не остаются пожеланием: факт
// без якоря не существует; величина без единицы — не факт; внешнее — [В] с
// датой, допущение — [П]; конфликт показывается обоими фактами, модель не
// выбирает. Контекст проекта (ограничения Р, класс миссии) идёт туда же —
// чтобы «80–200 кг» столкнулось с Р2 на входе, а не на приёмке.
//
// Ворота ответа — на нашей стороне: `Intake.putFacts` не принимает факт без
// якоря из канона. Модель может ошибиться; система — нет.
//
// Поле знаний v2 (стадия А, ПОЛЕ-ЗНАНИЙ-V2-СИНТЕЗ §1–2). У документа есть
// РАНГ доверия, и он идёт в промпт: ранг наследуют факты, а при конфликте он
// подсказывает человеку — но не выбирает победителя. Режим разбора выбирает
// ПРОФИЛЬ содержимого — доли блоков «постановка · параметры · нормы ·
// оценки», — а не тип файла: тип документа как поле ввода запрещён решением
// владельца, и единственный способ закрыть эту ловушку — выводить режим из
// того, что в документе написано. Разбор той же стадией возвращает связи
// между фактами (supports · contradicts · refines · same_as).
//
// На проекте без флага `knowledge_v2` промпт остаётся прежним ДО БУКВЫ:
// журнал кэширует ответ отпечатком промпта, и лишний пробел стоит живого
// вызова на каждом документе стенда прохода.
