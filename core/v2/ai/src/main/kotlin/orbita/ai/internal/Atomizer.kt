    /** Ранг доверия документа словами: его наследуют факты (ПОЛЕ-ЗНАНИЙ-V2-СИНТЕЗ §1). */
    private fun ранг(карточка: Entity?): String = when (карточка?.doc?.path("authority")?.asText("") ?: "") {
        "mandatory" -> "обязательный — заказчик, регулятор, директива: факты имеют вес нормы"
        "expert" -> "экспертный — слово специалиста: факты имеют вес свидетельства эксперта"
        "reference" -> "справочный — аналитика, наследие, даташит: факты имеют вес свидетельства"
        "doubtful" -> "сомнительный — источник не подтверждён: факты принимаются только явным решением человека"
        // Ранга нет у материалов, загруженных до перестройки: авансом доверие
        // не выдаётся, но и разбор из-за этого не останавливается.
        else -> "не назначен"
    }

    /**
     * Режим по типу входного (ДОКУМЕНТЫ-1-ВХОДНЫЕ §3): ТЗ — полный разбор и
     * ОЦЕНКА против нужд проекта; даташит — параметры в поля АНКЕТЫ узла;
     * норматив — пункты обязательствами с порогом ПОЛЕМ. Записка и прочее —
     * общий режим.
     *
     * Прежний путь: работает на проектах без поля знаний v2 и остаётся
     * дословным — от буквы промпта зависит попадание в журнал.
     */
    private fun режимПоТипу(project: String, тип: String, intent: String): String = when (тип) {
        "tor" -> блокТЗ(project)
        "datasheet" -> блокДаташита(project, intent)
        "normative" -> блокНорматива()
        else -> ""
    }

    /**
     * Режим по ПРОФИЛЮ содержимого (Д2а): доли блоков решают, какие правила
     * уходят в промпт, а тип файла не решает ничего.
     *
     * Правила складываются, а не исключают друг друга: документ бывает
     * смешанным — постановка, таблица параметров и ссылки на нормы в одном
     * файле, — и режим применяется К БЛОКУ. Задание инженера сужает выбор
     * там, где профиль сказать не может: пункты-обязательства есть и у ТЗ
     * заказчика, и у нормативного акта, а действия плана у них разные.
     */
    private fun режимПоПрофилю(project: String, карточка: Entity?, intent: String, блоки: List<CanonBlock>): String {
        val доли = профильКарточки(карточка) ?: профильПоТексту(блоки)
        val задание = intent.lowercase()
        val проТЗ = ЗАДАНИЕ_ТЗ.containsMatchIn(задание)
        val проНорматив = ЗАДАНИЕ_НОРМАТИВ.containsMatchIn(задание)
        val нормы = доли.norms >= ДОЛЯ_РЕЖИМА
        val части = mutableListOf<String>()
        if (доли.statement >= ДОЛЯ_РЕЖИМА) части += "постановка"
        if (доли.params >= ДОЛЯ_РЕЖИМА) части += "параметры"
        if (нормы) части += "нормы"
        if (доли.assessments >= ДОЛЯ_РЕЖИМА) части += "оценки"

        // Пункты-обязательства есть и у ТЗ заказчика, и у нормативного акта —
        // профиль их не различает, а действия плана у них разные (требование
        // против полки нормативов). Различает заголовок документа: акт
        // называет себя сам («ГОСТ Р…», «Постановление Правительства…»).
        val нпа = проНорматив || (нормы && !проТЗ && НАЗВАНИЕ_НПА.containsMatchIn(заголовок(блоки)))
        val правила = mutableListOf<String>()
        if (проТЗ || (нормы && !нпа)) правила += блокТЗ(project)
        if (нпа) правила += блокНорматива()
        if (доли.params >= ДОЛЯ_РЕЖИМА || ЗАДАНИЕ_ПАРАМЕТРЫ.containsMatchIn(задание)) {
            // Запрет «действий по параметрам не предлагай» написан для
            // чистого даташита. В смешанном документе он молча съел бы
            // стороны и нужды постановочных блоков — поэтому область
            // запрета называется вслух.
            val областьЗапрета =
                if (части.size <= 1) ""
                else "\nЗапрет на действия по параметрам касается ТОЛЬКО параметрических блоков: " +
                    "в постановочных блоках предлагай действия по общему правилу."
            правила += блокДаташита(project, intent) + областьЗапрета
        }
        if (доли.assessments >= ДОЛЯ_РЕЖИМА) правила += блокОценок()

        val шапка = """
## Профиль содержимого документа: ${части.joinToString(" · ").ifBlank { "постановка" }}
Правила режимов ниже применяются К БЛОКУ по тому, что в нём написано, а не ко
всему документу: тип файла режима не выбирает. Пункт-обязательство разбирается
правилом нормы, строка с величиной — правилом параметров, суждение — правилом
оценки, остальное — общим правилом постановки.""".trimIndent()
        return (listOf(шапка) + правила).joinToString("\n\n")
    }

    /**
     * Профиль из карточки материала: его ставит разбор (Д2а), инженер не
     * вводит. Пустой профиль — это «ещё не считали», а не «нулевые доли».
     *
     * Повторный разбор ТОЙ ЖЕ версии документа читает уже записанный профиль,
     * и, если разбор разошёлся с первичной оценкой на пороге, промпт меняется
     * и живой вызов случается второй раз — один раз на документ, дальше
     * профиль устойчив и ответ берётся из журнала. Обратное (считать режим
     * всегда по первичной оценке) обесценило бы сам profile.
     */
    private fun профильКарточки(карточка: Entity?): ContentProfile? {
        val узел = карточка?.doc?.path("profile") ?: return null
        if (!узел.isObject) return null
        val профиль = runCatching {
            ContentProfile(
                statement = узел.path("statement").asDouble(0.0),
                params = узел.path("params").asDouble(0.0),
                norms = узел.path("norms").asDouble(0.0),
                assessments = узел.path("assessments").asDouble(0.0),
            )
        }.getOrNull() ?: return null
        return профиль.takeIf { it.statement + it.params + it.norms + it.assessments > 0.0 }
    }

    /** Заголовок документа — первый блок-заголовок канона; им акт называет себя. */
    private fun заголовок(блоки: List<CanonBlock>): String =
        (блоки.firstOrNull { it.kind == "heading" } ?: блоки.firstOrNull())?.text?.lowercase() ?: ""

    /**
     * Первичная оценка профиля — до того, как разбор вернул свой.
     *
     * Первый разбор документа профиля ещё не имеет, а режим выбрать надо —
     * и выбирать его по типу файла нельзя. Считаются ДОЛИ БЛОКОВ по словам,
     * которыми блок написан; величина из текста не извлекается и в модель не
     * попадает (thresholds_rule: порог живёт полем, а не regex-ом).
     */
    private fun профильПоТексту(блоки: List<CanonBlock>): ContentProfile {
        var нормы = 0
        var параметры = 0
        var оценки = 0
        var постановка = 0
        блоки.filter { it.kind != "heading" }.forEach { блок ->
            val текст = блок.text.lowercase()
            when {
                ОБЯЗАННОСТЬ.containsMatchIn(текст) -> нормы += 1
                СУЖДЕНИЕ.containsMatchIn(текст) -> оценки += 1
                ВЕЛИЧИНА.containsMatchIn(текст) -> параметры += 1
                else -> постановка += 1
            }
        }
        val всего = (нормы + параметры + оценки + постановка).coerceAtLeast(1).toDouble()
        return ContentProfile(постановка / всего, параметры / всего, нормы / всего, оценки / всего)
    }

    /**
     * Режим ТЗ — дословно (ШИП-G-ПРИНЯТ и ответ владельца 09.09): перечень
     * классов сущностей и двусторонняя оценка против нужд считаются живым
     * прогоном (tools/v2/check_tor_mode.py), переписывать их нельзя.
     */
    private fun блокТЗ(project: String): String {
        val нужды = store.list(Area.Project(project), "need")
            .joinToString("\n") { "  · ${it.code}: ${it.doc.path("statement").asText("")}" }
            .ifBlank { "  (нужд в проекте пока нет — оценка невозможна, верни assessment с пустыми lines)" }
        return """
## Режим: техническое задание заказчика (полный разбор + оценка против нужд)
ПРАВИЛО АТОМИЗАЦИИ (ШИП-G-ПРИНЯТ): каждое требование, каждая функция и
каждый сервис (услуга) ТЗ — ОТДЕЛЬНЫЙ факт; ничего не объединяй: «услуги
связи, телеметрии и навигации (PNT)» — три факта, не один. Так же отдельными
фактами — каждая сторона, каждый узел состава, каждое ограничение, каждая веха
и каждый нормативный акт, на который ТЗ ссылается. У каждого факта ТЗ —
поле `entity_class` из: requirement · function · service · composition_node ·
stakeholder · constraint · milestone · normative_ref.
Требование ТЗ — факт вида obligation: subject — «ТЗ п. N», predicate —
формулировка требования, value — «требование». Функция — capability, сервис —
capability с value «услуга», узел состава — framing с value «узел», веха —
event с датой, норматив — framing с обозначением акта.
Действия плана — по классу факта: requirement и function → create_entity
