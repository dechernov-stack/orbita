        /** Потолок ответа разбора: сто фактов с якорями — это десятки тысяч токенов. */
        const val БЮДЖЕТ_РАЗБОРА: Int = 64_000

        /**
         * Связи стадии А (ПОЛЕ-ЗНАНИЙ-V2-СИНТЕЗ §2) — ровно те же значения,
         * что у `link.type` в схемах и в реестре связей. Произвольных связей
         * не бывает: перечень назван промпту и им же стережётся ответ.
