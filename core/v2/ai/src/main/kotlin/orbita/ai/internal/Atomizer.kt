class Atomizer(
    private val store: EntityStore,
    private val intake: Intake,
    private val service: AiService,
    private val mapper: ObjectMapper = ObjectMapper(),
) {

    /** Разбор материала живым вызовом. Повтор той же версии — из журнала. */
    fun atomize(project: String, material: String, intent: String, author: String): FactIntake {
        val промпт = prepare(project, material, intent)
        // Урожай в сотню фактов не помещается в бюджет короткого ответа:
        // разбор просит свой потолок, а не полагается на общий.
        val ответ = service.ask(project, KIND, промпт, maxTokens = БЮДЖЕТ_РАЗБОРА)
        return apply(project, material, intent, author, ответ, journaled = true)
    }

    /**
     * Промпт разбора — читается из базы на потоке запросов; дальше он
     * самодостаточен, и сетевой вызов можно делать где угодно (ADR-069).
     */
    fun prepare(project: String, material: String, intent: String): String {
        val блоки = intake.canon(project, material)
        require(блоки.isNotEmpty()) {
            "у материала «$material» нет текста: разбирать нечего. " +
                "Приложите текст документа — канон строится из него"
        }
        return промпт(project, material, intent, блоки)
    }

    /** Применить ответ модели: журнал (если ещё не записан) и приём фактов — на потоке запросов. */
    fun apply(project: String, material: String, intent: String, author: String, answer: Answer, journaled: Boolean = false, prompt: String? = null): FactIntake {
        if (!journaled && prompt != null && !answer.cached) service.record(project, KIND, prompt, answer)
        // Связь неизвестного типа — не «почти связь»: она не доходит до
        // приёма и называется поимённо, как отклонённый факт. Реестр связей
        // на такой тип отвечает исключением, и один брак модели унёс бы
        // ВЕСЬ разбор документа.
        val (текст, отказыСвязей) = безБракованныхСвязей(project, answer.text)
        val итог = intake.putFacts(project, material, текст, author, intent)
        val сОтказами =
            if (отказыСвязей.isEmpty()) итог
            else итог.copy(
                refused = итог.refused + отказыСвязей,
                note = итог.note + ", связей отклонено ${отказыСвязей.size} (тип вне реестра связей)",
            )
        return itogСПометой(сОтказами, answer.cached)
    }

    private fun itogСПометой(итог: FactIntake, изЖурнала: Boolean): FactIntake =
        if (!изЖурнала) итог
        else итог.copy(note = итог.note + " · ответ взят из журнала: та же версия документа уже разбиралась")

    /**
     * Ответ без брака в связях: тип вне перечня стадии А, конец не номером
     * факта и связь факта с самим собой отсеиваются с причиной.
     *
     * Без флага и без блока `links` текст возвращается БУКВА В БУКВУ: на
     * проекте прохода ответ модели не переписывается вовсе.
     */
    private fun безБракованныхСвязей(project: String, raw: String): Pair<String, List<String>> {
        if (!KnowledgeFlag.on(store, project)) return raw to emptyList()
        val корень = разобрать(raw) as? ObjectNode ?: return raw to emptyList()
        val связи = корень.path("links")
        if (!связи.isArray || связи.isEmpty) return raw to emptyList()
        val отказы = mutableListOf<String>()
        val годные = mapper.createArrayNode()
        связи.forEachIndexed { i, с ->
            val тип = с.path("type").asText("")
            val от = с.path("from").asInt(-1)
            val к = с.path("to").asInt(-1)
            when {
                тип !in ТИПЫ_СВЯЗЕЙ -> отказы += "связь $i «${тип.ifBlank { "без типа" }}»: такого типа связи нет в реестре — " +
                    "принимаются ${ТИПЫ_СВЯЗЕЙ.joinToString(" · ")}"
                от < 0 || к < 0 -> отказы += "связь $i «$тип»: концы связи — номера фактов ответа, а здесь их нет"
                от == к -> отказы += "связь $i «$тип»: факт связан сам с собой"
                else -> годные.add(с)
            }
        }
        if (отказы.isEmpty()) return raw to emptyList()
        корень.set<JsonNode>("links", годные)
        return mapper.writeValueAsString(корень) to отказы
    }

    /** Ответ модели деревом; не разобрался — пусть отвечает приём фактов, он это уже умеет. */
    private fun разобрать(raw: String): JsonNode? = runCatching {
        mapper.readTree(raw.trim().removePrefix("```json").removePrefix("```").removeSuffix("```").trim())
    }.getOrNull()

    /**
     * Промпт разбора. Контекст проекта — ограничения и класс — идёт в него
     * целиком: без них модель не столкнёт величину документа с рамкой
     * проекта и отдаст «80–200 кг» как факт без вопроса.
     */
    private fun промпт(project: String, material: String, intent: String, блоки: List<CanonBlock>): String {
        val область = Area.Project(project)
        val новоеПоле = KnowledgeFlag.on(store, project)
        val паспорт = store.list(область, "project").firstOrNull()
        val ограничения = store.list(область, "constraint")
            .joinToString("\n") { "  · ${it.code}: ${it.doc.path("text").asText("")}" }
            .ifBlank { "  (ограничений в проекте пока нет)" }
        val карточка = store.byCode(область, material)
        val имя = карточка?.doc?.path("name")?.asText(material) ?: material
        val тип = карточка?.doc?.path("kind")?.asText("") ?: ""
        val режим = if (новоеПоле) режимПоПрофилю(project, карточка, intent, блоки) else режимПоТипу(project, тип, intent)
        // Ранг заменяет тип в описи документа: доверие называет инженер,
        // режим выводит разбор. Пока флага нет — прежняя строка с типом.
        val опись =
            if (новоеПоле) "Наименование: «$имя»\nРанг доверия источника: ${ранг(карточка)}"
            else "Наименование: «$имя»${if (тип.isNotBlank()) ", тип: $тип" else ""}"
        val правилоРанга =
            if (!новоеПоле) ""
            else "\n7. Ранг документа НЕ делает факт верным: при расхождении с фактом\n" +
                "   другого документа записываются ОБА факта, ранг лишь подсказывает\n" +
                "   человеку, кому верить. Выбирать победителя — не твоё дело."
        val стадияА = if (!новоеПоле) "" else СТАДИЯ_А
        val профильВОтвете =
            if (!новоеПоле) ""
            else "\n  \"profile\": {\"statement\": 0.0, \"params\": 0.0, \"norms\": 0.0, \"assessments\": 0.0},\n" +
                "  \"links\": [{\"from\": 0, \"to\": 3, \"type\": \"supports|contradicts|refines|same_as\", \"rationale\": \"почему связь именно такая\"}],"
        val выжимка = блоки.joinToString("\n") { "[${it.anchor}] ${it.text}" }

        return """
Ты разбираешь входной документ инженерного проекта на АТОМАРНЫЕ ФАКТЫ.

## Проект
Название: ${паспорт?.doc?.path("name")?.asText(project) ?: project}
Ограничения проекта (рамки, с которыми факты обязаны быть сверены):
$ограничения

## Документ
$опись
Задание инженера: «$intent»

$режим

## Правила честности — нарушение делает ответ непригодным
1. Факт без ЯКОРЯ не существует. Якорь — это метка блока в квадратных
   скобках из текста ниже (например s3#2). Придумывать якоря нельзя:
   принимаются только те, что есть в тексте.
2. Величина без ЕДИНИЦЫ измерения — не факт. У вида `quantity` единица
   обязательна.
3. Метка достоверности: И — утверждение самого документа; В — внешний
   источник, на который документ ссылается; П — предположение или цель.
4. Конфликт величин между источниками — ДВА факта, оба с якорями. Не
   выбирай, какой верен.
5. Ничего не обобщай и не додумывай: чего в тексте нет, того нет.
6. Если величина документа противоречит ограничению проекта — факт всё
   равно записывается, а в `conflict` называется код ограничения.$правилоРанга

