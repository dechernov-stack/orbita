         * Блок-параметр: величина с единицей. Само число НЕ извлекается —
         * считается только то, что блок параметрический (thresholds_rule).
         *
         * `(?U)` обязателен: без него граница слова `\b` считается по
         * латинскому алфавиту, и русская единица («кг», «Вт») не совпадает
