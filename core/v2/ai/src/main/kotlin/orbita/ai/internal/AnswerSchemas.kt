        return узел
    }

    /**
     * Величина — ОБЪЕКТОМ, никогда строкой (истина, `normalization.measures`):
     * значение либо диапазон, и единица отдельным полем.
     */
    private fun величина(mapper: ObjectMapper, пояснение: String): ObjectNode {
        val узел = объект(mapper, обязательные = listOf("unit"))
        поле(узел, "value", строка(mapper, "значение числом, если оно одно"))
        поле(узел, "min", строка(mapper, "нижняя граница диапазона"))
        поле(узел, "max", строка(mapper, "верхняя граница диапазона"))
        поле(узел, "unit", строка(mapper, "единица величины"))
        узел.put("description", пояснение)
        return узел
    }

    /** Общие поля всякого пункта чтения: свой номер, цитата, якорь, уверенность. */
    private fun пункт(mapper: ObjectMapper, обязательные: List<String>): ObjectNode {
        val узел = объект(mapper, обязательные = listOf("id", "quote", "anchor") + обязательные)
        поле(узел, "id", строка(mapper, "номер пункта в этом ответе, например s1 — на него ссылаются соседи"))
        поле(
            узел, "quote",
            строка(
                mapper,
                "ДОСЛОВНЫЙ фрагмент текста выше, 10–200 знаков. Пересказ недопустим: " +
                    "система сверяет цитату с каноном и пункт без совпадения отбрасывает",
            ),
        )
        поле(узел, "anchor", строка(mapper, "якорь блока, где найдена цитата, например s3#2"))
        поле(узел, "confidence", число(mapper, "уверенность 0…1"))
        return узел
    }

    private fun ссылка(mapper: ObjectMapper, пояснение: String): ObjectNode {
        val узел = объект(mapper, обязательные = emptyList())
        поле(узел, "code", строка(mapper, "код уже принятого понятия"))
        поле(узел, "ref", строка(mapper, "id пункта ЭТОГО же ответа"))
        узел.put("description", пояснение)
        return узел
    }

    private fun сторона(mapper: ObjectMapper): ObjectNode {
        val узел = пункт(mapper, обязательные = listOf("name", "role", "needs"))
        поле(узел, "name", строка(mapper, "имя организации, ведомства или группы"))
        поле(узел, "role", перечень(mapper, РОЛИ_СТОРОНЫ, "роль к проекту"))
        поле(узел, "interest", строка(mapper, "интерес одной фразой, если назван"))
        поле(узел, "scale", величина(mapper, "масштаб стороны: число и единица (ТС · терминалов · объектов), если назван"))
        // Нужды живут ВНУТРИ стороны, а не отдельным списком.
        //
        // У нужды ровно один носитель (`owns→stakeholder`), и общая нужда
        // документа принадлежит каждой стороне, которой касается, — отдельной
        // записью. Пока нужды шли одним плоским списком, модель писала каждую
        // формулировку ОДИН раз: на записке выходило 14 нужд вместо сорока
        // трёх эталона, сколько её об этом ни проси словами (прогон 16.09).
        // Форма ответа надёжнее уговора: перечисляя нужды у каждой стороны,
        // модель повторяет общую столько раз, скольким сторонам она нужна.
        поле(узел, "needs", массив(mapper, нужда(mapper)))
        return узел
    }

    private fun нужда(mapper: ObjectMapper): ObjectNode {
        val узел = объект(mapper, обязательные = listOf("id", "statement", "quote", "anchor"))
        // Свой id ОБЯЗАТЕЛЕН (истина, `answer_shape`): на него ссылаются цели
        // и сервисы; ответ без id у нужды недействителен.
        поле(узел, "id", строка(mapper, "свой номер нужды вида p1.n2 — на него ссылаются цели и сервисы"))
        поле(узел, "statement", строка(mapper, "чего ЭТОЙ стороне не хватает или что она требует"))
        поле(
            узел, "quote",
