        поле(узел, "designation", строка(mapper, "обозначение как в тексте: «ПП РФ от 22.12.2020 №2216»"))
        поле(узел, "title", строка(mapper, "наименование акта"))
        поле(узел, "edition", строка(mapper, "редакция, если названа"))
        поле(узел, "edition_date", строка(mapper, "дата редакции, если названа"))
        поле(узел, "valid_until", строка(mapper, "срок действия, если назван"))
        return узел
    }

    /** Граница рамки — объектом: что меряем, оператор, значение, единица. */
    private fun граница(mapper: ObjectMapper): ObjectNode {
        val узел = объект(mapper, обязательные = listOf("value", "unit"))
        поле(узел, "key", строка(mapper, "что меряем: mass · power · share · count"))
        поле(узел, "op", перечень(mapper, listOf("le", "ge", "lt", "gt", "eq"), "оператор"))
        поле(узел, "value", строка(mapper, "число"))
        поле(узел, "unit", строка(mapper, "единица"))
