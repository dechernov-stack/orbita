// Линт формулировок: EARS-форма плюс словарь качества П13–П20.
//
// Словарь правил живёт данными (полка `quality_dictionary` в v1) и здесь не
// переписывается: проверяется ФОРМА шаблона EARS, которой у v1 не было.
// Замечания — пометы, а не запрет записи: черновик пишется всегда, а вот
// базирование помет не переживёт.
package orbita.requirements.internal

import orbita.requirements.api.Ears
import orbita.requirements.api.LintNote

object EarsLint {

    /** Слова-«цели», которым не место среди требований (П18). */
    private val словаЦели = listOf("обеспечить", "улучшить", "повысить", "оптимизировать", "минимизировать")

    /** Расплывчатое: измерить нельзя, значит проверить тоже (П19). */
    private val расплывчатое = listOf(
        "по возможности", "при необходимости", "адекватн", "достаточн", "удобн", "быстро", "надёжно",
    )

    // Модальность: «должен · должна · должно · должны». Границу слова (\b)
    // здесь брать нельзя — в Java она считается по ASCII-классу \w, и после
    // кириллической буквы её попросту нет (проверено падением теста).
    private val модальность = Regex("""долж(?:ен|на|но|ны)""")

    /** Форма шаблона: с чего начинается и что обязано присутствовать. */
    private val формы = mapOf(
        Ears.ALWAYS to Regex("""долж(?:ен|на|но|ны)\s+\S+"""),
        Ears.EVENT to Regex("""^\s*Когда\s+.+,\s*.+долж(?:ен|на|но|ны)\s+"""),
        Ears.STATE to Regex("""^\s*Пока\s+.+,\s*.+долж(?:ен|на|но|ны)\s+"""),
        Ears.UNWANTED to Regex("""^\s*Если\s+.+,\s*то\s+.+долж(?:ен|на|но|ны)\s+"""),
        Ears.OPTIONAL to Regex("""^\s*Где\s+предусмотрен.*,\s*.+долж(?:ен|на|но|ны)\s+"""),
    )

    private val подсказки = mapOf(
        Ears.ALWAYS to "‹Носитель› должен ‹действие› ‹объект› [‹показатель›].",
        Ears.EVENT to "Когда ‹событие›, ‹носитель› должен ‹действие› [в течение ‹T›].",
        Ears.STATE to "Пока ‹состояние›, ‹носитель› должен ‹действие›.",
        Ears.UNWANTED to "Если ‹условие›, то ‹носитель› должен ‹парирование›.",
        Ears.OPTIONAL to "Где предусмотрен ‹элемент›, ‹носитель› должен ….",
    )

    fun check(statement: String, ears: Ears): List<LintNote> {
        val замечания = mutableListOf<LintNote>()
        val текст = statement.trim()

        if (текст.isEmpty()) {
            return listOf(LintNote("L-E0", "формулировка пуста", "требование без формулировки нечего проверять"))
        }

        формы[ears]?.let { форма ->
            if (!форма.containsMatchIn(текст)) {
                замечания += LintNote(
                    "L-E1",
                    "формулировка не по шаблону ${ears.name}",
                    "ожидается форма: ${подсказки[ears]}",
                )
            }
        }

        if (!модальность.containsMatchIn(текст)) {
            замечания += LintNote(
                "L-C1", "нет модального «должен»",
                "без модальности это описание, а не требование (П16)",
            )
        }

        // Одна мысль на требование: союз «и» между двумя действиями режет
        // проверяемость — верификация распадётся на два разных события.
        if (Regex("""долж(?:ен|на|но|ны)\s+[^.]*\sи\s+[^.]*""").containsMatchIn(текст)) {
            замечания += LintNote(
                "L-C2", "в одном требовании два действия",
                "разделите: иначе непонятно, что именно не выполнено при отказе (П14)",
            )
        }

        словаЦели.firstOrNull { текст.lowercase().contains(it) }?.let {
            замечания += LintNote(
                "L-C6", "слово цели «$it» в требовании",
                "цель отвечает «зачем», требование — «что система делает» (П18)",
            )
        }

        расплывчатое.firstOrNull { текст.lowercase().contains(it) }?.let {
            замечания += LintNote(
                "L-C5", "расплывчатое «$it»",
                "что нельзя измерить, того нельзя и проверить (П19)",
            )
        }

        if (Regex("""^\s*(Необходимо|Требуется|Предполагается|Планируется)\b""").containsMatchIn(текст)) {
            замечания += LintNote(
                "L-C3", "формулировка начинается не с носителя",
                "пассив прячет того, кто отвечает за выполнение (П13)",
            )
        }

        return замечания
    }
}
