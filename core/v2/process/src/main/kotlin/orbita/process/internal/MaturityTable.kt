// Таблица решений зрелости: код позиции экспертизы → наша проверка.
//
// Полка Романова даёт позициям коды зрелости (С · Р · F · U · Σ · Δ · x · °)
// без легенды; расшифровка в полке помечена «предположительно» и ждёт
// владельца (ЗАДАНИЕ-CODE-БОЛЬШОЕ, шип D п. 4). Таблица — единственное
// место, где код превращается в условие; поменяется легенда — поменяется
// строка здесь, а не десять мест по коду.
//
// Что мы умеем измерить: у документа — начат · полон к ступени ·
// базирован; у записи реестра — есть хотя бы одна. Зрелость реестра к
// точке считать нечем, и таблица этого не выдумывает: для реестра любой
// требующий код сводится к «записи есть», и это сказано словами.
package orbita.process.internal

object MaturityTable {

    /** Коды, которые ТРЕБУЮТ артефакт; x и ° — не требуют. */
    private val требующие = setOf("С", "Р", "F", "U", "Σ", "Δ")

    fun required(code: String): Boolean = code in требующие

    /**
     * Держит ли позиция точку. Только ДОКУМЕНТ: у него есть мера (начат ·
     * полон к ступени · базирован). У записи реестра мера одна — «записи
     * есть», и держать ею ворота значило бы подменять критерии сцен
     * владельца (MCR ждёт сцены 3–8, а не «есть хоть одна цель»): позиция
     * по реестру показывается ✓/☐, но точку не держит.
     */
    fun blocking(code: String, ourRef: String?): Boolean =
        required(code) && ourRef?.startsWith("document_template:") == true

    /**
     * Проверка по коду и ссылке на наш артефакт.
     *
     * @param ourRef `document_template:<код>` либо `kind:<вид>`; null — не сопоставлено
     * @return имя условия для оценщика готовности либо null, если проверять нечего
     */
    fun check(code: String, ourRef: String?, gate: String): String? {
        val ссылка = ourRef?.takeIf { it.isNotBlank() } ?: return null
        if (!required(code)) return null
        val (тип, имя) = ссылка.split(":", limit = 2).let { it[0] to it.getOrElse(1) { "" } }
        if (имя.isBlank()) return null
        return when (тип) {
            "document_template" -> when (code) {
                "С" -> "document_started:$имя"
                "F", "Σ" -> "document_baselined:$имя"
                else -> "document_complete:$имя:$gate"
            }
            "kind" -> "exists:$имя"
            else -> null
        }
    }

    /** Что именно проверяется — словами, чтобы позиция не обещала больше, чем меряет. */
    fun words(code: String, ourRef: String?): String? {
        val ссылка = ourRef?.takeIf { it.isNotBlank() } ?: return "не сопоставлено с нашим артефактом — не проверяется"
        if (!required(code)) return "по необходимости — не держит точку"
        return if (ссылка.startsWith("kind:")) "наличие записей — помета, точку держат критерии сцен"
        else when (code) {
            "С" -> "документ начат"
            "F", "Σ" -> "документ базирован"
            else -> "документ полон к ступени"
        }
    }
}
