// Стадия А разбора: ранг доверия, профиль содержимого и связи фактов
// (план «Знания v2», шаг 7).
//
// Проверяется не «в промпте нашлось слово», а то, ради чего стадию
// перестроили: тип файла режима больше НЕ выбирает — выбирает профиль блоков;
// ранг документа идёт в промпт и победителя не выбирает; связи приходят тем
// же ответом, а связь с типом вне реестра до приёма не доходит и называется
// поимённо. Отдельно стережётся совместимость: на проекте без флага промпт
// остаётся прежним до буквы — иначе журнал перестанет узнавать ответ и
// каждый документ стенда прохода будет оплачен заново.
//
// Правило нужд из промпта разбора живёт в IntakePromptRulesTest и этим
// шагом не трогается.
package orbita.api

import com.fasterxml.jackson.databind.ObjectMapper
import orbita.ai.api.AiFactory
import orbita.ai.api.Answer
import orbita.ai.api.Transport
import orbita.kernel.TestDbV2
import orbita.kernel.api.Area
import orbita.kernel.api.Channel
import orbita.kernel.api.KernelFactory
import orbita.kernel.api.Provenance
import orbita.knowledge.api.FactIntake
import orbita.knowledge.api.Intake
import orbita.knowledge.api.KnowledgeFactory
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class IntakeProfilePromptTest {

    private val mapper = ObjectMapper()
    private val store = KernelFactory.entityStore(TestDbV2.conn, mapper)
    private val links = KernelFactory.linkRegistry(TestDbV2.conn)
    private val знания = KnowledgeFactory.intake(store, links, mapper)

    private var промпт = ""
    private var звонков = 0
    private var ответМодели = ОТВЕТ_ТЗ

    private val транспорт = Transport { текст, _, _ ->
        промпт = текст
        звонков += 1
        Answer(ответМодели, "модель-проверки", 100, 200)
    }
    private val служба = AiFactory.service(store, транспорт, mapper)

    @BeforeTest
    fun чисто() {
        TestDbV2.очистить()
        промпт = ""
        звонков = 0
        ответМодели = ОТВЕТ_ТЗ
    }

    /** Флаг — поле проекта: поле знаний v2 включается проекту, а не стенду. */
    private fun проект(код: String, полеЗнаний: Boolean) {
        store.create(
            код, "project", Area.Project(код), "1",
            mapper.readTree(
                """{"name":"Поле знаний","standard":"NASA-7120","phase":"Pre-Phase A","knowledge_v2":$полеЗнаний}""",
            ),
            Provenance(Channel.MANUAL, "Чернов Д."),
        )
    }

    private fun разобрать(проект: String, материал: String, задание: String = "разбери по сущностям"): FactIntake =
        AiFactory.atomize(store, знания, служба, mapper).atomize(проект, материал, задание, "Иванов И.")

    @Test
    fun `промпт разбора несёт ранг документа, требование профиля и формат связей`() {
        val код = "PJ-9350"
        проект(код, полеЗнаний = true)
        val материал = знания.putMaterial(код, "ТЗ МКУСС", "tor", ТЗ, "Иванов И.", authority = "mandatory")
        разобрать(код, материал)

        listOf(
            "Ранг доверия источника: обязательный",
            "Ранг документа НЕ делает факт верным",
            "## Профиль содержимого (Д2а)",
            "\"profile\": {\"statement\": 0.0, \"params\": 0.0, \"norms\": 0.0, \"assessments\": 0.0}",
            "## Связи между фактами (стадия А)",
            "supports (второй факт",
            "contradicts",
            "refines",
            "same_as",
            "\"links\": [{\"from\": 0, \"to\": 3,",
            "НОМЕРА фактов в массиве",
        ).forEach { assertTrue(it in промпт, "в промпте нет «$it»") }
        // Тип документа как поле ввода запрещён: в описи стоит ранг, не тип.
        assertFalse(", тип: tor" in промпт, "тип входного вернулся в опись документа")
    }

    @Test
    fun `режим требований выбирается профилем блоков, перечень классов ТЗ на месте`() {
        val код = "PJ-9351"
        проект(код, полеЗнаний = true)
        // Задание — общее: про ТЗ в нём ни слова, режим обязан прийти из
        // того, что в документе написано.
        val материал = знания.putMaterial(код, "Задание заказчика", "tor", ТЗ, "Иванов И.", authority = "mandatory")
        разобрать(код, материал)

        assertTrue("## Профиль содержимого документа: постановка · нормы" in промпт, промпт.take(1200))
        assertTrue("применяются К БЛОКУ" in промпт, "режим объявлен блочным")
        assertTrue("## Режим: техническое задание заказчика" in промпт, "норм-содержимое включило режим требований")
        listOf(
            "ПРАВИЛО АТОМИЗАЦИИ (ШИП-G-ПРИНЯТ)",
            "requirement · function · service · composition_node ·\nstakeholder · constraint · milestone · normative_ref",
            "Верни блок \"assessment\" с lines по всем требованиям",
        ).forEach { assertTrue(it in промпт, "режим ТЗ потерял «$it»") }
        // Обязательства ТЗ — не пункты НПА: полка нормативов из задания
        // заказчика не заводится.
        assertFalse("## Режим: нормативный акт" in промпт, "ТЗ разбирается правилом нормативного акта")
    }

    @Test
    fun `нормативный акт называет себя заголовком и получает режим нормы`() {
        val код = "PJ-9356"
        проект(код, полеЗнаний = true)
        val материал = знания.putMaterial(код, "Требования к уводу", "tor", НПА, "Иванов И.", authority = "mandatory")
        разобрать(код, материал)

        assertTrue("## Профиль содержимого документа: нормы" in промпт, промпт.take(1200))
        assertTrue("## Режим: нормативный акт" in промпт, "акт разбирается правилом нормы")
        assertTrue("ПОЛЕМ `limit {key, op, value, unit}`" in промпт, "порог нормы остаётся полем")
        assertFalse("## Режим: техническое задание заказчика" in промпт, "акт разобран как задание заказчика")
    }

    @Test
    fun `тип файла режима не выбирает — его выбирает содержимое`() {
        val код = "PJ-9352"
        проект(код, полеЗнаний = true)
        // Тип тот же самый (tor), а блоки — суждения: режим требований не
        // включается, включается режим оценок. Это и есть закрытая ловушка
        // «тип документа как поле ввода».
        val материал = знания.putMaterial(код, "Анализ идей", "tor", ОЦЕНКИ, "Иванов И.", authority = "reference")
        разобрать(код, материал)

        assertTrue("## Профиль содержимого документа: оценки" in промпт, промпт.take(1200))
        assertTrue("## Режим: оценки и суждения" in промпт, "оценочные блоки включили свой режим")
        assertFalse("## Режим: техническое задание заказчика" in промпт, "режим ТЗ пришёл из типа файла, а не из блоков")
        assertTrue("Ранг доверия источника: справочный" in промпт, "ранг справочного документа в промпте")
    }

    @Test
    fun `связь неизвестного типа до приёма не доходит и названа поимённо`() {
        val код = "PJ-9353"
        проект(код, полеЗнаний = true)
        val материал = знания.putMaterial(код, "ТЗ МКУСС", "tor", ТЗ, "Иванов И.", authority = "mandatory")
        ответМодели = ОТВЕТ_СО_СВЯЗЯМИ
        val перехват = Перехват(знания)
        val итог = AiFactory.atomize(store, перехват, служба, mapper)
            .atomize(код, материал, "разбери по сущностям", "Иванов И.")

        assertFalse("похоже" in перехват.сырой, "брак связи дошёл до приёма фактов")
        assertTrue("supports" in перехват.сырой, "годная связь отброшена вместе с браком")
        assertTrue(
            итог.refused.any { "такого типа связи нет в реестре" in it && "похоже" in it },
            "отказ не назван поимённо: ${итог.refused}",
        )
        assertTrue("связей отклонено 1" in итог.note, итог.note)
        // Один брак модели не уносит разбор документа: факты приняты.
        assertEquals(2, итог.accepted.size, "факты приняты несмотря на брак связи")
    }

    @Test
    fun `на проекте без поля знаний промпт остаётся прежним`() {
        val код = "PJ-9354"
        проект(код, полеЗнаний = false)
        // Ранг материалу всё равно проставится (наследовать фактам надо), но
        // в промпт он не идёт: иначе журнал перестанет узнавать ответ.
        val материал = знания.putMaterial(код, "ТЗ МКУСС", "tor", ТЗ, "Иванов И.")
        ответМодели = ОТВЕТ_СО_СВЯЗЯМИ
        val перехват = Перехват(знания)
        AiFactory.atomize(store, перехват, служба, mapper)
            .atomize(код, материал, "разбери по сущностям", "Иванов И.")

        assertTrue(", тип: tor" in промпт, "прежняя опись документа с типом входного")
        assertTrue("## Режим: техническое задание заказчика" in промпт, "прежний режим по типу входного")
        listOf(
            "Ранг доверия источника",
            "Ранг документа НЕ делает факт верным",
            "## Профиль содержимого",
            "## Связи между фактами",
            "\"links\"",
        ).forEach { assertFalse(it in промпт, "на проекте прохода промпт изменился: «$it»") }
        // И ответ модели на прежнем проекте не переписывается вовсе.
        assertEquals(ОТВЕТ_СО_СВЯЗЯМИ, перехват.сырой, "ответ модели переписан на проекте без флага")
    }

    @Test
    fun `повторный разбор той же версии не звонит и фактов не удваивает`() {
        val код = "PJ-9355"
        проект(код, полеЗнаний = true)
        val материал = знания.putMaterial(код, "ТЗ МКУСС", "tor", ТЗ, "Иванов И.", authority = "mandatory")
        val первый = разобрать(код, материал)
        val второй = разобрать(код, материал)

        assertEquals(1, звонков, "повтор той же версии документа стоил второго живого вызова")
        assertEquals(2, первый.accepted.size)
        assertEquals(0, второй.accepted.size, "факты не заведены заново")
        assertTrue("ответ взят из журнала" in второй.note, второй.note)
        assertEquals(2, знания.facts(код).size, "ключ «якорь|утверждение» удержал повтор")
    }

    /**
     * Приём фактов под наблюдением: тест видит РОВНО тот текст ответа,
     * который дошёл до знаний, — иначе «связь не доходит до приёма» пришлось
     * бы проверять по словам сообщения, а не по делу.
     */
    private class Перехват(private val внутри: Intake) : Intake by внутри {
        var сырой: String = ""

        override fun putFacts(project: String, material: String, raw: String, author: String, intent: String): FactIntake {
            сырой = raw
            return внутри.putFacts(project, material, raw, author, intent)
        }
    }

    companion object {
        /** Норм-содержимое: три блока-обязательства и один постановочный. */
        private val ТЗ = """
            Техническое задание на МКУСС
            2.1 Система должна обеспечивать передачу данных в Арктической зоне.
            2.2 Оператор обязан обеспечить гарантированную доставку сообщений класса B'.
            2.3 Задержка доставки не должна превышать 180 мин.
            Состав группировки
            Группировка разворачивается поэтапно до 2030 года.
        """.trimIndent()

        /** Тот же тип входного (tor), а документ — акт: заголовок называет его сам. */
        private val НПА = """
            Постановление Правительства о требованиях к орбитальной группировке
            1 Оператор обязан обеспечить увод аппарата с орбиты не более чем за 5 лет.
            2 Владелец подлежит обязательной регистрации космического объекта.
            3 Использование частот не допускается без решения ГКРЧ.
        """.trimIndent()

        /** Тот же тип входного, но блоки — суждения: режим обязан стать другим. */
        private val ОЦЕНКИ = """
            Анализ идей построения группировки
            По нашему мнению, целесообразна платформа 12U с обработкой на борту.
            Сравнение вариантов показывает предпочтительность РЧ-межспутниковой связи.
            Оценка стоимости развёртывания дана в приложении.
        """.trimIndent()

        /** Профиль в ответе совпадает с первичной оценкой: режим устойчив, промпт тот же. */
        private const val ПРОФИЛЬ =
            "\"profile\":{\"statement\":0.25,\"params\":0.0,\"norms\":0.75,\"assessments\":0.0}"

        private val ФАКТЫ = """
            "facts":[
              {"kind":"obligation","topic":"передача данных","subject":"ТЗ п. 2.1",
               "predicate":"передача данных в Арктической зоне","value":"требование",
               "source":{"anchor":"s1#1"},"source_mark":"И","confidence":0.9,"entity_class":"requirement"},
              {"kind":"obligation","topic":"передача данных","subject":"ТЗ п. 2.2",
               "predicate":"гарантированная доставка сообщений","value":"требование",
               "source":{"anchor":"s1#2"},"source_mark":"И","confidence":0.9,"entity_class":"requirement"}
            ]
        """.trimIndent()

        private val ОТВЕТ_ТЗ = """{"topics":[{"label":"передача данных"}],$ПРОФИЛЬ,"actions":[],$ФАКТЫ}"""

        /** Ответ со связями: одна годная и одна с выдуманным типом. */
        private val ОТВЕТ_СО_СВЯЗЯМИ = """{"topics":[{"label":"передача данных"}],$ПРОФИЛЬ,
            "links":[{"from":0,"to":1,"type":"supports","rationale":"второй пункт держится на первом"},
                     {"from":0,"to":1,"type":"похоже","rationale":"на глаз похоже"}],
            "actions":[],$ФАКТЫ}"""
    }
}
