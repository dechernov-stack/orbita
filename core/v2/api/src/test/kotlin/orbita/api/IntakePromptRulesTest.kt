// Правило ОБРАЗОВАНИЯ в промпте разбора (остановка ПМИ-6, 14.09).
//
// До 14.09 этот тест держал прежнее правило поставки 12.09: «интерес стороны
// — ЭТО НУЖДА с меткой [П]», «у каждой стороны хотя бы одна нужда». Оно и
// набило «Постановку» мусором: строка РОЛИ стороны стала нуждой
// (ND-0002…ND-0009 из колонки «Интерес»/«Роль»), а нужды придумывались, чтобы
// у каждой стороны была хоть одна. Тест охранял дефект — и переписан под
// истину ОНТОЛОГИЯ-ФОРМИРОВАНИЯ.
//
// Что он держит теперь:
//  · сторона образуется ТОЛЬКО из фактов, названных онтологией
//    (`stakeholder.from_facts` — предикаты роли К ПРОЕКТУ); автор нормативного
//    акта стороной не становится;
//  · текст роли/интереса — ПОЛЕ стороны `interest`, а не утверждение нужды;
//  · нужда рождается из ФАКТА (`need.from_facts`): framing с предикатами
//    нужды либо assessment о стороне с меткой [П]; общая нужда §2.1
//    привязывается к сторонам по субъекту факта;
//  · сторона без нужды — помета к воротам, не отказ (note онтологии): нужду
//    под сторону не придумывают.
//
// Перечни в тест не копируются: предикаты и виды фактов берутся у
// `GeneratedOntology`, значения влияния — у `GeneratedKinds`. Иначе промпт и
// истина разойдутся молча — ровно так, как разошлись к остановке.
//
// Тест смотрит на ПРОМПТ: ворота приёма плана (правило образования, обязательные
// связи, ранг материала) живут в :core:v2:knowledge и стерегутся там.
package orbita.api

import com.fasterxml.jackson.databind.ObjectMapper
import orbita.ai.api.AiFactory
import orbita.ai.api.Answer
import orbita.ai.api.Transport
import orbita.kernel.TestDbV2
import orbita.kernel.api.Area
import orbita.kernel.api.Channel
import orbita.kernel.api.KernelFactory
import orbita.kernel.api.Provenance
import orbita.kernel.schema.GeneratedKinds
import orbita.knowledge.api.KnowledgeFactory
import orbita.knowledge.schema.GeneratedOntology
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class IntakePromptRulesTest {
    private val mapper = ObjectMapper()
    private val store = KernelFactory.entityStore(TestDbV2.conn, mapper)
    private val links = KernelFactory.linkRegistry(TestDbV2.conn)
    private val проект = "PJ-9810"
    private val intake = KnowledgeFactory.intake(store, links, mapper)

    /** Промпт, ушедший в службу, — предмет теста. */
    private var промпт = ""

    @BeforeTest
    fun чисто() {
        TestDbV2.очистить()
        промпт = ""
        // Поле знаний v2 включено: правило образования — его правило, и ранг
        // материала на таком проекте называет человек, а не тип файла.
        store.create(
            проект, "project", Area.Project(проект), "1",
            mapper.readTree(
                """{"name":"Промпт","standard":"NASA-7120","phase":"Pre-Phase A","knowledge_v2":true}""",
            ),
            Provenance(Channel.MANUAL, "Чернов Д."),
        )
        val материал = intake.putMaterial(
            проект, "Записка миссии", "note", ЗАПИСКА, "Иванов И.", authority = "mandatory",
        )
        val служба = AiFactory.service(
            store,
            Transport { текст, _, _ ->
                промпт = текст
                Answer(ПУСТОЙ_ОТВЕТ, "тест", 1, 1)
            },
            mapper,
        )
        // Ответ пуст: что с ним сделает приём фактов — забота другого теста,
        // здесь важен только текст, ушедший в службу.
        runCatching {
            AiFactory.atomize(store, intake, служба, mapper)
                .atomize(проект, материал, "разбери по сущностям", "Иванов И.")
        }
        assertTrue(промпт.isNotBlank(), "промпт не собран: разбор не дошёл до вызова службы")
    }

    @Test
    fun `нужда в промпте рождается из фактов онтологии, а не из строки роли`() {
        val понятие = GeneratedOntology.of("need")
        val блок = блокПлана("need")
        понятие.fromFacts.mapNotNull { it.kind }.forEach { вид ->
            assertTrue(несёт(блок, вид), "правило нужды не называет вид факта «$вид»:\n$блок")
        }
        понятие.fromFacts.flatMap { it.predicateIn }.forEach { предикат ->
            assertTrue(несёт(блок, предикат), "правило нужды не несёт предиката онтологии «$предикат»:\n$блок")
        }
        // Оценка о стороне даёт нужду с меткой [П]: это метка самой нужды, а
        // не документа, и промпт обязан её назвать (need.from_facts, mark: П).
        assertTrue(несёт(блок, "[П]"), "правило нужды не называет метку [П] у нужды из оценки о стороне:\n$блок")
        // Общая нужда §2.1 привязывается ПО СУБЪЕКТУ факта (section_hint
        // онтологии), а не по догадке «кому это могло бы понадобиться».
        assertTrue(несёт(блок, "§2.1"), "правило нужды не называет раздел общих нужд §2.1:\n$блок")
        assertTrue(несёт(блок, "субъект"), "общая нужда привязывается к сторонам не по субъекту:\n$блок")
        // Обязательная связь понятия (must_link owns→stakeholder) названа
        // полем: нужды без стороны не бывает.
        assertTrue(несёт(блок, "owner"), "правило нужды не требует стороны-владельца:\n$блок")
        // И место текста роли/интереса названо здесь же — иначе модель снова
        // положит его в statement.
        assertTrue(несёт(блок, "interest"), "правило нужды не отводит текст интереса в поле стороны:\n$блок")
    }

    @Test
    fun `сторона в промпте образуется из предикатов роли, интерес остаётся её полем`() {
        val понятие = GeneratedOntology.of("stakeholder")
        val блок = блокПлана("stakeholder")
        понятие.fromFacts.mapNotNull { it.kind }.forEach { вид ->
            assertTrue(несёт(блок, вид), "правило стороны не называет вид факта «$вид»:\n$блок")
        }
        понятие.fromFacts.flatMap { it.predicateIn }.forEach { предикат ->
            assertTrue(несёт(блок, предикат), "правило стороны не несёт предиката роли «$предикат»:\n$блок")
        }
        // «Президент РФ» и «Правительство РФ» стали сторонами потому, что
        // подписали Указ 645 и ПП 2216. Подписавший несёт норматив, а не роль.
        assertTrue(
            несёт(блок, "автор") && несёт(блок, "норматив"),
            "правило стороны не отводит автора нормативного акта — он снова станет стороной:\n$блок",
        )
        // Текст роли/интереса из источника — ПОЛЕ стороны.
        assertTrue(несёт(блок, "interest"), "поле `interest` в правиле стороны не названо:\n$блок")
        // Влияние — перечень истины схем, а не выдумка промпта.
        GeneratedKinds.of("stakeholder").enums.getValue("influence").forEach { значение ->
            assertTrue(несёт(блок, значение), "правило влияния не несёт значения истины схем «$значение»:\n$блок")
        }
        // Помета онтологии — её же словами: она снимает соблазн дописать нужду
        // ради полноты сетки.
        val помета = понятие.note
        assertTrue(
            помета != null && несёт(блок, помета),
            "промпт не несёт помету онтологии «$помета»:\n$блок",
        )
    }

    @Test
    fun `прежнее правило «интерес стороны — это нужда» из промпта убрано`() {
        val плоский = сплошняком(промпт)
        listOf("ЭТО НУЖДА", "хотя бы одна нужда", "интерес не превращён в нужду").forEach { дефект ->
            assertFalse(
                плоский.contains(дефект, ignoreCase = true),
                "промпт снова требует превращать интерес стороны в нужду («$дефект») — " +
                    "это и породило ND-0002…ND-0009 из колонки «Интерес»/«Роль»",
            )
        }
    }

    /**
     * Кусок промпта про один вид плана действий, одной строкой.
     *
     * Правило образования обязано стоять У СВОЕГО вида: модель читает строку
     * вида, и правило нужды, положенное к стороне, работать не будет. Переносы
     * строк при сверке схлопываются — иначе тест ловил бы перенос, а не
     * правило.
     */
    private fun блокПлана(вид: String): String {
        val начало = промпт.indexOf("· $вид (")
        assertTrue(начало >= 0, "в «План действий» нет строки вида «$вид»")
        val конец = промпт.indexOf("\n  · ", начало + 1)
        return сплошняком(if (конец < 0) промпт.substring(начало) else промпт.substring(начало, конец))
    }

    /** Есть ли текст в куске промпта: регистр значения не имеет. */
    private fun несёт(блок: String, текст: String): Boolean = блок.contains(текст, ignoreCase = true)

    private fun сплошняком(текст: String): String = текст.replace(Regex("\\s+"), " ")

    private companion object {
        /**
         * Записка: роль и интерес стороны разными полями (§3) и общая нужда
         * отрасли (§2.1) — те два случая, которые правило обязано различать.
         */
        private val ЗАПИСКА = """
            §3 Стороны миссии
            ГКРЧ — роль: регулирует использование частот; интерес: частотные
            присвоения и координация до запуска.
            §2.1 Общие нужды
            Отрасли не хватает связи в «белых пятнах» наземной сети.
        """.trimIndent()

        /** Ответ службы пуст: предмет теста — вопрос, а не ответ. */
        private val ПУСТОЙ_ОТВЕТ: String =
            """{"topics":[],"profile":{"statement":1.0,"params":0.0,"norms":0.0,"assessments":0.0},""" +
                """"actions":[],"facts":[]}"""
    }
}
