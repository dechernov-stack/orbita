// Карта разделов канона: чем раздел является — таблицей, перечнем или прозой.
//
// РЕШЕНИЕ-ЧИТАТЬ-СМЫСЛ (владелец, 15.09): структура раздела читается как
// структура. Карта подаётся в промпт перед текстом, и от неё зависит мера
// владельца: «14 сторон из §3» берутся построчно из таблицы, а не поиском
// слова «является заказчиком» в прозе.
//
// Меряется настоящая записка миссии из поставки, а не выдуманный текст:
// карта обязана работать на том документе, на котором стоит прогон.
package orbita.knowledge

import orbita.knowledge.internal.Canon
import orbita.knowledge.internal.Раздел
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class CanonSectionMapTest {

    private val корень = File(System.getenv("ORBITA_REPO_ROOT") ?: ".")
    private val записка: File = корень.resolve("docs/tz/v2/поставка-09-15/ЗАПИСКА-МИССИИ-IoT.md")

    @Test
    fun `таблица узнаётся таблицей и называет свои колонки`() {
        val карта = Canon.of(
            """
            # Стороны
            | сторона | роль | интерес | масштаб |
            |---|---|---|---|
            | Минтранс России | заказчик | контроль исполнения | 270 653 ТС |
            | АО «ГЛОНАСС» | оператор | интеграция с ГАИС | 13,3 млн ТС |
            """.trimIndent(),
        ).карта()

        val раздел = карта.single { it.title == "Стороны" }
        assertEquals(Раздел.ТАБЛИЦА, раздел.type)
        assertEquals(listOf("сторона", "роль", "интерес", "масштаб"), раздел.columns)
    }

    @Test
    fun `перечень узнаётся перечнем, проза — прозой`() {
        val карта = Canon.of(
            """
            # Нужды
            - непрерывная телеметрия вне зоны покрытия
            - резервный канал в белых пятнах
            - российское хранение данных
            # Постановка задачи
            Система предназначена для передачи коротких сообщений и телеметрии
            в интересах транспортного комплекса страны на всём её протяжении.
            """.trimIndent(),
        ).карта()

        assertEquals(Раздел.ПЕРЕЧЕНЬ, карта.single { it.title == "Нужды" }.type)
        assertEquals(Раздел.ПРОЗА, карта.single { it.title == "Постановка задачи" }.type)
    }

    @Test
    fun `на записке миссии карта находит таблицу сторон`() {
        assertTrue(записка.isFile, "записки нет по пути ${записка.path}")
        val карта = Canon.of(записка.readText()).карта()

        assertTrue(карта.size >= 5, "разделов в записке ${карта.size}")
        val таблицы = карта.filter { it.type == Раздел.ТАБЛИЦА }
        assertTrue(таблицы.isNotEmpty(), "в записке есть хоть одна таблица: ${карта.map { it.title to it.type }}")
        assertTrue(
            таблицы.any { it.columns.size >= 3 },
            "у таблицы названы колонки: ${таблицы.map { it.title to it.columns }}",
        )
        // Якорь раздела — тот же, что у блоков: по нему человек найдёт место
        // глазами, и по нему же проверяется цитата предложения.
        карта.forEach { раздел ->
            assertTrue(раздел.anchor.matches(Regex("^s\\d+$")), "якорь раздела «${раздел.anchor}»")
        }
    }
}

/**
 * Сторож правки канона 15.09: содержание не становится заголовком.
 *
 * Пока становилось, перечень нужд рассыпался на разделы, и якоря указывали
 * на заголовок вместо пункта — человек не находил цитату глазами.
 */
class CanonHeadingTest {

    @Test
    fun `короткий пункт перечня остаётся содержанием, а не заголовком`() {
        val канон = Canon.of(
            """
            # Нужды
            - телеметрия груза
            - резервный канал
            - хранение в России
            """.trimIndent(),
        )

        assertEquals(1, канон.blocks.count { it.kind == "heading" }, "заголовок один: ${канон.blocks}")
        assertEquals(
            listOf("s1#1", "s1#2", "s1#3"),
            канон.blocks.filter { it.kind == "para" }.map { it.anchor },
            "все три пункта — абзацы одного раздела",
        )
    }

    @Test
    fun `строка таблицы остаётся содержанием`() {
        val канон = Canon.of(
            """
            # Стороны
            | сторона | роль |
            |---|---|
            | ГКРЧ | регулятор |
            """.trimIndent(),
        )

        assertEquals(1, канон.blocks.count { it.kind == "heading" })
        assertEquals(3, канон.blocks.count { it.kind == "para" }, "три строки таблицы — три абзаца")
    }
}
