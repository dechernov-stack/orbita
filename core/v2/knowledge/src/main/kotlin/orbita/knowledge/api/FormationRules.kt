// Обязательные связи понятия — ворота 4–5 истины (`formation.gates`).
//
// Правил образования по видам фактов больше нет (ОНТОЛОГИЯ-АУДИТ-И-МОДЕЛЬ,
// часть 7; ЗАДАНИЕ-ШИП-4 §1): понятие узнаётся ключом идентичности и границами,
// а не видом и предикатом факта. Здесь осталось то, что ворота проверяют
// машинно: незакрытые обязательные связи.
//
// ВОРОТАМИ ВИД ФАКТА НЕ СЛУЖИТ. РЕШЕНИЕ-ЧИТАТЬ-СМЫСЛ (владелец, 15.09):
// «предикаты задумывались подсказкой, а записаны воротами» — и очевидное
// отбивалось, потому что факт оказался вида `assessment`, когда правило ждало
// `relation`. Истина теперь говорит прямо: `gates.never` — «судить о виде
// факта · требовать предиката из списка · отбивать содержательное предложение
// по форме»; у каждого понятия стоит `from_facts_note`: «подсказка, откуда
// понятие обычно берётся; ворота на вид факта не ставятся».
//
// Что осталось. Правило по-прежнему умеет сказать, ПОХОЖ ли факт на
// происхождение понятия, — этим печатается промпт и объясняется человеку,
// откуда взялось предложение. Никакой отказ и никакая помета на нём больше не
// строятся: ворота проверяют только машинно проверяемое (`gates.check`) —
// цитату в каноне, якорь, число с единицей, разрешимость ссылок, обязательные
// поля и дубль по ключу идентичности.
package orbita.knowledge.api

import orbita.knowledge.schema.Concept

object FormationRules {

    /**
     * Незакрытые обязательные связи понятия по его полям.
     *
     * Это ВОРОТА 4–5 истины («ссылки разрешаются · обязательные поля
     * заполнены»), и считать их обязан КАЖДЫЙ контур, который делает
     * предложение. Пока читатель документа их не считал, «требуют внимания»
     * оставалось пустым, в пакет уходило всё подряд и двадцать шесть строк
     * из восьмидесяти одной отбивались уже на заведении (216, 16.09).
     */
    fun нехватка(понятие: Concept, содержимое: Map<String, String>): List<String> =
        понятие.mustLink.map { it.trim() }.filter { токен ->
            токен.isNotBlank() && нужна(токен, содержимое) && содержимое[полеСвязи(понятие, токен)].isNullOrBlank()
        }

    /**
     * Условие обязательности («normative_basis if obligation»): связь нужна
     * только такому источнику. Онтология сама сопоставляет источник и тип —
     * «obligation→regulatory».
     */
    private fun нужна(токен: String, содержимое: Map<String, String>): Boolean {
        val условие = токен.substringAfter(" if ", "").trim()
        if (условие.isBlank()) return true
        return содержимое["kind"] == условие || (условие == "obligation" && содержимое["type"] == "regulatory")
    }

    /**
     * Каким полем понятия называется связь. Истина — `fields` того же понятия:
     * онтология сама говорит, что нужда несёт сторону полем `stakeholder`, а
     * цель — нужды полем `needs`.
     */
    fun полеСвязи(понятие: Concept, токен: String): String {
        val голова = токен.substringBefore(" if ").trim()
        if (!голова.contains("→")) return голова
        val связь = голова.substringBefore("→").trim()
        val вид = голова.substringAfter("→").substringBefore(">=").trim()
        return понятие.fields.entries.firstOrNull { it.value.contains(связь) }?.key
            ?: понятие.fields.keys.firstOrNull { it == вид || it == "${вид}s" }
            ?: вид
    }
}
