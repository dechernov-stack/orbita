    /** Действующий устав проекта: роль charter, не заменённый новой версией. */
    fun charter(store: EntityStore, область: Area): Entity? {
        val материалы = store.list(область, "material").filter { it.status != "cancelled" }
        val заменённые = материалы.mapNotNull { it.doc.path("supersedes").asText("").ifBlank { null } }.toSet()
        return материалы.firstOrNull { it.doc.path("role").asText("") == "charter" && it.code !in заменённые }
    }

    /** Границы устава — блоки пункта 2 «чего мы не строим»; пусто — устава нет или границ в нём не найдено. */
    fun boundaries(store: EntityStore, область: Area): List<CharterBoundary> {
        val устав = charter(store, область) ?: return emptyList()
        val пункт = ПУНКТЫ.first { it.n == 2 }
        return Canon.of(устав.doc.path("text").asText("")).blocks
            .filter { it.kind != "heading" && пункт.есть(it.text) }
            .map { CharterBoundary(устав.code, it.anchor, it.text) }
    }
