// Двенадцать пунктов записки миссии (ТРЕБОВАНИЯ-К-ЗАПИСКЕ-МИССИИ) — словами, по
// которым они узнаются в каноне устава. Одно место на карту пробелов (§3) и
// границу устава для применимости (§5): «не наш профиль» опирается на пункт 2
// «чего мы не строим».
package orbita.knowledge.internal

