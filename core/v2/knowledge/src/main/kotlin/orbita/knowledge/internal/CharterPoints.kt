/** Пункт записки: номер · что · сцена · мера · слова, по которым узнаётся. */
internal class ПунктУстава(val n: Int, val what: String, val scene: String, val measure: String, вхождения: List<String>) {
    val слова: List<Regex> = вхождения.map { Regex(it) }
    fun есть(текст: String): Boolean = слова.any { it.containsMatchIn(текст.lowercase()) }
}

/** Граница устава — блок канона пункта «чего мы не строим»: документ · якорь · текст. */
data class CharterBoundary(val material: String, val anchor: String, val text: String)

