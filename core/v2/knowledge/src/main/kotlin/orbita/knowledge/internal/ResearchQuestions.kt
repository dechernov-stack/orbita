// Вопросы исследования полноты: пять классов и ни одним больше.
//
// Классы — ровно ключи `research_task.accepted_summary` истины схем: сторона ·
// программа · норма · применение · аналог. Шестого класса не бывает, и
// придумывать его в коде запрещено: иначе принятое из результата некуда
// разложить, а остатки следующего цикла считать не по чему.
//
// Вопрос — СТРОКА «<класс>: <текст>». Класс в начале строки не украшение: по
// нему задача раскладывает ответ по классам, а инженер видит, чего именно
// спрашивают. Снять вопрос и дописать свой человек может; класс придумать —
// нет.
//
// Вызовов модели здесь нет и быть не может: вопросы собираются из среза поля
// подстановкой, а не сочинением. Мера прямая — журнал ИИ после формулирования
// не прирастает.
package orbita.knowledge.internal

import orbita.kernel.schema.GeneratedKinds
import orbita.knowledge.api.ResearchClass
import orbita.knowledge.api.ResearchTrigger

internal object ResearchQuestions {

    /**
     * Сцены входа — из истины схем (`born_in` вида `research_task`:
     * «3,4,5,7,12,точки»). Второй копии перечня в коде нет: разошлась бы молча.
     */
    val сцены: List<String> = GeneratedKinds.byCode["research_task"]?.bornIn.orEmpty()
        .split(",").map { it.trim() }.filter { it.matches(Regex("\\d+")) }

    /**
     * Ведущий класс сцены: с него начинается перечень вопросов.
     *
     * Сцена задаёт, ЧЕГО в ней не хватает прежде всего (3 — стороны, 4 —
     * повестка, 5 — нормы, 7 — аналоги, 12 — бенчмарки стоимости: аналоги и
     * применение). Спрашиваются при этом ВСЕ пять классов: исследование
     * ходит наружу редко, и уходить за одним классом, чтобы через день
     * уходить за вторым, — трата чужого времени, а не бережливость.
     */
    private val ведущий: Map<String, List<ResearchClass>> = mapOf(
        "3" to listOf(ResearchClass.STAKEHOLDER),
        "4" to listOf(ResearchClass.PROGRAM),
        "5" to listOf(ResearchClass.NORM),
        "7" to listOf(ResearchClass.ANALOG),
        "12" to listOf(ResearchClass.ANALOG, ResearchClass.APPLICATION),
    )

    /**
     * Вопросы для места входа.
     *
     * @param остатки классы, по которым принятого ещё нет. На точке спрашивают
     *   именно их («точка → остатки»): к воротам важно не то, с чего начинали,
     *   а то, что так и осталось незакрытым. Пусто — спрашиваются все пять.
     */
    fun вопросы(trigger: ResearchTrigger, поле: ПолеПроекта, остатки: List<ResearchClass>): List<String> {
        val первые = when (trigger) {
            is ResearchTrigger.Scene -> ведущий[trigger.scene].orEmpty()
            is ResearchTrigger.Gate -> остатки
        }
        val порядок = первые + ResearchClass.entries.filterNot { it in первые }
        return поКлассам(порядок, поле)
    }

    /**
     * Вопросы названных классов — ими идёт следующий цикл: спрашивается ровно
     * то, на что ответа нет, а не весь перечень заново.
     */
    fun поКлассам(классы: List<ResearchClass>, поле: ПолеПроекта): List<String> =
        классы.distinct().map { "${it.word}: ${текст(it, поле)}" }

    /**
     * Класс вопроса: слово до двоеточия. Вопрос без класса не бывает — иначе
     * ответ некуда положить.
     */
    fun класс(вопрос: String): ResearchClass? = ResearchClass.of(вопрос.substringBefore(":", ""))

    /**
     * Вопросы инженера: снятое и дописанное. Проверяется ровно то, без чего
     * ответ не разложить, — класс в начале строки и текст после него.
     */
    fun проверить(questions: List<String>): List<String> {
        val чистые = questions.map { it.trim() }.filter { it.isNotBlank() }
        require(чистые.isNotEmpty()) {
            "вопросов нет: исследование без вопроса — не исследование (истина схем: не менее одного)"
        }
        чистые.forEach { вопрос ->
            val класс = класс(вопрос)
            requireNotNull(класс) {
                "вопрос «${вопрос.take(40)}…» начинается не классом: строка вопроса — " +
                    "«<класс>: <текст>», классы — ${ResearchClass.words()}"
            }
            require(вопрос.substringAfter(":").isNotBlank()) {
                "вопрос класса «${класс.word}» без текста: спрашивать нечего"
            }
        }
        return чистые
    }

    /**
     * Шаблоны вопросов одной строкой — для отпечатка версии промпта.
     *
     * Правка формулировки вопроса обязана менять `prompt_version`: иначе два
     * запуска с разными вопросами назовутся одной версией, и повторить запуск
     * по его записи станет нечем.
     */
    val шаблоны: String = ResearchClass.entries.joinToString("\n") {
        "${it.code}|${текст(it, ПолеПроекта.пустое)}"
    }

    private fun текст(класс: ResearchClass, поле: ПолеПроекта): String = when (класс) {
        ResearchClass.STAKEHOLDER ->
            "Какие органы власти, госкорпорации, институты развития, отраслевые ассоциации и " +
                "операторы заинтересованы в замысле проекта, но не названы среди уже названных " +
                "сторон (${поле.стороны.size})? Для каждой: роль (заказчик · регулятор · оператор · " +
                "потребитель · поставщик · партнёр), интерес одной фразой, масштаб числом с источником."

        ResearchClass.PROGRAM ->
            "Какие действующие национальные и отраслевые программы, стратегии и федеральные проекты " +
                "задают показатели, к которым проект может быть привязан? Для каждой: название и " +
                "реквизит, орган-владелец, целевые показатели с годами, где именно проект — " +
                "инструмент их достижения."

        ResearchClass.NORM ->
            "Какие НПА, стандарты и требования применимы к проекту сверх уже названных " +
                "(${перечень(поле.нормы, "в поле их пока нет")})? Для каждого: реквизит, редакция, " +
                "срок действия, пункт-обязательство."

        ResearchClass.APPLICATION ->
            "Какие объекты и потоки требуют предмета проекта${где(поле)}? Для каждого: объект или " +
                "поток, оценка числа с источником, чем нынешнее решение не устраивает."

        ResearchClass.ANALOG ->
            "Какие российские и зарубежные проекты решают ту же задачу и с какими заявленными " +
                "параметрами? Для каждого: название, кто ведёт, заявленные параметры числом, " +
                "источник и дата."
    }

    /** География замысла, если она названа: «в Арктике и на СМП» — часть вопроса, а не украшение. */
    private fun где(поле: ПолеПроекта): String = поле.где.trim().let { if (it.isBlank()) "" else " $it" }

    private fun перечень(значения: List<String>, пусто: String): String =
        if (значения.isEmpty()) пусто else значения.take(ПРЕДЕЛ_ПЕРЕЧНЯ).joinToString(", ") +
            (if (значения.size > ПРЕДЕЛ_ПЕРЕЧНЯ) " и ещё ${значения.size - ПРЕДЕЛ_ПЕРЕЧНЯ}" else "")

    /** Сколько уже названного перечисляется в вопросе: дальше внешнему контуру читать незачем. */
    private const val ПРЕДЕЛ_ПЕРЕЧНЯ = 12
}
