// Сторож перечислений: значения полей приводятся к кодам истины, чужое —
// названо словами.
//
// Журнал ПМИ-7, З-11: в требованиях записки категория пришла ПО-РУССКИ
// («характеристика», «безопасность»), а у RE-0001 в категорию попало значение
// УРОВНЯ — «проектное». Ни один сторож этого не отбил: перечень был у вида, но
// проверять значения при записи никто не брался.
//
// Истина 19.09 (`enum_labels`) даёт русские значения перечислений — и тем самым
// даёт обратный ход: русское имя узнаётся и кладётся кодом, значение чужого
// поля переносится туда, где оно значит, а неузнанное снимается или отбивается.
// Правила перевода в коде нет: только карта владельца.
package orbita.kernel.schema

import com.fasterxml.jackson.databind.node.ObjectNode

object Enums {

    /** Правка значения: что было, что стало и куда переехало — словами. */
    data class Правка(
        val поле: String,
        val было: String,
        val стало: String?,
        val куда: String?,
        val словами: String,
    )

    /** Русское имя значения поля: экран показывает только его. */
    fun метка(вид: String, поле: String, значение: String): String? =
        GeneratedKinds.enumLabels["$вид.$поле"]?.get(значение)

    /** Код по русскому имени того же поля: «характеристика» → performance. */
    fun код(вид: String, поле: String, значение: String): String? {
        val метки = GeneratedKinds.enumLabels["$вид.$поле"] ?: return null
        val искомое = значение.trim().lowercase()
        return метки.entries.firstOrNull { (_, имя) -> имя.trim().lowercase() == искомое }?.key
    }

    /** Значения поля с метками, если истина их назвала. */
    fun значения(вид: String, поле: String): Map<String, String> =
        GeneratedKinds.enumLabels["$вид.$поле"].orEmpty()

    /**
     * Поля вида, для которых значение — их допустимый код или их русское имя.
     *
     * Ими узнаётся значение, записанное НЕ В ТО ПОЛЕ: «проектное» — уровень, а
     * пришло категорией. Своё поле из перечня исключено вызывающим.
     */
    fun чьёЗначение(вид: String, значение: String): List<String> {
        val спец = GeneratedKinds.byCode[вид] ?: return emptyList()
        val искомое = значение.trim().lowercase()
        return спец.fields.filter { поле ->
            спец.enums[поле]?.any { it.lowercase() == искомое } == true ||
                код(вид, поле, значение) != null
        }
    }

    /**
     * Приводит значения полей записи к кодам истины.
     *
     * Русское имя становится кодом; значение чужого поля переезжает туда, где
     * оно значит, — если то поле пусто; неузнанное значение снимается (поле
     * пустым не навредит: обязательность стоит стадией, а не записью). Всякая
     * правка возвращается словами — приём называет её человеку, тихо ничего не
     * меняется.
     */
    fun нормализовать(вид: String, документ: ObjectNode): List<Правка> {
        val спец = GeneratedKinds.byCode[вид] ?: return emptyList()
        val правки = mutableListOf<Правка>()
        спец.fields.forEach { поле ->
            val перечень = спец.enums[поле]
            val метки = GeneratedKinds.enumLabels["$вид.$поле"]
            if (перечень == null && метки == null) return@forEach
            val узел = документ.path(поле)
            if (!узел.isTextual) return@forEach
            val значение = узел.asText().trim()
            if (значение.isEmpty()) return@forEach
            if (перечень != null && значение in перечень) return@forEach
            if (перечень == null && метки?.containsKey(значение) == true) return@forEach

            val свой = код(вид, поле, значение)
            if (свой != null) {
                документ.put(поле, свой)
                правки += Правка(
                    поле, значение, свой, null,
                    "«${имя(вид, поле)}: $значение» записано кодом истины ($свой)",
                )
                return@forEach
            }

            val чужое = чьёЗначение(вид, значение).filter { it != поле }
            val свободное = чужое.firstOrNull { документ.path(it).let { з -> !з.isTextual || з.asText().isBlank() } }
            if (свободное != null) {
                val код = код(вид, свободное, значение) ?: значение
                документ.put(свободное, код)
                документ.remove(поле)
                правки += Правка(
                    поле, значение, код, свободное,
                    "«$значение» — значение поля «${имя(вид, свободное)}», а стояло в «${имя(вид, поле)}»: " +
                        "перенесено, ${имя(вид, поле).lowercase()} остаётся пустым до своей стадии",
                )
                return@forEach
            }

            документ.remove(поле)
            правки += Правка(
                поле, значение, null, null,
                "«${имя(вид, поле)}: $значение» — не из перечня истины (${перечислить(вид, поле)}): " +
                    "поле снято, заполнит человек на своей стадии",
            )
        }
        return правки
    }

    /**
     * Отказы для РУЧНОЙ правки: человек ввёл значение вне перечня.
     *
     * Здесь чистка не годится — правка пришла с экрана, и молча снятое поле
     * человек прочтёт как «сохранилось». Русское имя значения при этом
     * законно: экран им и показывает.
     *
     * @param только поля ЭТОЙ правки. Прежние значения соседних полей правку не
     *   держат: на стенде у требований уже лежит «категория: проектное» от
     *   старого приёма (журнал ПМИ-7, З-11), и отказ на весь документ запер бы
     *   карточку целиком — а лечит её как раз приведение ниже.
     */
    fun проверить(вид: String, документ: ObjectNode, только: Set<String> = emptySet()): List<String> {
        val спец = GeneratedKinds.byCode[вид] ?: return emptyList()
        return спец.fields.filter { только.isEmpty() || it in только }.mapNotNull { поле ->
            val перечень = спец.enums[поле] ?: return@mapNotNull null
            val узел = документ.path(поле)
            if (!узел.isTextual) return@mapNotNull null
            val значение = узел.asText().trim()
            if (значение.isEmpty() || значение in перечень || код(вид, поле, значение) != null) return@mapNotNull null
            "«${имя(вид, поле)}»: значения «$значение» в перечне истины нет — ${перечислить(вид, поле)}"
        }
    }

    private fun имя(вид: String, поле: String): String =
        GeneratedKinds.byCode[вид]?.labels?.get(поле) ?: поле

    /** Перечень значений словами человека: русские имена, если истина их дала. */
    private fun перечислить(вид: String, поле: String): String {
        val метки = GeneratedKinds.enumLabels["$вид.$поле"]
        val перечень = GeneratedKinds.byCode[вид]?.enums?.get(поле).orEmpty()
        val слова = if (метки != null) перечень.map { метки[it] ?: it } else перечень
        return слова.joinToString(" · ")
    }
}
