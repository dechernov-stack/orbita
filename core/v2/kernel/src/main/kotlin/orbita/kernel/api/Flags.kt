// Флаг поля знаний v2 — признак ПРОЕКТА, а не стенда.
//
// Один стенд держит одновременно проект прохода ПМИ-5 (прежнее поведение:
// ввод сохраняется без сверки, синтеза нет, у материала прежний тип) и новый
// проект, на котором новый порядок проверяется мерой ПМИ-6. Переменной среды
// на двоих не хватает — она одна на процесс, — поэтому флаг живёт полем
// `knowledge_v2` вида project, а переменная среды остаётся только умолчанием
// для ВНОВЬ открываемых проектов.
//
// Читать флаг положено здесь и больше нигде: правило, размазанное по
// маршрутам, через две развилки перестаёт быть правилом (ВНЕШНЕЕ-ИССЛЕДОВАНИЕ:
// «завести в Boundary, а не размазать»). Ядро лежит ниже всех слоёв, поэтому
// одну функцию видят и knowledge, и ai, и documents, и api.
package orbita.kernel.api

/** Поле знаний v2 — синтез постановки, сверка ввода, ранг доверия. */
object KnowledgeFlag {

    /**
     * Переменная среды стенда: умолчание для новых проектов. Имя объявлено
     * здесь, а читает переменную только граница (Boundary) — в маршрутах
     * `System.getenv` не появляется ни разу.
     */
    const val DEFAULT_ENV: String = "ORBITA_KNOWLEDGE_V2_DEFAULT"

    /**
     * Умолчание стенда для новых проектов. Значение подставляет граница при
     * сборке роутера; до зелёной меры ПМИ-6 оно выключено, и новый порядок
     * включается телом запроса на отдельном проекте.
     */
    @Volatile
    var newProjectsDefault: Boolean = false

    /**
     * Умолчание стенда из строки переменной среды. Включает ровно «1»:
     * иначе пустая или забытая переменная («», «false», «off») включила бы
     * новое поведение на стенде владельца молча.
     */
    fun defaultFrom(env: String?): Boolean = env?.trim() == "1"

    /**
     * Включено ли поле знаний v2 на проекте.
     *
     * Отсутствие поля — выключено: на проекте, заведённом до перестройки, ни
     * одна развилка не срабатывает и данные не переписываются. Проекта нет
     * вовсе — тоже выключено: спрашивать о несуществующем проекте некому,
     * а падать на чтении флага нельзя.
     */
    fun on(store: EntityStore, project: String): Boolean {
        val область = Area.Project(project)
        // Паспорт лежит кодом проекта в его же области; запасной путь — первый
        // project области: у проектов, заведённых импортом и примером, код
        // области и код паспорта совпадают не всегда (так же читает обмен).
        val паспорт = store.byCode(область, project)?.takeIf { it.kind == "project" }
            ?: store.list(область, "project").firstOrNull()
            ?: return false
        return паспорт.doc.path("knowledge_v2").asBoolean(false)
    }
}
