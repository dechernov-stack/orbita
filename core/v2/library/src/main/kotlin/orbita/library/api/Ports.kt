// Порты библиотеки (ТЗ-BACKEND §3, слой L0).
//
// Полка — не витрина: с неё берут в проект, и взятое помнит исток. Здесь
// объявлено ровно то, чем пользуются другие модули; наполнение полок идёт
// генератором из поставки внешнего контура, руками — отказ сторожа.
package orbita.library.api

import com.fasterxml.jackson.databind.JsonNode

/** Запись полки: вид, код и документ поставки. */
data class ShelfItem(val kind: String, val code: String, val doc: JsonNode)

/** Что стало с записью при выкладке. */
enum class ShelfState { CREATED, UPDATED, UNCHANGED }

/**
 * Итог выкладки: запись и что с ней стало.
 *
 * Состояние — не украшение отчёта: без него поставщик не отличает повтор
 * от новой заливки и рапортует «залито 12» там, где не переписано ничего.
 * `item.code` может отличаться от запрошенного — если акт уже лежал на
 * полке под своим кодом, выкладка попадает в НЕГО, а не заводит двойника.
 */
data class ShelfWrite(val item: ShelfItem, val state: ShelfState)

interface Shelves {
    /** Все записи полки заданного вида. */
    fun of(kind: String): List<ShelfItem>

    /** Одна запись по коду; null — записи нет, и это состояние, а не сбой. */
    fun item(code: String): ShelfItem?

    /**
     * Запись, узнанная по СОДЕРЖАНИЮ, а не по коду: у норматива это акт с
     * тем же обозначением, как бы его ни процитировали.
     *
     * Нужна тем, кто кладёт на полку своей дорогой и со своим провенансом
     * (принятый факт живого разбора), — чтобы правило «один акт — одна
     * карточка» жило в ОДНОМ месте, а не переписывалось у каждого входа.
     */
    fun matching(kind: String, doc: JsonNode): ShelfItem?

    /**
     * Шаблон фазы по стандарту. Стандарт по умолчанию задаётся проектом:
     * решение владельца от 05.09 — NASA-7120.
     */
    fun phaseTemplate(code: String): JsonNode

    /**
     * Положить запись поставки на полку.
     *
     * Идемпотентно: повторная выкладка того же содержимого версий не плодит.
     * Правка полки руками запрещена сторожем отпечатков — сюда попадает
     * только то, что пришло поставкой внешнего контура.
     *
     * Запись узнаётся кодом, а у видов с естественным ключом — ещё и
     * содержанием: один и тот же акт не лежит на полке дважды.
     */
    fun put(kind: String, code: String, doc: JsonNode, author: String): ShelfWrite
}
