// «Ноль правок молча» — главное свойство верификации (мера ПМИ-6 п. 2.10).
//
// Проверка документа против поля соблазнительна ровно тем, чем опасна:
// расхождение видно, исправление очевидно, «давайте починим сами». Починенный
// молча документ читается как верный — и читателю неоткуда узнать, что он
// однажды разошёлся с основанием и кто-то это сгладил.
//
// Поэтому здесь снимок всей модели до проверки и после: версия документа,
// версии всех сущностей и диспозиции всех фактов. Отличие хоть на единицу —
// провал, каким бы полезным ни было «исправление».
//
// Обвязка (стенд, память сущностей и связей) объявлена в VerificationTest.kt:
// второй копии хранилища в тестах модуля не заводится.
package orbita.documents

import com.fasterxml.jackson.databind.node.ObjectNode
import orbita.documents.api.Issue
import orbita.documents.api.VerificationReport
import orbita.kernel.api.Area
import orbita.kernel.api.Channel
import orbita.kernel.api.Provenance
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertTrue

class VerificationReportTest {

    private val стенд = СтендПоля()
    private val область = Area.Project(СтендПоля.ПРОЕКТ)
    private val автор = "Иванов И."

    /** Поле с расхождениями: иначе «ничего не изменилось» доказывает пустота. */
    private fun расставить() {
        стенд.материал("MM-0001", "Записка о миссии", "mandatory")
        стенд.материал("AN-0002", "Анализ идей", "reference")

        val обязательный = стенд.факт("F-0001", "группировка", "год развёртывания", "2030", material = "MM-0001")
        стенд.факт("F-0009", "группировка", "год развёртывания", "2032", material = "AN-0002")
        стенд.спор("F-0001", "F-0009")
        стенд.факт("F-0007", "сервис", "охват абонентов", "95", единица = "%", material = "AN-0002")

        стенд.основание(стенд.цель("G-0001", "развернуть группировку", 2030), обязательный)
        стенд.цель("G-0002", "обеспечить связность приполярных районов", 2031)

        стенд.документы.ensure(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)
        стенд.документы.addStatement(
            СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, "2",
            "Ожидаемый охват абонентов — 97 %.",
            listOf("Э-ЦЕЛИ"), автор,
        )
    }

    /** Снимок модели: код сущности → версия, статус и диспозиция факта. */
    private fun снимок(): Map<String, Triple<Int, String, String>> = стенд.store.list(область)
        .filterNot { it.kind == "verification_report" }
        .associate {
            it.code to Triple(it.version, it.status, it.doc.path("disposition").asText(""))
        }

    @Test
    fun `проверка не меняет ни документа, ни сущностей, ни диспозиций фактов`() {
        расставить()
        val версияДо = стенд.документы.document(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ).version
        val доПроверки = снимок()

        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)

        assertTrue(отчёт.items.isNotEmpty(), "расхождения были — иначе «ничего не изменилось» ничего не доказывает")
        assertEquals(доПроверки, снимок(), "проверка правит молча: снимок модели изменился")
        assertEquals(
            версияДо, стенд.документы.document(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ).version,
            "версия документа выросла от одной только проверки",
        )
    }

    @Test
    fun `две проверки подряд не трогают модель и заводят два отчёта`() {
        расставить()
        val доПроверки = снимок()

        val первый = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)
        val второй = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)

        assertEquals(доПроверки, снимок(), "вторая проверка правит молча: снимок модели изменился")
        assertTrue(первый.code != второй.code, "каждая проверка — свой отчёт: история расхождения не переписывается")
        assertEquals(
            первый.items.map { it.issue to it.element },
            второй.items.map { it.issue to it.element },
            "поле не менялось — находки обязаны совпасть",
        )
        assertEquals(2, стенд.проверка.reports(СтендПоля.ПРОЕКТ).size)
    }

    @Test
    fun `закрытие отчёта не трогает ни находок, ни модели`() {
        расставить()
        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)
        val послеПроверки = снимок()

        val закрытый = стенд.проверка.close(
            СтендПоля.ПРОЕКТ, отчёт.code, автор, "находки разобраны на внутреннем обзоре",
        )

        assertEquals(VerificationReport.CLOSED, закрытый.status)
        assertEquals(отчёт.items, закрытый.items, "закрытие стёрло находки — след расхождения потерян")
        assertTrue("находки разобраны" in закрытый.summary, "причина закрытия не записана: ${закрытый.summary}")
        assertEquals(послеПроверки, снимок(), "закрытие отчёта изменило модель")
    }

    @Test
    fun `сводка отчёта называет и число мест, и роды находок`() {
        расставить()
        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)

        assertTrue("проверено" in отчёт.summary, "сводка не сказала, сколько проверено: ${отчёт.summary}")
        отчёт.byIssue().forEach { (род, сколько) ->
            assertTrue(
                "${род.word} — $сколько" in отчёт.summary,
                "в сводке нет рода «${род.word}»: ${отчёт.summary}",
            )
        }
    }

    @Test
    fun `отчёт против базовой линии называет её человеческим именем`() {
        расставить()
        val линия = стенд.документы.baseline(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, "внутренний обзор", автор)
        val доПроверки = снимок()

        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор, линия.name)

        assertEquals("внутренний обзор", отчёт.baselineName)
        assertTrue(отчёт.baseline.orEmpty().startsWith("BL-"), "снимок линии не назван кодом: ${отчёт.baseline}")
        assertEquals(доПроверки, снимок(), "проверка против линии правит молча")
    }

    @Test
    fun `опора, изменённая после базирования, показана устаревшей`() {
        расставить()
        val линия = стенд.документы.baseline(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, "внутренний обзор", автор)

        // Правку делает ЧЕЛОВЕК в поле знаний, а не проверка.
        val факт = стенд.store.byCode(область, "F-0001")!!
        стенд.store.update(
            факт.id,
            (факт.doc.deepCopy() as ObjectNode).put("value", "2031"),
            Provenance(Channel.MANUAL, автор),
        )

        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор, линия.name)
        val устарело = отчёт.items.first { it.issue == Issue.STALE }

        assertTrue("F-0001" in устарело.detail, "не названа изменившаяся опора: ${устарело.detail}")
        assertTrue("внутренний обзор" in устарело.detail, "не названа линия: ${устарело.detail}")
    }

    // --- отказные ----------------------------------------------------------

    @Test
    fun `закрытие без причины отказывает`() {
        расставить()
        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)
        assertFailsWith<IllegalArgumentException> {
            стенд.проверка.close(СтендПоля.ПРОЕКТ, отчёт.code, автор, "  ")
        }
        assertEquals(VerificationReport.OPEN, стенд.проверка.report(СтендПоля.ПРОЕКТ, отчёт.code).status)
    }

    @Test
    fun `закрытие без автора отказывает`() {
        расставить()
        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)
        assertFailsWith<IllegalArgumentException> {
            стенд.проверка.close(СтендПоля.ПРОЕКТ, отчёт.code, " ", "разобрано")
        }
    }

    @Test
    fun `закрыть дважды нельзя`() {
        расставить()
        val отчёт = стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)
        стенд.проверка.close(СтендПоля.ПРОЕКТ, отчёт.code, автор, "разобрано на обзоре")
        assertFailsWith<IllegalArgumentException> {
            стенд.проверка.close(СтендПоля.ПРОЕКТ, отчёт.code, автор, "разобрано ещё раз")
        }
    }

    @Test
    fun `закрытие отчёта с чужим кодом отказывает`() {
        assertFailsWith<NoSuchElementException> {
            стенд.проверка.close(СтендПоля.ПРОЕКТ, "VR-9999", автор, "разобрано")
        }
    }

    @Test
    fun `перечень отчётов чужого документа пуст`() {
        расставить()
        стенд.проверка.verify(СтендПоля.ПРОЕКТ, СтендПоля.ОТЧЁТ, автор)
        assertTrue(стенд.проверка.reports(СтендПоля.ПРОЕКТ, СтендПоля.ПУСТОЙ).isEmpty())
    }

    /**
     * Порт проверки не умеет править — уметь нечем. Сторож на будущее: кнопка
     * «исправить всё» начинается с метода, который что-то исправляет.
     */
    @Test
    fun `у порта проверки нет ни одного метода правки документа`() {
        val методы = orbita.documents.api.Verification::class.java.methods.map { it.name }.toSet()
        assertTrue(
            методы.containsAll(setOf("verify", "reports", "report", "close")),
            "порт растерял свои методы: ${методы.sorted()}",
        )
        assertTrue(
            методы.none { имя -> listOf("fix", "repair", "resolve", "rewrite").any { it in имя.lowercase() } },
            "у проверки появился метод правки: ${методы.sorted()}",
        )
    }
}
