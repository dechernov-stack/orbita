// Сторож чисел и квалификаторов (перенос из DocPilot, ОБЗОР-DOCPILOT §1.2).
//
// Тезис — единственный свободный текст документа, и в нём легко появиться
// числу, которого нет ни в одной опоре. Сторож сравнивает числа текста с
// числами опор по НОРМАЛИЗОВАННОМУ виду с единицей: «120 м³/ч» и «120 м3/ч»
// — одно число, «120 м³/ч» и «120 с» — разные.
//
// Исключения не в коде, а перечнем: даты ISO, номера разделов и числа
// внутри кодов сущностей числами документа не являются. Квалификаторы
// («не менее», «только», «кроме») приходят СПИСКОМ ДАННЫМИ из шаблона —
// правило языка меняется без пересборки.
package orbita.documents.internal

internal object NumberGuard {

    private val ЧИСЛО = Regex(
        """(?<![\w-])(?:[≤≥]\s*)?-?\d+(?:[.,]\d+)?(?:\s*(?:[%°]|[%°]?[A-Za-zА-Яа-яЁё³²]+(?:/[A-Za-zА-Яа-яЁё³²]+)*))?""",
    )
    private val КОД = Regex("""\[[A-ZА-Я]{1,12}-\d+]|\b[a-z_]+-[0-9a-f]{6,}\b""")
    private val ДАТА = Regex("""\b\d{4}-\d{2}-\d{2}(?:T\S+)?\b""")
    private val РАЗДЕЛ = Regex("""§\s*\d+(?:\.\d+)*""")

    /**
     * Числа текста в нормализованном виде; служебное отсеяно исключениями.
     *
     * @param единицы токены, которые в этом разделе ДЕЙСТВИТЕЛЬНО служат
     *   единицами. Без них любое русское слово после числа читается как
     *   единица: «Сторона 2 и Сторона 3» давало число «2 и», не совпадавшее
     *   с «2» из той же таблицы, — и сторож отказывал честному тексту
     *   (поймано живой проверкой рендеринга). Своего справочника единиц у
     *   сторожа нет намеренно: единицей считается то, что стоит единицей в
     *   самих сведениях раздела, а не то, что мы про язык предположили.
     */
    fun numbers(text: String, единицы: Set<String> = emptySet()): List<String> {
        val очищенный = РАЗДЕЛ.replace(ДАТА.replace(КОД.replace(text, " "), " "), " ")
        return ЧИСЛО.findAll(очищенный).map { нормализовать(it.value, единицы) }.toList()
    }

    /**
     * Токены, стоящие единицами в этих строках.
     *
     * Единица без пробела («20%», «5°») — всегда единица: слов, слипшихся
     * с числом, в тексте не бывает. Единица через пробел признаётся такой
     * же, как встреченная слитно, либо любой односимвольный/дробный
     * токен — «м3/ч», «км».
     */
    fun unitsOf(строки: List<String>): Set<String> {
        val найдено = mutableSetOf<String>()
        строки.forEach { строка ->
            val очищенный = РАЗДЕЛ.replace(ДАТА.replace(КОД.replace(строка, " "), " "), " ")
            ЧИСЛО.findAll(очищенный).forEach { м ->
                val хвост = ЕДИНИЦА.find(м.value) ?: return@forEach
                val слитно = !хвост.value.startsWith(" ")
                val токен = хвост.value.trim().lowercase().replace("³", "3").replace("²", "2")
                if (токен.isBlank()) return@forEach
                // Слитная единица и дробная («м3/ч») — единицы без сомнений;
                // отдельное слово через пробел признаётся, только если оно
                // же встретилось слитно где-то ещё либо содержит косую.
                if (слитно || токен in ЗНАКИ || "/" in токен) найдено += токен
            }
        }
        return найдено
    }

    /**
     * Квалификаторы текста по списку из шаблона. Найденное возвращается в
     * нижнем регистре: рецензия сравнивает наборы, а не написание.
     *
     * Совпадение — ПО СЛОВУ, а не по подстроке. Подстрочное сравнение
     * находило «не» внутри «нештатной» и «менее» внутри «уменьшение», и
     * живой рендер отклонялся за квалификатор, которого в тексте нет
     * (поймано днём живой модели на ConOps §5).
     */
    fun qualifiers(text: String, словарь: List<String>): List<String> {
        val низ = text.lowercase().replace("ё", "е")
        return словарь
            .filter { слово -> целымСловом(низ, слово.lowercase().replace("ё", "е")) }
            .map { it.lowercase() }
            .sorted()
    }

    /** Есть ли оборот в тексте целыми словами: «не» ≠ часть «нештатной». */
    private fun целымСловом(текст: String, оборот: String): Boolean =
        Regex("(?<![\\p{L}\\p{N}])" + Regex.escape(оборот) + "(?![\\p{L}\\p{N}])")
            .containsMatchIn(текст)

    /** Числа текста, которых нет ни в одной опоре. Пусто — тезис чист. */
    fun unsupported(text: String, опоры: List<String>): List<String> {
        // Единицы берутся из ОПОР: они и есть словарь единиц этого раздела.
        val единицы = unitsOf(опоры)
        val вОпорах = опоры.flatMap { numbers(it, единицы) }.toSet()
        return numbers(text, единицы).filterNot { it in вОпорах }.distinct()
    }

    /** Единицы-знаки: словом языка не бывают, признаются без оговорок. */
    private val ЗНАКИ = setOf("%", "°")

    /** Хвост токена после числа: возможный пробел и сама единица. */
    private val ЕДИНИЦА = Regex(
        """(?<=\d)\s?(?:[%°]|[A-Za-zА-Яа-яЁё³²]+(?:/[A-Za-zА-Яа-яЁё³²]+)*)$""",
    )

    private fun нормализовать(токен: String, единицы: Set<String> = emptySet()): String {
        val м = Regex("""-?\d+(?:[.,]\d+)?""").find(токен) ?: return токен
        val сырое = м.value.replace(",", ".").removePrefix("+")
        val число = сырое.toDoubleOrNull()?.let { d ->
            if (d == Math.floor(d) && !d.isInfinite()) d.toLong().toString() else d.toString()
        } ?: сырое
        val оператор = when {
            "≤" in токен.take(м.range.first) -> "≤"
            "≥" in токен.take(м.range.first) -> "≥"
            else -> ""
        }
        val хвост = токен.substring(м.range.last + 1)
        val слитно = хвост.isNotEmpty() && !хвост.startsWith(" ")
        val единица = хвост.trim().lowercase().replace("³", "3").replace("²", "2")
        // Слово после числа считается единицей, только если оно единица в
        // этом разделе: иначе «2 и» и «2» — разные числа, и сторож врёт.
        // Знаки процента и градуса — единицы всегда: русским словом они не
        // бывают, и пробел перед ними ничего не меняет.
        val признана = единица.isNotBlank() &&
            (слитно || единица in ЗНАКИ || "/" in единица || единица in единицы)
        return оператор + if (!признана) число else "$число $единица"
    }
}
