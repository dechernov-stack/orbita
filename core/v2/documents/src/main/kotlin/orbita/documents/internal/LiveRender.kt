// «Написать связно»: раздел прозой из его же элементов.
//
// Главная гипотеза документов — «модель делает читаемый документ из
// элементов» — до сих пор не проверялась: рендер был stub-склейкой, и вся
// защита (сторож чисел, квалификаторы, патчи) стерегла текст, который
// заведомо не нарушал правил (ОБЗОР-DOCPILOT §Противоречие 1).
//
// Здесь модель получает ТОЛЬКО элементы раздела и правило: излагать, не
// добавляя. Проверка атомарна — раздел принимается целиком либо не
// принимается вовсе: полупринятый текст хуже отсутствующего, потому что в
// нём не видно, где враньё.
package orbita.documents.internal

import orbita.documents.api.ElementKind
import orbita.documents.api.SectionView

internal object LiveRender {

    /**
     * Промпт: элементы раздела и правила честности — больше ничего.
     *
     * @param обороты квалификаторы, найденные в сведениях раздела. Их
     *   список даётся модели ЯВНО: без него живая модель пересказывала
     *   «без внешней зависимости» как «исключает зависимость» — смысл тот
     *   же, набор оборотов другой, и сторож отказывал честному тексту.
     */
    fun prompt(
        документ: String,
        раздел: SectionView,
        элементы: String,
        обороты: List<String> = emptyList(),
    ): String = """
Ты пишешь раздел инженерного документа «$документ» связным текстом.

## Раздел ${раздел.no} «${раздел.title}»

Сведения раздела — ниже. Другого источника у тебя нет.

$элементы

## Правила — нарушение делает текст непригодным

1. НЕ ДОБАВЛЯЙ ЧИСЕЛ. Любое число в твоём тексте обязано стоять в
   сведениях выше. Нельзя округлять, пересчитывать в другие единицы,
   складывать и выводить новые величины: «78 кг и 12 кг» не превращаются
   в «90 кг».
2. СОХРАНИ ЭТИ ОБОРОТЫ ДОСЛОВНО: ${обороты.joinToString(", ") { "«$it»" }.ifBlank { "(в сведениях их нет)" }}.
   Они несут смысл, а не стиль: «не менее 20 минут» — это нижняя граница,
   и пересказ «20 минут» или «исключает» её теряет. Переписывать их
   синонимами нельзя даже там, где смысл кажется тем же.
3. Не выдумывай сведений, которых нет: ни причин, ни последствий, ни
   оценок. Если раздел скуден — пиши коротко, это честный ответ.
4. Пиши по-русски, деловой прозой, без списков и заголовков. Три-семь
   предложений. Не пересказывай таблицу построчно — свяжи её в текст.
5. Не ссылайся на «таблицу выше» и на коды элементов: читатель видит
   документ, а не наши сведения.

Верни ТОЛЬКО текст раздела, без пояснений и без разметки.
""".trimIndent()

    /** Сведения раздела для промпта: строки таблиц и тезисы человека. */
    fun facts(раздел: SectionView): String {
        val куски = mutableListOf<String>()
        раздел.elements.forEach { элемент ->
            when (элемент.kind) {
                ElementKind.STATEMENT -> элемент.text?.let { куски += "· $it" }
                ElementKind.QUERY -> {
                    if (элемент.rows.isEmpty()) return@forEach
                    куски += "### ${элемент.title}"
                    элемент.rows.forEach { строка ->
                        куски += "· " + элемент.columns.mapIndexed { i, колонка ->
                            "${колонка.title}: ${строка.getOrNull(i).orEmpty().ifBlank { "—" }}"
                        }.joinToString("; ")
                    }
                }
                else -> Unit
            }
        }
        return куски.joinToString("\n").ifBlank { "(сведений в разделе нет)" }
    }

    /**
     * Проверка написанного. Пусто — текст принят.
     *
     * Сравнение идёт со ВСЕМИ значениями раздела: числа в ячейках таблиц и
     * в тезисах человека — законный источник, всё остальное — выдумка.
     */
    fun refusals(текст: String, раздел: SectionView, квалификаторы: List<String>): List<String> =
        проверка(текст, раздел, квалификаторы).first

    /** Пометы: сказано, но не отклонено. */
    fun notes(текст: String, раздел: SectionView, квалификаторы: List<String>): List<String> =
        проверка(текст, раздел, квалификаторы).second

    /**
     * Проверка написанного: отказы и пометы.
     *
     * Отказы и пометы разведены НЕСИММЕТРИЧНО, и это решение, а не
     * недосмотр. Пропавший квалификатор ослабляет утверждение: «не менее
     * 20 минут» превращается в «20 минут», и это отказ. Появившийся —
     * почти всегда связка речи: живая модель написала «без иных вариантов»
     * и «нештатная ситуация», и отказывать за это значит требовать от
     * прозы канцелярита. Поэтому добавленный квалификатор называется
     * пометой: человек видит его и решает сам.
     */
    private fun проверка(
        текст: String,
        раздел: SectionView,
        квалификаторы: List<String>,
    ): Pair<List<String>, List<String>> {
        val опоры = раздел.elements.flatMap { элемент ->
            элемент.rows.flatten() + listOfNotNull(элемент.text)
        }
        val отказы = mutableListOf<String>()
        val пометы = mutableListOf<String>()

        val лишние = NumberGuard.unsupported(текст, опоры)
        if (лишние.isNotEmpty()) {
            отказы += "числа, которых нет ни в одном элементе раздела: " +
                лишние.joinToString(", ") + " — документ не место, где числа появляются"
        }

        // Квалификатор меняет СМЫСЛ, а не изложение: пропажа «не менее»
        // превращает нижнюю границу в точное значение.
        val вОпорах = NumberGuard.qualifiers(опоры.joinToString(" "), квалификаторы).toSet()
        val вТексте = NumberGuard.qualifiers(текст, квалификаторы).toSet()
        val пропали = вОпорах - вТексте
        val появились = вТексте - вОпорах
        if (пропали.isNotEmpty()) {
            отказы += "пропали квалификаторы: " + пропали.sorted().joinToString(", ") +
                " — без них смысл меняется"
        }
        if (появились.isNotEmpty()) {
            пометы += "в тексте появились обороты, которых нет в сведениях: " +
                появились.sorted().joinToString(", ") + " — проверьте, что смысл не усилен"
        }
        if (текст.isBlank()) отказы += "модель вернула пустой текст"
        return отказы to пометы
    }
}
